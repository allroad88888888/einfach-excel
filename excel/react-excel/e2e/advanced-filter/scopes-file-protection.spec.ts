import { readFile } from 'node:fs/promises'
import { expect, test } from '@playwright/test'
import { summary, alternatives, apply, records, button, minimum, menu, select, open, field, cell } from './support'
import { openProtection, protect, closeProtection } from '../protection/support'

test('grouped ordinary filter and two tables keep independent visibility and totals', async ({ page }) => {
  await summary(page); await alternatives(page); await field(page, 2, 'Missing'); await apply(page)
  await records(page, ['W20', 'W10'])
  await select(page, 'A80', '79:0'); await menu(page).selectOption('open')
  const table = page.getByRole('dialog', { name: 'DemoTable filter conditions', exact: true })
  await table.getByLabel('Filter column 1', { exact: true }).selectOption('0')
  await table.getByLabel('Filter condition 1', { exact: true }).selectOption('equals')
  await table.getByLabel('Filter value 1', { exact: true }).fill('Keyboard')
  await button(page, 'Add OR group').click()
  await table.getByLabel('Filter value 2', { exact: true }).fill('Mouse')
  await button(page, 'Apply filter').click(); await expect(table).toHaveCount(0)
  await expect(cell(page, 80, 0)).toHaveText('Keyboard')
  await expect(cell(page, 81, 0)).toHaveText('Mouse')
  await expect(cell(page, 82, 0)).toHaveCount(0)
  await expect(cell(page, 83, 1)).toHaveText('30')
  await expect(cell(page, 84, 1)).toHaveText('ALPHA')
  await select(page, 'A46', '45:0')
  await expect(button(page, 'Filter CalculatedOrders column A')).toHaveAttribute('data-filtered', 'true')
  await select(page, 'A25', '24:0'); await records(page, ['W20', 'W10'])
  await select(page, 'A80', '79:0'); await menu(page).selectOption('clear')
  await expect(cell(page, 82, 0)).toBeVisible()
  await expect(cell(page, 83, 1)).toHaveText('60')
  await select(page, 'A25', '24:0'); await records(page, ['W20', 'W10'])
})

test('download and actual file reopen preserve grouped rules and the stored snapshot', async ({ page }) => {
  await summary(page); await alternatives(page)
  await button(page, 'Add condition').click(); await minimum(page, 3, '15')
  await apply(page); await records(page, ['W20', 'E10', 'E30'])
  await button(page, 'File').click()
  const downloading = page.waitForEvent('download')
  await button(page, 'Download workbook').click()
  const downloaded = await downloading
  const text = await readFile((await downloaded.path())!, 'utf8')
  const file = JSON.parse(text)
  const filter = file.workbook.filters.find((entry: { sheet: number }) => entry.sheet === 1)
  expect(filter.rules).toEqual([]); expect(filter.groups).toHaveLength(2)
  await button(page, 'Close').click()
  await menu(page).selectOption('clear'); await records(page, ['W20', 'E10', 'W10', 'E30'])
  await button(page, 'File').click()
  page.once('dialog', (prompt) => prompt.accept())
  await page.getByLabel('Open workbook', { exact: true }).setInputFiles({
    name: 'Grouped.einfach.json', mimeType: 'application/json', buffer: Buffer.from(text),
  })
  await expect(page.getByRole('dialog', { name: 'Workbook files' })).toHaveCount(0)
  await page.getByRole('tab', { name: 'Summary', exact: true }).click()
  await select(page, 'A25', '24:0'); await records(page, ['W20', 'E10', 'E30'])
  await expect(cell(page, 9, 0)).toHaveCount(0)
  await expect(button(page, 'Undo')).toBeDisabled()
  await open(page)
  await expect(page.getByRole('group', { name: 'Filter group 2' })).toBeVisible()
  await expect(page.getByLabel('Minimum 2', { exact: true })).toHaveValue('15')
})

test('protected grouped apply keeps the editable draft and redo usable after correction', async ({ page }) => {
  await summary(page); await alternatives(page); await field(page, 2, 'Missing'); await apply(page)
  await select(page, 'A30', '29:0')
  const input = page.getByRole('textbox', { name: 'Active cell value' })
  await input.fill('Keep redo'); await input.press('Enter'); await button(page, 'Undo').click()
  await openProtection(page); await protect(page); await closeProtection(page)
  await select(page, 'A25', '24:0'); await open(page); await field(page, 2, 'East')
  await button(page, 'Apply filter').click()
  await expect(page.getByRole('dialog', { name: 'Filter conditions' }).getByRole('alert')).toContainText('Unprotect')
  await expect(page.getByLabel('Filter value 2', { exact: true })).toHaveValue('East')
  await button(page, 'Cancel').click(); await records(page, ['W20', 'W10'])
  await expect(button(page, 'Redo')).toBeEnabled()
  await openProtection(page); await button(page, 'Unprotect worksheet').click(); await closeProtection(page)
  await button(page, 'Redo').click(); await select(page, 'A30', '29:0')
  await expect(cell(page, 29, 0)).toHaveText('Keep redo')
  await select(page, 'A25', '24:0'); await open(page); await field(page, 2, 'East'); await apply(page)
  await records(page, ['W20', 'E10', 'W10', 'E30'])
})
