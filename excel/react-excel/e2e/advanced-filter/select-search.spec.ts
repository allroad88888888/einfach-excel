import { test, expect } from '@playwright/test'
import { orders, search, button, choice, valuesPage, apply, cell, select } from './support'

for (const width of [1280, 390]) test(`advanced filter Select all search matches includes off-page values at ${width}px`, async ({ page }) => {
  await page.setViewportSize({ width, height: 850 })
  await orders(page); await search(page, 'SO-10')
  await expect(valuesPage(page)).toHaveText('1–50 of 998')
  await button(page, 'Select all search matches').click()
  await expect(page.getByLabel('Selected filter values')).toHaveText('998 selected')
  await button(page, 'Next filter values page').click()
  await expect(choice(page, 'SO-10052')).toBeChecked()
  await search(page, 'SO-10999')
  await expect(choice(page, 'SO-10999')).toBeChecked()
  await expect(page.getByLabel('Selected filter values')).toHaveText('998 selected')
  await expect(cell(page, 2, 0)).toHaveText('SO-10002')
  await apply(page)
  await select(page, 'A1000', '999:0')
  await expect(cell(page, 999, 0)).toHaveText('SO-10999')
  await expect(cell(page, 1000, 0)).toHaveCount(0)
  await button(page, 'Undo').click()
  await select(page, 'A1001', '1000:0')
  await expect(cell(page, 1000, 0)).toHaveText('SO-11000')
  await button(page, 'Redo').click()
  await expect(cell(page, 1000, 0)).toHaveCount(0)
})

test('complete search selection over budget preserves the draft and accepts a narrower query', async ({ page }) => {
  await orders(page)
  await button(page, 'Hide values for condition 1').click()
  await page.getByLabel('Filter condition 1', { exact: true }).selectOption('list')
  await page.getByLabel('Filter value 1', { exact: true }).fill('Saved extra value')
  await button(page, 'Choose values for condition 1').click()
  await button(page, 'Select all search matches').click()
  await expect(page.getByRole('dialog').getByRole('alert')).toContainText('1,000-value')
  await expect(page.getByLabel('Selected filter values')).toHaveText('1 selected')
  await expect(choice(page, 'SO-10001')).not.toBeChecked()
  await expect(cell(page, 2, 0)).toHaveText('SO-10002')
  await search(page, 'SO-11000'); await button(page, 'Select all search matches').click()
  await expect(page.getByLabel('Selected filter values')).toHaveText('2 selected')
  await apply(page)
  await expect(cell(page, 1000, 0)).toHaveText('SO-11000')
  await expect(cell(page, 1, 0)).toHaveCount(0)
})
