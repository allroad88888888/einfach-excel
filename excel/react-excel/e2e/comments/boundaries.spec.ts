import { expect, test } from '@playwright/test'
import { select } from '../support/clipboard'
import { button, cell, marker, editor, timeline, author, body, openComments, createComment, closeComments, expectNeighbors } from './fixtures'

for (const width of [1280, 390]) test.describe(`${width}px comment boundaries`, () => {
  test.use({ viewport: { width, height: 850 } })
  test.beforeEach(async ({ page }) => {
    await page.goto('/e2e/fixtures/plain-sales-orders/')
    await expect(cell(page, '1:0')).toHaveText('SO-10001')
  })

  for (const [operation, moved] of [
    ['insert-rows', '2:0'], ['delete-rows', null], ['insert-columns', '1:1'], ['delete-columns', null],
  ] as const) test(`native ${operation} carries comment history at ${width}px`, async ({ page }) => {
    await createComment(page)
    await page.getByRole('combobox', { name: 'Insert or delete rows and columns' }).selectOption(operation)
    await expect(marker(page, '1:0')).toHaveCount(0)
    if (moved) await expect(marker(page, moved)).toHaveCount(1)
    await button(page, 'Undo').click(); await expect(marker(page, '1:0')).toHaveCount(1)
    await select(page, 'A2', '1:0'); await openComments(page)
    await expect(timeline(page)).toContainText('First line\n第二行🙂')
    await closeComments(page); await expectNeighbors(page)
  })

  test(`ordinary input preserves independent comment metadata at ${width}px`, async ({ page }) => {
    await createComment(page)
    const input = page.getByRole('textbox', { name: 'Active cell value' })
    await input.fill('Updated order'); await input.press('Enter')
    await expect(cell(page, '1:0')).toHaveText('Updated order'); await expect(marker(page, '1:0')).toHaveCount(1)
    await button(page, 'Undo').click(); await expect(cell(page, '1:0')).toHaveText('SO-10001')
    await select(page, 'A2', '1:0'); await openComments(page)
    await expect(timeline(page)).toContainText('First line\n第二行🙂')
    await closeComments(page); await expectNeighbors(page)
  })

  test(`sheet switching keeps discussions attached to the correct native sheet at ${width}px`, async ({ page }) => {
    await createComment(page)
    await page.getByRole('tab', { name: 'Summary', exact: true }).click()
    await select(page, 'A2', '1:0'); await openComments(page)
    await expect(body(page, false)).toBeEnabled()
    await closeComments(page); await createComment(page, 'A2', '1:0', 'Summary only')
    await page.getByRole('tab', { name: 'Sales Orders', exact: true }).click()
    await select(page, 'A2', '1:0'); await openComments(page)
    await expect(timeline(page)).toContainText('First line\n第二行🙂')
    await expect(timeline(page)).not.toContainText('Summary only')
    await closeComments(page); await expectNeighbors(page)
  })

  test(`blank and formula cells retain comment markers without replacing content at ${width}px`, async ({ page }) => {
    await createComment(page, 'G2', '1:6', 'Formula discussion')
    await expect(page.getByRole('textbox', { name: 'Active cell value' })).toHaveValue('=E2*F2')
    await expect(cell(page, '1:6')).toHaveText('79')
    // K3原本是日期；空白场景通过真实清空命令准备，不能把有值格当空白格。
    await select(page, 'K3', '2:10')
    await expect(cell(page, '2:10')).toHaveText('2026-09-04')
    await button(page, 'Clear contents').click()
    await expect(cell(page, '2:10')).toHaveText('')
    await expect(page.locator('[data-workbook-grid]')).toHaveAttribute('data-projection-retained', 'false')
    await expect(button(page, 'Clear contents')).toBeEnabled()
    await createComment(page, 'K3', '2:10', 'Blank discussion')
    await expect(cell(page, '2:10')).toHaveText('')
    await openComments(page); await expect(timeline(page)).toContainText('Blank discussion')
    await closeComments(page); await button(page, 'Undo').click()
    await expect(marker(page, '2:10')).toHaveCount(0)
    await expect(cell(page, '2:10')).toHaveText('')
    // 撤销线程不撤销清空；再撤销准备命令才恢复原日期。
    await button(page, 'Undo').click()
    await expect(cell(page, '2:10')).toHaveText('2026-09-04')
    await select(page, 'G2', '1:6'); await expect(marker(page, '1:6')).toHaveCount(1)
    await expect(page.getByRole('textbox', { name: 'Active cell value' })).toHaveValue('=E2*F2')
    await expect(cell(page, '1:6')).toHaveText('79')
    await select(page, 'A2', '1:0'); await expectNeighbors(page)
  })

  test(`merged anchor displays one comment marker and retains the thread at ${width}px`, async ({ page }) => {
    await createComment(page, 'K3', '2:10', 'Merged discussion')
    await expect(cell(page, '2:10')).toHaveText('2026-09-04')
    await select(page, 'L3', '2:11'); await expect(cell(page, '2:11')).toHaveText('Express')
    await select(page, 'K3:L3', '2:10')
    await page.getByRole('combobox', { name: 'Merge cells', exact: true }).selectOption('merge')
    const confirmation = page.getByRole('alertdialog', { name: 'Merge these cells?', exact: true })
    await expect(confirmation).toBeVisible()
    await confirmation.getByRole('button', { name: 'Merge cells', exact: true }).click()
    await expect(confirmation).toHaveCount(0)
    const merged = page.locator('[data-merged-cell="true"][data-cell="2:10"]')
    await expect(merged).toBeVisible()
    await expect(merged).toHaveText('2026-09-04')
    await expect(merged.locator('[data-cell-comment]')).toHaveCount(1)
    await expect(marker(page, '2:10')).toHaveCount(0)
    await expect(cell(page, '2:11')).toHaveText('')
    await openComments(page); await expect(timeline(page)).toContainText('Merged discussion')
    await closeComments(page); await button(page, 'Undo').click()
    await expect(merged).toHaveCount(0)
    await expect(cell(page, '2:10')).toHaveText('2026-09-04')
    await expect(cell(page, '2:11')).toHaveText('Express')
    await expect(marker(page, '2:10')).toHaveCount(1)
    await select(page, 'K3', '2:10'); await openComments(page)
    await expect(timeline(page)).toContainText('Merged discussion')
    await closeComments(page); await select(page, 'A2', '1:0'); await expectNeighbors(page)
  })

  test(`frozen pane retains the comment marker while scrolling at ${width}px`, async ({ page }) => {
    await createComment(page, 'A1', '0:0', 'Frozen discussion')
    await page.getByRole('combobox', { name: 'Freeze panes', exact: true }).selectOption('first-row')
    await select(page, 'A50', '49:0')
    const frozen = page.locator('[data-frozen-pane="top"] td[data-cell="0:0"]')
    await expect(frozen.locator('[data-cell-comment]')).toHaveCount(1)
    const name = page.getByRole('textbox', { name: 'Name box' })
    await name.fill('A1'); await name.press('Enter'); await openComments(page)
    await expect(timeline(page)).toContainText('Frozen discussion')
    await closeComments(page); await button(page, 'Undo').click()
    await select(page, 'A2', '1:0'); await expectNeighbors(page)
  })

  test(`protected cells reject comments while an editable range accepts them at ${width}px`, async ({ page }) => {
    await select(page, 'G2', '1:6'); await button(page, 'Worksheet protection').click()
    await button(page, 'Allow editing in selection G2').click()
    await expect(button(page, 'Remove editable range G2')).toBeVisible()
    await button(page, 'Protect worksheet').click()
    await expect(button(page, 'Unprotect worksheet')).toBeEnabled(); await button(page, 'Close').click()
    await select(page, 'A2', '1:0'); await openComments(page)
    await author(page).fill('Alice'); await body(page, false).fill('locked draft')
    await button(page, 'New comment').click()
    await expect(editor(page).getByRole('alert')).toContainText('locked')
    await closeComments(page); await expect(marker(page, '1:0')).toHaveCount(0)
    await expect(button(page, 'Undo')).toBeDisabled()
    await createComment(page, 'G2', '1:6', 'Allowed discussion')
    await expect(page.getByRole('textbox', { name: 'Active cell value' })).toHaveValue('=E2*F2')
    await expectNeighbors(page)
  })
})
