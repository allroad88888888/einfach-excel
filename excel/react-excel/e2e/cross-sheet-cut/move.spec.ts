import { expect, test } from '@playwright/test'
import { button, cell, copy, formula, paste, select, sheet, start } from './support'

test.beforeEach(async ({ page, context }) => {
  await context.grantPermissions(['clipboard-read', 'clipboard-write'])
  await start(page)
})

test('XSCUT-01 keyboard cut across tabs retargets mixed references in three sheets with one undo', async ({ page }) => {
  await select(page, 'A1:B1', '0:0')
  await page.locator('[data-workbook-grid]').press('ControlOrMeta+x')
  await expect(page.getByLabel('Clipboard status')).toContainText('ready to move')
  await expect(cell(page, '0:0')).toHaveText('4')
  await expect(cell(page, '0:1')).toHaveText('19')
  await sheet(page, "Target O'Brien")
  await select(page, 'C4', '3:2')
  await page.locator('[data-workbook-grid]').press('ControlOrMeta+v')
  await expect(page.getByLabel('Clipboard status')).toHaveText('Pasted cells.')
  await expect(cell(page, '3:2')).toHaveText('4')
  await expect(cell(page, '3:3')).toHaveText('19')
  await select(page, 'D4', '3:3')
  await expect(formula(page)).toHaveValue("=((((C4+$C$4)+$C4)+C$4)+'Cut Source'!F1)")
  await select(page, 'A1', '0:0')
  await expect(formula(page)).toHaveValue("='Target O''Brien'!$C$4")
  await sheet(page, 'Cut Source')
  await expect(await select(page, 'A1', '0:0')).toHaveText('')
  await expect(cell(page, '0:1')).toHaveText('')
  await select(page, 'G1', '0:6')
  await expect(formula(page)).toHaveValue("=SUM('Target O''Brien'!$C4:D$4)")
  await sheet(page, 'Cut Audit')
  await select(page, 'A1', '0:0')
  await expect(cell(page, '0:0')).toHaveText('23')
  await expect(formula(page)).toHaveValue("=SUM('Target O''Brien'!$C4:D$4)")
  await button(page, 'Undo').click()
  await expect(button(page, 'Undo')).toBeDisabled()
  await sheet(page, 'Cut Source')
  await expect(await select(page, 'A1', '0:0')).toHaveText('4')
  await expect(cell(page, '0:1')).toHaveText('19')
  await sheet(page, "Target O'Brien")
  await expect(await select(page, 'C4', '3:2')).toHaveText('9')
  await expect(cell(page, '3:3')).toHaveText('99')
  await button(page, 'Redo').click()
  await expect(cell(page, '3:2')).toHaveText('4')
  await expect(cell(page, '3:3')).toHaveText('19')
  await sheet(page, 'Cut Audit')
  await select(page, 'A1', '0:0')
  await expect(formula(page)).toHaveValue("=SUM('Target O''Brien'!$C4:D$4)")
})

test('XSCUT-02 toolbar cut across tabs moves formatting hyperlinks and blank payloads', async ({ page }) => {
  await select(page, 'A20:B20', '19:0')
  await copy(page, 'Cut')
  await sheet(page, "Target O'Brien")
  await select(page, 'C20', '19:2')
  await paste(page)
  await expect(cell(page, '19:2')).toHaveText('linked')
  await expect(cell(page, '19:2')).toHaveCSS('font-weight', '700')
  await expect(cell(page, '19:2')).toHaveCSS('font-style', 'italic')
  await expect(cell(page, '19:2').locator('[data-cell-hyperlink]')).toHaveAttribute('href', 'https://source.example/')
  await expect(cell(page, '19:3')).toHaveText('')
  await sheet(page, 'Cut Source')
  await expect(await select(page, 'A20', '19:0')).toHaveText('')
  await expect(cell(page, '19:0')).toHaveCSS('font-weight', '400')
  await expect(cell(page, '19:0').locator('[data-cell-hyperlink]')).toHaveCount(0)
  await button(page, 'Undo').click()
  await expect(cell(page, '19:0')).toHaveText('linked')
  await expect(cell(page, '19:0').locator('[data-cell-hyperlink]')).toHaveAttribute('href', 'https://source.example/')
  await sheet(page, "Target O'Brien")
  await expect(await select(page, 'C20', '19:2')).toHaveText('old')
  await expect(cell(page, '19:3')).toHaveText('99')
  await button(page, 'Redo').click()
  await expect(cell(page, '19:2')).toHaveText('linked')
  await expect(cell(page, '19:3')).toHaveText('')
})
