import { expect, test } from '@playwright/test'
import { button, cell, copy, edit, formula, paste, select, sheet, start } from './support'

test('named range overlap rejects the cross-sheet cut and the same snapshot retries after name repair', async ({ page, context }, info) => {
  await context.grantPermissions(['clipboard-read', 'clipboard-write'])
  await start(page)
  await select(page, 'A1', '0:0')
  await button(page, 'Name manager').click()
  await page.getByLabel('Name', { exact: true }).fill('CutSales')
  await page.getByLabel('Worksheet', { exact: true }).selectOption('source')
  await page.getByLabel('Refers to', { exact: true }).fill('A1')
  await button(page, 'Create name').click()
  const manager = page.getByRole('dialog', { name: 'Name manager', exact: true })
  await expect(manager).toHaveCount(0)
  await sheet(page, 'Cut Audit')
  await select(page, 'B1', '0:1')
  await edit(page, '=SUM(CutSales)')
  await expect(cell(page, '0:1')).toHaveText('4')

  await sheet(page, "Target O'Brien")
  await select(page, 'H1', '0:7')
  await edit(page, 'redo')
  await button(page, 'Undo').click()
  await expect(button(page, 'Redo')).toBeEnabled()
  await sheet(page, 'Cut Source')
  await select(page, 'A1:B1', '0:0')
  await copy(page, 'Cut')
  await sheet(page, "Target O'Brien")
  await select(page, 'C4', '3:2')
  await button(page, 'Paste').click()
  await expect(page.getByLabel('Clipboard status')).toContainText('overlap a named range')
  await expect(page.getByLabel('Clipboard status')).toContainText('Name manager')
  await expect(cell(page, '3:2')).toHaveText('9')
  await expect(cell(page, '3:3')).toHaveText('99')
  await expect(button(page, 'Redo')).toBeEnabled()
  await page.screenshot({ path: info.outputPath('named-range-rejection.png') })
  await sheet(page, 'Cut Source')
  await expect(await select(page, 'A1', '0:0')).toHaveText('4')
  await expect(cell(page, '0:1')).toHaveText('19')
  await sheet(page, 'Cut Audit')
  await select(page, 'B1', '0:1')
  await expect(cell(page, '0:1')).toHaveText('4')
  await expect(formula(page)).toHaveValue('=SUM(CutSales)')
  await expect(cell(page, '0:0')).toHaveText('23')

  // Change only the name definition through the product UI; do not capture another cut.
  await button(page, 'Name manager').click()
  await button(page, 'Edit CutSales').click()
  await expect(page.getByLabel('Worksheet', { exact: true })).toHaveValue('source')
  await expect(page.getByLabel('Refers to', { exact: true })).toHaveValue('A1')
  await page.getByLabel('Refers to', { exact: true }).fill('F1')
  await button(page, 'Save changes').click()
  await expect(manager).toHaveCount(0)
  await expect(cell(page, '0:1')).toHaveText('3')
  await sheet(page, "Target O'Brien")
  await select(page, 'C4', '3:2')
  await paste(page)
  await expect(cell(page, '3:2')).toHaveText('4')
  await expect(cell(page, '3:3')).toHaveText('19')
  await sheet(page, 'Cut Source')
  await expect(await select(page, 'A1', '0:0')).toHaveText('')
  await expect(cell(page, '0:1')).toHaveText('')
  await sheet(page, 'Cut Audit')
  await expect(cell(page, '0:1')).toHaveText('3')
  await expect(cell(page, '0:0')).toHaveText('23')
  await button(page, 'Undo').click()
  await expect(cell(page, '0:1')).toHaveText('3')
  await sheet(page, 'Cut Source')
  await expect(await select(page, 'A1', '0:0')).toHaveText('4')
  await expect(cell(page, '0:1')).toHaveText('19')
  await sheet(page, "Target O'Brien")
  await expect(await select(page, 'C4', '3:2')).toHaveText('9')
  await expect(cell(page, '3:3')).toHaveText('99')
})
