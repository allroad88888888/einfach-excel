import { expect, test } from '@playwright/test'
import { button, cell, copy, edit, formula, paste, select, sheet, start } from './support'

test.beforeEach(async ({ page, context }) => {
  await context.grantPermissions(['clipboard-read', 'clipboard-write'])
  await start(page)
})

test('XSCUT-03 partial range rejection preserves data redo and the same cut for a corrected retry', async ({ page }) => {
  await sheet(page, "Target O'Brien")
  await select(page, 'H1', '0:7')
  await edit(page, 'redo')
  await button(page, 'Undo').click()
  await expect(button(page, 'Redo')).toBeEnabled()
  await sheet(page, 'Cut Source')
  await select(page, 'A12', '11:0')
  await copy(page, 'Cut')
  await sheet(page, "Target O'Brien")
  await select(page, 'C14', '13:2')
  await button(page, 'Paste').click()
  await expect(page.getByLabel('Clipboard status')).toContainText('larger range')
  await expect(cell(page, '13:2')).toHaveText('')
  await expect(button(page, 'Redo')).toBeEnabled()
  await sheet(page, 'Cut Source')
  await expect(await select(page, 'A12', '11:0')).toHaveText('5')
  await expect(cell(page, '12:0')).toHaveText('6')
  await sheet(page, 'Cut Audit')
  await select(page, 'A5', '4:0')
  await edit(page, "='Cut Source'!A12")
  await sheet(page, "Target O'Brien")
  await select(page, 'C14', '13:2')
  await paste(page)
  await expect(cell(page, '13:2')).toHaveText('5')
  await sheet(page, 'Cut Source')
  await expect(await select(page, 'A12', '11:0')).toHaveText('')
  await expect(cell(page, '12:0')).toHaveText('6')
  await expect(cell(page, '13:0')).toHaveText('7')
  await sheet(page, 'Cut Audit')
  await select(page, 'A5', '4:0')
  await expect(formula(page)).toHaveValue("='Target O''Brien'!C14")
})

test('XSCUT-04 stop validation rolls back the cross-sheet cut and permits a corrected destination', async ({ page }) => {
  await select(page, 'A6', '5:0')
  await copy(page, 'Cut')
  await sheet(page, "Target O'Brien")
  await select(page, 'C8', '7:2')
  await button(page, 'Paste').click()
  await expect(page.getByLabel('Clipboard status')).toContainText('Nothing was pasted')
  await expect(cell(page, '7:2')).toHaveText('9')
  await expect(button(page, 'Undo')).toBeDisabled()
  await sheet(page, 'Cut Source')
  await expect(await select(page, 'A6', '5:0')).toHaveText('20')
  await sheet(page, "Target O'Brien")
  await select(page, 'C9', '8:2')
  await paste(page)
  await expect(cell(page, '8:2')).toHaveText('20')
  await expect(cell(page, '7:2')).toHaveText('9')
  await button(page, 'Undo').click()
  await expect(cell(page, '8:2')).toHaveText('')
  await sheet(page, 'Cut Source')
  await expect(await select(page, 'A6', '5:0')).toHaveText('20')
})

test('XSCUT-05 warning cancel keeps the cut and explicit continue moves it with one history entry', async ({ page }) => {
  await select(page, 'A7', '6:0')
  await copy(page, 'Cut')
  await sheet(page, "Target O'Brien")
  await select(page, 'C10', '9:2')
  await button(page, 'Paste').click()
  const confirmation = page.getByRole('dialog', { name: 'Within 0–10', exact: true })
  await expect(confirmation).toBeVisible()
  await expect(cell(page, '9:2')).toHaveText('9')
  await confirmation.getByRole('button', { name: 'Cancel', exact: true }).click()
  await expect(confirmation).toHaveCount(0)
  await expect(button(page, 'Undo')).toBeDisabled()
  await button(page, 'Paste').click()
  await confirmation.getByRole('button', { name: 'Continue', exact: true }).click()
  await expect(confirmation).toHaveCount(0)
  await expect(cell(page, '9:2')).toHaveText('20')
  await button(page, 'Undo').click()
  await expect(cell(page, '9:2')).toHaveText('9')
  await expect(button(page, 'Undo')).toBeDisabled()
  await sheet(page, 'Cut Source')
  await expect(await select(page, 'A7', '6:0')).toHaveText('20')
  await button(page, 'Redo').click()
  await expect(cell(page, '6:0')).toHaveText('')
})

test('XSCUT-06 merged destination rejects atomically and the same cut can move to an ordinary cell', async ({ page }) => {
  await select(page, 'A20', '19:0')
  await copy(page, 'Cut')
  await sheet(page, "Target O'Brien")
  await select(page, 'G20:H20', '19:6')
  await button(page, 'Paste').click()
  await expect(page.getByLabel('Clipboard status')).toContainText('Unmerge the source and destination')
  await expect(button(page, 'Undo')).toBeDisabled()
  await sheet(page, 'Cut Source')
  await expect(await select(page, 'A20', '19:0')).toHaveText('linked')
  await sheet(page, "Target O'Brien")
  await select(page, 'C20', '19:2')
  await paste(page)
  await expect(cell(page, '19:2')).toHaveText('linked')
})
