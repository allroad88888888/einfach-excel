import { expect, test, type Page } from '@playwright/test'
import { select } from '../support/clipboard'

const panel = (page: Page) => page.getByRole('dialog', { name: 'Fill series', exact: true })
const cell = (page: Page, coord: string) => page.locator(`td[data-cell="${coord}"]`)
const button = (page: Page, name: string) => panel(page).getByRole('button', { name, exact: true })
async function open(page: Page) {
  await select(page, 'E55:E59', '54:4')
  await page.getByRole('button', { name: 'Fill series', exact: true }).click()
  await panel(page).getByLabel('Sequence type').selectOption('custom-list')
}
async function save(page: Page, name = 'Priority', items = 'Low\nMedium\nHigh') {
  await panel(page).getByLabel('List name', { exact: true }).fill(name)
  await panel(page).getByLabel('Custom list items').fill(items)
  await button(page, 'Save list').click()
  await expect(panel(page).getByRole('status')).toHaveText('List saved.')
}
async function apply(page: Page) {
  await button(page, 'Apply series').click()
  await expect(panel(page)).toHaveCount(0)
}
test.beforeEach(async ({ page }) => {
  await page.goto('/')
  await expect(cell(page, '1:0')).toHaveText('SO-10001')
  await page.getByRole('tab', { name: 'Summary', exact: true }).click()
})

for (const width of [1280, 390]) {
  test(`save and reuse a preset with one native fill and undo at ${width}px`, async ({ page }, info) => {
    const errors: string[] = []
    page.on('pageerror', error => errors.push(error.message))
    await page.setViewportSize({ width, height: 850 })
    await open(page)
    await save(page)
    await expect(page.getByRole('button', { name: 'Undo', exact: true })).toBeDisabled()
    await expect(cell(page, '55:4')).toHaveText('')
    for (const control of await panel(page).locator('input, select, textarea, button').all())
      await expect(control).toBeInViewport()
    await page.screenshot({ path: info.outputPath(`custom-lists-${width}.png`) })
    await button(page, 'Cancel').click()
    await expect(page.getByRole('button', { name: 'Fill series', exact: true })).toBeFocused()
    await open(page)
    await button(page, 'New list').click()
    await panel(page).getByLabel('Saved lists').selectOption('0')
    await expect(panel(page).getByLabel('Custom list items')).toHaveValue('Low\nMedium\nHigh')
    await apply(page)
    await expect(cell(page, '55:4')).toHaveText('Medium')
    await expect(cell(page, '56:4')).toHaveText('High')
    await expect(cell(page, '58:4')).toHaveText('Medium')
    await expect(cell(page, '58:4')).toHaveCSS('text-decoration-line', 'underline')
    await page.getByRole('button', { name: 'Undo', exact: true }).click()
    await expect(cell(page, '55:4')).toHaveText('')
    await expect(page.getByRole('button', { name: 'Undo', exact: true })).toBeDisabled()
    // 管理预设不能清除已有 Redo，也不能改变那次填充已记录的原生结果。
    await open(page)
    await save(page, 'Updated priority', 'Low\nHigh')
    await button(page, 'Delete list').click()
    await button(page, 'Cancel').click()
    await expect(page.getByRole('button', { name: 'Redo', exact: true })).toBeEnabled()
    await page.getByRole('button', { name: 'Redo', exact: true }).click()
    await expect(cell(page, '55:4')).toHaveText('Medium')
    expect(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth)).toBe(true)
    expect(errors).toEqual([])
  })

  test(`edit replaces only the saved preset and Rust uses the new order at ${width}px`, async ({ page }) => {
    await page.setViewportSize({ width, height: 850 })
    await open(page)
    await save(page)
    await button(page, 'New list').click()
    await save(page, 'Status', 'Open\nClosed')
    await panel(page).getByLabel('Saved lists').selectOption('0')
    await save(page, 'Urgency', 'Low\nHigh\nMedium')
    await expect(panel(page).getByLabel('Saved lists').locator('option')).toHaveText([
      'New unsaved list', 'Urgency', 'Status',
    ])
    await expect(cell(page, '55:4')).toHaveText('')
    await apply(page)
    await expect(cell(page, '55:4')).toHaveText('High')
    await expect(cell(page, '56:4')).toHaveText('Medium')
    await page.getByRole('button', { name: 'Undo', exact: true }).click()
    await expect(cell(page, '55:4')).toHaveText('')
    await expect(page.getByRole('button', { name: 'Undo', exact: true })).toBeDisabled()
  })

  test(`delete never changes cells or leaves a stale selected list at ${width}px`, async ({ page }) => {
    await page.setViewportSize({ width, height: 850 })
    await open(page)
    await save(page)
    await button(page, 'New list').click()
    await save(page, 'Status', 'Open\nClosed')
    await panel(page).getByLabel('Saved lists').selectOption('0')
    await button(page, 'Delete list').click()
    await expect(panel(page).getByRole('status')).toHaveText('List deleted.')
    await expect(panel(page).getByLabel('List name', { exact: true })).toHaveValue('')
    await expect(panel(page).getByLabel('Custom list items')).toHaveValue('')
    await expect(button(page, 'Delete list')).toBeDisabled()
    await panel(page).getByLabel('Saved lists').selectOption('0')
    await expect(panel(page).getByLabel('Custom list items')).toHaveValue('Open\nClosed')
    await button(page, 'Delete list').click()
    await expect(panel(page).getByLabel('Saved lists').locator('option')).toHaveCount(1)
    await page.keyboard.press('Escape')
    await expect(cell(page, '54:4')).toHaveText('Low')
    await expect(cell(page, '55:4')).toHaveText('')
    await expect(page.getByRole('button', { name: 'Undo', exact: true })).toBeDisabled()
  })
}

test('invalid presets and native source rejection keep drafts retryable', async ({ page }) => {
  await open(page)
  await panel(page).getByLabel('List name', { exact: true }).fill('Priority')
  await panel(page).getByLabel('Custom list items').fill('Low\nlow')
  await button(page, 'Save list').click()
  await expect(panel(page).getByRole('alert')).toContainText('unique')
  await save(page, 'Priority', 'Open\nClosed')
  await button(page, 'Apply series').click()
  await expect(panel(page).getByRole('alert')).toContainText('do not match this named list')
  await expect(panel(page).getByLabel('Custom list items')).toHaveValue('Open\nClosed')
  await expect(cell(page, '55:4')).toHaveText('')
  await expect(page.getByRole('button', { name: 'Undo', exact: true })).toBeDisabled()
  await save(page)
  await apply(page)
  await expect(cell(page, '55:4')).toHaveText('Medium')
})

test('sheet changes retain presets, new workbook and reload clear them', async ({ page }) => {
  await open(page)
  await save(page)
  await button(page, 'Cancel').click()
  await page.getByRole('tab', { name: 'Sales Orders', exact: true }).click()
  await page.getByRole('tab', { name: 'Summary', exact: true }).click()
  await open(page)
  await expect(panel(page).getByLabel('List name', { exact: true })).toHaveValue('Priority')
  await button(page, 'Cancel').click()
  await page.getByRole('button', { name: 'File', exact: true }).click()
  page.once('dialog', dialog => dialog.accept())
  await page.getByRole('button', { name: 'New blank workbook', exact: true }).click()
  await expect(page.getByRole('tab', { name: 'Sheet1', exact: true })).toBeVisible()
  await select(page, 'A1:A5', '0:0')
  await page.getByRole('button', { name: 'Fill series', exact: true }).click()
  await panel(page).getByLabel('Sequence type').selectOption('custom-list')
  await expect(panel(page).getByLabel('Saved lists').locator('option')).toHaveCount(1)
  await expect(panel(page).getByLabel('Custom list items')).toHaveValue('')
  await page.reload()
  await expect(cell(page, '1:0')).toHaveText('SO-10001')
  await page.getByRole('tab', { name: 'Summary', exact: true }).click()
  await open(page)
  await expect(panel(page).getByLabel('Saved lists').locator('option')).toHaveCount(1)
})

test('Chinese list controls, validation and feedback are translated', async ({ page }, info) => {
  await page.goto('/?locale=zh')
  await expect(cell(page, '1:0')).toHaveText('SO-10001')
  await page.getByRole('tab', { name: 'Summary', exact: true }).click()
  const name = page.getByRole('textbox', { name: '名称框' })
  await name.fill('E55:E59')
  await name.press('Enter')
  await page.getByRole('button', { name: '填充序列', exact: true }).click()
  const dialog = page.getByRole('dialog', { name: '填充序列', exact: true })
  await dialog.getByLabel('序列类型').selectOption('custom-list')
  await dialog.getByRole('button', { name: '保存列表', exact: true }).click()
  await expect(dialog.getByRole('alert')).toHaveText('请输入 1–64 个字符的列表名称。')
  await dialog.getByLabel('列表名称', { exact: true }).fill('优先级')
  await dialog.getByLabel('自定义列表项', { exact: true }).fill('Low\nMedium\nHigh')
  await dialog.getByRole('button', { name: '保存列表', exact: true }).click()
  await expect(dialog.getByRole('status')).toHaveText('列表已保存。')
  await page.screenshot({ path: info.outputPath('custom-lists-zh.png') })
  await dialog.getByRole('button', { name: '删除列表', exact: true }).click()
  await expect(dialog.getByRole('status')).toHaveText('列表已删除。')
})
