import { expect, test, type Page } from '@playwright/test'
import { select } from '../support/clipboard'

const cell = (page: Page, coord: string) => page.locator(`td[data-cell="${coord}"]`)

for (const width of [1280, 390]) for (const action of ['New list', 'New unsaved list', 'Saved list'])
  test(`${action} entry preserves saved presets and fills only after Apply at ${width}px`, async ({ page }) => {
    await page.setViewportSize({ width, height: 850 })
    await page.goto('/e2e/fixtures/plain-sales-orders/')
    await expect(cell(page, '1:0')).toHaveText('SO-10001')
    await page.getByRole('tab', { name: 'Summary', exact: true }).click()
    await select(page, 'E55:E59', '54:4')
    await page.getByRole('button', { name: 'Fill series', exact: true }).click()
    const dialog = page.getByRole('dialog', { name: 'Fill series', exact: true })
    await dialog.getByRole('combobox', { name: 'Sequence type', exact: true }).selectOption('custom-list')
    const saved = dialog.getByRole('combobox', { name: 'Saved lists', exact: true })
    const name = dialog.getByRole('textbox', { name: 'List name', exact: true })
    const items = dialog.getByRole('textbox', { name: 'Custom list items', exact: true })
    await name.fill('Priority')
    await items.fill('Low\nMedium\nHigh')
    await dialog.getByRole('button', { name: 'Save list', exact: true }).click()
    await expect(dialog.getByRole('status')).toHaveText('List saved.')
    if (action === 'Saved list') await dialog.getByRole('button', { name: 'New list', exact: true }).click()
    await name.fill('Discard draft')
    await items.fill('Low\nOther')
    if (action === 'New list') await dialog.getByRole('button', { name: action, exact: true }).click()
    else await saved.selectOption(action === 'Saved list' ? '0' : '')
    await expect(saved).toHaveValue(action === 'Saved list' ? '0' : '')
    await expect(name).toHaveValue(action === 'Saved list' ? 'Priority' : '')
    await expect(items).toHaveValue(action === 'Saved list' ? 'Low\nMedium\nHigh' : '')
    await expect(saved.getByRole('option', { name: 'Priority', exact: true })).toHaveCount(1)
    await expect(cell(page, '54:4')).toHaveText('Low')
    await expect(cell(page, '55:4')).toHaveText('')
    await expect(page.getByRole('button', { name: 'Undo', exact: true })).toBeDisabled()
    if (action !== 'Saved list') await saved.selectOption('0')
    await dialog.getByRole('button', { name: 'Apply series', exact: true }).click()
    await expect(dialog).toHaveCount(0)
    await expect(cell(page, '55:4')).toHaveText('Medium')
    await expect(cell(page, '56:4')).toHaveText('High')
    await expect(cell(page, '58:4')).toHaveText('Medium')
    await expect(cell(page, '58:4')).toHaveCSS('text-decoration-line', 'underline')
    await expect(cell(page, '54:2')).toHaveText('Nov')
    await page.getByRole('button', { name: 'Undo', exact: true }).click()
    await expect(cell(page, '54:4')).toHaveText('Low')
    await expect(cell(page, '55:4')).toHaveText('')
    await expect(cell(page, '58:4')).toHaveText('')
    await expect(page.getByRole('button', { name: 'Undo', exact: true })).toBeDisabled()
    await page.getByRole('button', { name: 'Redo', exact: true }).click()
    await expect(cell(page, '58:4')).toHaveText('Medium')
  })
