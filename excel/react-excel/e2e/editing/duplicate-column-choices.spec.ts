import { expect, test } from '@playwright/test'
import { select } from '../support/clipboard'

for (const width of [1280, 390]) for (const action of ['Select all', 'Clear all', 'Compare column'])
  test(`${action} duplicate columns invalidates confirmation without losing redo at ${width}px`, async ({ page }) => {
    await page.setViewportSize({ width, height: 850 })
    await page.goto('/e2e/fixtures/plain-sales-orders/')
    const cell = (coord: string) => page.locator(`td[data-cell="${coord}"]`)
    const button = (name: string) => page.getByRole('button', { name, exact: true })
    await expect(cell('1:0')).toHaveText('SO-10001')
    await select(page, 'E2', '1:4')
    const bar = page.getByRole('textbox', { name: 'Active cell value', exact: true })
    await bar.fill('2')
    await bar.press('Enter')
    await expect(cell('1:6')).toHaveText('158')
    await button('Undo').click()
    await page.getByRole('tab', { name: 'Summary', exact: true }).click()
    await select(page, 'D32:F37', '31:3')
    await button('Remove duplicates').click()
    const dialog = page.getByRole('dialog', { name: 'Remove duplicates', exact: true })
    const status = dialog.getByRole('status')
    await expect(status).toContainText('0 duplicate records;')
    await dialog.getByRole('checkbox', { name: 'Compare column F', exact: true }).uncheck()
    await button('Update preview').click()
    await expect(status).toContainText('2 duplicate records;')
    await dialog.getByRole('checkbox', { name: /Remove 2 duplicate records/ }).check()
    await expect(button('Remove records')).toBeEnabled()
    if (action === 'Compare column')
      await dialog.getByRole('checkbox', { name: 'Compare column F', exact: true }).check()
    else await dialog.getByRole('button', { name: action, exact: true }).click()
    await expect(button('Remove records')).toBeDisabled()
    for (const col of ['D', 'E', 'F'])
      await expect(dialog.getByRole('checkbox', { name: `Compare column ${col}`, exact: true }))
        .toBeChecked({ checked: action !== 'Clear all' })
    await expect(dialog.getByRole('checkbox', { name: /Remove .* duplicate records/ })).toHaveCount(0)
    await button('Update preview').click()
    if (action === 'Clear all') {
      await expect(dialog.getByRole('alert')).toContainText('at least one comparison column')
      await dialog.getByRole('button', { name: 'Select all', exact: true }).click()
      await button('Update preview').click()
    }
    await expect(status).toContainText('0 duplicate records;')
    await expect(button('Remove records')).toBeDisabled()
    await button('Cancel').click()
    await expect(button('Remove duplicates')).toBeFocused()
    await expect(await select(page, 'F33', '32:5')).toHaveCSS('font-style', 'italic')
    await expect(await select(page, 'F37', '36:5')).toHaveText('P1')
    await expect(button('Undo')).toBeDisabled()
    await button('Redo').click()
    await page.getByRole('tab', { name: 'Sales Orders', exact: true }).click()
    await select(page, 'E2', '1:4')
    await expect(cell('1:4')).toHaveText('2')
    await expect(cell('1:4')).toHaveCSS('color', 'rgb(192, 0, 0)')
    await expect(cell('1:6')).toHaveText('158')
  })
