import { expect, test } from '@playwright/test'
import { select } from '../support/clipboard'

for (const width of [1280, 390]) for (const action of ['Open', 'Cancel', 'Escape', 'Tab', 'Shift+Tab'])
  test(`${action} duplicate dialog resets its draft and preserves native redo at ${width}px`, async ({ page }, info) => {
    await page.setViewportSize({ width, height: 850 })
    await page.goto('/e2e/fixtures/plain-sales-orders/')
    const cell = (coord: string) => page.locator(`td[data-cell="${coord}"]`)
    const button = (name: string) => page.getByRole('button', { name, exact: true })
    await expect(cell('1:0')).toHaveText('SO-10001')
    await page.getByRole('tab', { name: 'Summary', exact: true }).click()
    await select(page, 'H94', '93:7')
    const bar = page.getByRole('textbox', { name: 'Active cell value', exact: true })
    await bar.fill('duplicate redo')
    await bar.press('Enter')
    await expect(cell('93:7')).toHaveText('duplicate redo')
    await button('Undo').click()
    await select(page, 'D32:F37', '31:3')
    await button('Remove duplicates').click()
    const dialog = page.getByRole('dialog', { name: 'Remove duplicates', exact: true })
    const first = dialog.getByRole('checkbox', { name: 'First row contains headers', exact: true })
    await expect(first).toBeFocused()
    await expect(first).toBeChecked()
    const policy = dialog.getByRole('combobox', { name: 'Text comparison', exact: true })
    await expect(policy).toHaveValue('ignoreCase')
    await expect(dialog.getByRole('status')).toContainText('0 duplicate records;')
    if (action === 'Open') {
      expect(await dialog.evaluate(node => node.scrollWidth <= node.clientWidth)).toBe(true)
      for (const control of await dialog.locator('input, select, button').all())
        await expect(control).toBeInViewport()
      await page.screenshot({ path: info.outputPath(`duplicates-open-${width}.png`) })
    } else {
      await first.uncheck()
      await policy.selectOption('trimIgnoreCase')
      await dialog.getByRole('checkbox', { name: 'Compare column F', exact: true }).uncheck()
    }
    if (action === 'Tab' || action === 'Shift+Tab') {
      // 未刷新草稿时 Apply 禁用，边界应落在 Update preview，不是禁用的提交按钮。
      const last = dialog.getByRole('button', { name: 'Update preview', exact: true })
      await (action === 'Tab' ? last : first).focus()
      await page.keyboard.press(action)
      await expect(action === 'Tab' ? first : last).toBeFocused()
    }
    if (action === 'Escape') await page.keyboard.press('Escape')
    else await button('Cancel').click()
    await expect(dialog).toHaveCount(0)
    await expect(button('Remove duplicates')).toBeFocused()
    await expect(page.getByRole('textbox', { name: 'Name box' })).toHaveValue('D32:F37')
    await expect(button('Undo')).toBeDisabled()
    await button('Remove duplicates').click()
    await expect(first).toBeChecked()
    await expect(policy).toHaveValue('ignoreCase')
    await expect(dialog.getByRole('checkbox', { name: 'Compare column F', exact: true })).toBeChecked()
    await button('Cancel').click()
    await expect(await select(page, 'F33', '32:5')).toHaveCSS('font-style', 'italic')
    await expect(await select(page, 'F37', '36:5')).toHaveText('P1')
    await expect(await select(page, 'D32', '31:3')).toHaveText('Key')
    await button('Redo').click()
    await expect(await select(page, 'H94', '93:7')).toHaveText('duplicate redo')
  })
