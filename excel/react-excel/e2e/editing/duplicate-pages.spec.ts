import { expect, test } from '@playwright/test'
import { paste, select } from '../support/clipboard'

for (const width of [1280, 390]) for (const action of ['Next page', 'Previous page'])
  test(`${action} duplicate preview reads its exact page without changing source history at ${width}px`, async ({ page, context }) => {
    await context.grantPermissions(['clipboard-read', 'clipboard-write'])
    await page.setViewportSize({ width, height: 850 })
    await page.goto('/e2e/fixtures/plain-sales-orders/')
    const cell = (coord: string) => page.locator(`td[data-cell="${coord}"]`)
    const button = (name: string) => page.getByRole('button', { name, exact: true })
    await expect(cell('1:0')).toHaveText('SO-10001')
    const originalHeader = await (await select(page, 'O1', '0:14')).textContent()
    const originalLast = await (await select(page, 'P46', '45:15')).textContent()
    const outside = await (await select(page, 'N46', '45:13')).textContent()
    await select(page, 'O1', '0:14')
    await page.evaluate(() => navigator.clipboard.writeText(
      Array.from({ length: 46 }, (_, index) => `Key${index % 3}\tID${index}`).join('\n'),
    ))
    await paste(page)
    await select(page, 'O1:P46', '0:14')
    await button('Remove duplicates').click()
    const dialog = page.getByRole('dialog', { name: 'Remove duplicates', exact: true })
    await expect(dialog.getByRole('status')).toContainText('0 duplicate records;')
    await dialog.getByRole('checkbox', { name: 'First row contains headers', exact: true }).uncheck()
    await dialog.getByRole('checkbox', { name: 'Compare column P', exact: true }).uncheck()
    await button('Update preview').click()
    const navigation = dialog.getByRole('navigation', { name: 'Duplicate preview pages', exact: true })
    await expect(navigation).toContainText('Showing 1–20 of 43')
    await expect(button('Previous page')).toBeDisabled()
    if (action === 'Previous page') {
      await button('Next page').click()
      await expect(navigation).toContainText('Showing 21–40 of 43')
      await button('Next page').click()
      await expect(navigation).toContainText('Showing 41–43 of 43')
      await expect(button('Next page')).toBeDisabled()
    }
    await dialog.getByRole('checkbox', { name: /Remove 43 duplicate records/ }).check()
    await button(action).click()
    await expect(navigation).toContainText('Showing 21–40 of 43')
    await expect(dialog.getByRole('checkbox', { name: /Remove 43 duplicate records/ })).not.toBeChecked()
    await expect(button('Remove records')).toBeDisabled()
    const rows = dialog.getByRole('table', { name: 'Duplicate records to remove' }).getByRole('row')
    await expect(rows).toHaveCount(21)
    await expect(rows.nth(1)).toHaveText('243Key2 · ID23')
    await expect(rows.nth(20)).toHaveText('431Key0 · ID42')
    await expect(button('Go to first occurrence row 3 for duplicate row 24')).toBeVisible()
    await button('Cancel').click()
    await button('Undo').click()
    await expect(await select(page, 'O1', '0:14')).toHaveText(originalHeader ?? '')
    await expect(await select(page, 'P46', '45:15')).toHaveText(originalLast ?? '')
    await expect(await select(page, 'N46', '45:13')).toHaveText(outside ?? '')
    await expect(button('Undo')).toBeDisabled()
    await button('Redo').click()
    await expect(await select(page, 'P46', '45:15')).toHaveText('ID45')
  })
