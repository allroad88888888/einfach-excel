import { expect, test } from '@playwright/test'
import { select } from '../support/clipboard'

for (const width of [1280, 390])
  test(`Update duplicate preview requires a fresh confirmation before one native removal at ${width}px`, async ({ page }) => {
    await page.setViewportSize({ width, height: 850 })
    await page.goto('/e2e/fixtures/plain-sales-orders/')
    const cell = (coord: string) => page.locator(`td[data-cell="${coord}"]`)
    const button = (name: string) => page.getByRole('button', { name, exact: true })
    await expect(cell('1:0')).toHaveText('SO-10001')
    await page.getByRole('tab', { name: 'Summary', exact: true }).click()
    await select(page, 'D32:F37', '31:3')
    await button('Remove duplicates').click()
    const dialog = page.getByRole('dialog', { name: 'Remove duplicates', exact: true })
    await expect(dialog.getByRole('status')).toContainText('0 duplicate records;')
    await dialog.getByRole('checkbox', { name: 'Compare column F', exact: true }).uncheck()
    await button('Update preview').click()
    await expect(dialog.getByRole('status')).toContainText('2 duplicate records;')
    const confirm = dialog.getByRole('checkbox', { name: /Remove 2 duplicate records/ })
    await confirm.check()
    await expect(button('Remove records')).toBeEnabled()
    await button('Update preview').click()
    await expect(dialog.getByRole('status')).toContainText('2 duplicate records;')
    await expect(confirm).not.toBeChecked()
    await expect(button('Remove records')).toBeDisabled()
    await expect(button('Undo')).toBeDisabled()
    await expect(cell('33:5')).toHaveText('M2')
    await confirm.check()
    await button('Remove records').click()
    await expect(dialog).toHaveCount(0)
    await expect(await select(page, 'F34', '33:5')).toHaveText('M4')
    await expect(await select(page, 'F35', '34:5')).toHaveText('P1')
    await expect(cell('34:5')).toHaveCSS('text-decoration-line', 'underline')
    await expect(await select(page, 'F33', '32:5')).toHaveCSS('font-style', 'italic')
    await button('Undo').click()
    await expect(await select(page, 'F37', '36:5')).toHaveText('P1')
    await expect(await select(page, 'F34', '33:5')).toHaveText('M2')
    await expect(button('Undo')).toBeDisabled()
    await button('Redo').click()
    await expect(cell('33:5')).toHaveText('M4')
  })
