import { expect, test, type Page } from '@playwright/test'
import { select } from '../support/clipboard'

const cell = (page: Page, coord: string) => page.locator(`td[data-cell="${coord}"]`)
const button = (page: Page, name: string) => page.getByRole('button', { name, exact: true })

for (const width of [1280, 390]) for (const action of ['Open', 'Cancel', 'Escape', 'Tab', 'Shift+Tab'])
  test(`${action} series dialog preserves samples and native redo at ${width}px`, async ({ page }, info) => {
    await page.setViewportSize({ width, height: 850 })
    await page.goto('/e2e/fixtures/plain-sales-orders/')
    await expect(cell(page, '1:0')).toHaveText('SO-10001')
    await page.getByRole('tab', { name: 'Summary', exact: true }).click()
    await select(page, 'H94', '93:7')
    const bar = page.getByRole('textbox', { name: 'Active cell value', exact: true })
    await bar.fill('retained redo')
    await bar.press('Enter')
    await expect(cell(page, '93:7')).toHaveText('retained redo')
    await button(page, 'Undo').click()
    await expect(cell(page, '93:7')).toHaveText('')
    await select(page, 'A40:A44', '39:0')
    await button(page, 'Fill series').click()
    const dialog = page.getByRole('dialog', { name: 'Fill series', exact: true })
    const kind = dialog.getByRole('combobox', { name: 'Sequence type', exact: true })
    await expect(kind).toBeFocused()
    await expect(kind).toHaveValue('number')
    await expect(dialog.getByRole('combobox', { name: 'Direction', exact: true })).toHaveValue('down')
    await expect(dialog.getByRole('spinbutton', { name: 'Source sample count', exact: true })).toHaveValue('2')
    if (action === 'Open') {
      expect(await dialog.evaluate(node => node.scrollWidth <= node.clientWidth)).toBe(true)
      for (const control of await dialog.locator('input, select, button').all())
        await expect(control).toBeInViewport()
      await page.screenshot({ path: info.outputPath(`series-open-${width}.png`) })
    } else if (action === 'Tab' || action === 'Shift+Tab') {
      const cancel = dialog.getByRole('button', { name: 'Cancel', exact: true })
      await (action === 'Tab' ? cancel : kind).focus()
      await page.keyboard.press(action)
      await expect(action === 'Tab' ? kind : cancel).toBeFocused()
    } else {
      await kind.selectOption('weekday-name')
      await dialog.getByRole('combobox', { name: 'Direction', exact: true }).selectOption('right')
      await dialog.getByRole('spinbutton', { name: 'Source sample count', exact: true }).fill('3')
    }
    if (action === 'Escape') await dialog.getByRole('spinbutton', { name: 'Source sample count' }).press('Escape')
    else await dialog.getByRole('button', { name: 'Cancel', exact: true }).click()
    await expect(dialog).toHaveCount(0)
    await expect(button(page, 'Fill series')).toBeFocused()
    for (const [coord, value] of [['39:0', '1'], ['40:0', '3'], ['41:0', ''], ['43:0', '']] as const)
      await expect(cell(page, coord)).toHaveText(value)
    await expect(cell(page, '39:2')).toHaveText('Item001')
    await expect(cell(page, '39:2')).toHaveCSS('font-style', 'italic')
    await expect(button(page, 'Undo')).toBeDisabled()
    await button(page, 'Fill series').click()
    await expect(kind).toHaveValue('number')
    await expect(dialog.getByRole('combobox', { name: 'Direction', exact: true })).toHaveValue('down')
    await expect(dialog.getByRole('spinbutton', { name: 'Source sample count', exact: true })).toHaveValue('2')
    await dialog.getByRole('button', { name: 'Cancel', exact: true }).click()
    await button(page, 'Redo').click()
    await select(page, 'H94', '93:7')
    await expect(cell(page, '93:7')).toHaveText('retained redo')
  })
