import { expect, test, type Page } from '@playwright/test'
import { select } from '../support/clipboard'

const cell = (page: Page, coord: string) => page.locator(`td[data-cell="${coord}"]`)
const menu = (page: Page) => page.getByRole('combobox', { name: 'Worksheet filter' })
const button = (page: Page, name: string) => page.getByRole('button', { name, exact: true })
async function open(page: Page) {
  await menu(page).selectOption('open')
  return page.getByRole('dialog', { name: 'Filter conditions' })
}
async function westStillApplied(page: Page) {
  await expect(cell(page, '25:2')).toHaveText('W20')
  await expect(cell(page, '26:2')).toHaveCount(0)
  await expect(cell(page, '27:2')).toHaveText('W10')
  await expect(cell(page, '28:2')).toHaveCount(0)
  await expect(cell(page, '25:2')).toHaveCSS('font-weight', '700')
  await expect(cell(page, '0:1')).toHaveText('79')
}
async function history(page: Page, counts: string) {
  await button(page, 'Recent operations').click()
  await expect(page.getByRole('dialog')).toContainText(counts)
  await button(page, 'Close history').click()
}
test.beforeEach(async ({ page }) => {
  await page.goto('/e2e/fixtures/plain-sales-orders/')
  await expect(cell(page, '1:0')).toHaveText('SO-10001')
  await page.getByRole('tab', { name: 'Summary', exact: true }).click()
  await select(page, 'A25:C29', '24:0')
  await menu(page).selectOption('selection')
  await button(page, 'Filter column A').click()
  await page.getByLabel('Filter value 1', { exact: true }).fill('West')
  await button(page, 'Apply filter').click()
  await westStillApplied(page)
  await select(page, 'A30', '29:0')
  const input = page.getByRole('textbox', { name: 'Active cell value' })
  await input.fill('Keep redo'); await input.press('Enter')
  await expect(cell(page, '29:0')).toHaveText('Keep redo')
  await button(page, 'Undo').click()
  await expect(cell(page, '29:0')).toHaveText('')
  await select(page, 'A25', '24:0')
})

for (const dismissal of ['Cancel', 'Escape']) for (const width of [1280, 390])
  test(`${dismissal} filter discards draft conditions and preserves redo at ${width}px`, async ({ page }) => {
    await page.setViewportSize({ width, height: 850 })
    const dialog = await open(page)
    await dialog.getByLabel('Filter condition 1', { exact: true }).selectOption('contains')
    await dialog.getByLabel('Filter value 1', { exact: true }).fill('East')
    await dialog.getByRole('checkbox', { name: 'Match case', exact: true }).check()
    await button(page, 'Add condition').click()
    await dialog.getByLabel('Filter value 2', { exact: true }).fill('20')
    if (dismissal === 'Cancel') await button(page, 'Cancel').click()
    else await page.keyboard.press('Escape')
    await expect(dialog).toHaveCount(0)
    await expect(menu(page)).toBeFocused()
    await westStillApplied(page)
    await history(page, '2 undo · 1 redo')
    await button(page, 'Redo').click()
    await expect(cell(page, '29:0')).toHaveText('Keep redo')
    await button(page, 'Undo').click()
    await expect(cell(page, '29:0')).toHaveText('')
    await open(page)
    await expect(dialog.getByLabel('Filter condition 1', { exact: true })).toHaveValue('equals')
    await expect(dialog.getByLabel('Filter value 1', { exact: true })).toHaveValue('West')
    await expect(dialog.getByRole('checkbox', { name: 'Match case', exact: true })).not.toBeChecked()
    await expect(dialog.getByLabel('Filter column 2', { exact: true })).toHaveCount(0)
  })

for (const width of [1280, 390])
  test(`invalid filter bounds stay correctable and commit only the corrected range at ${width}px`, async ({ page }) => {
    await page.setViewportSize({ width, height: 850 })
    const dialog = await open(page)
    await dialog.getByLabel('Filter column 1', { exact: true }).selectOption('1')
    await dialog.getByLabel('Filter condition 1', { exact: true }).selectOption('range')
    await dialog.getByLabel('Minimum 1', { exact: true }).fill('20')
    await dialog.getByLabel('Maximum 1', { exact: true }).fill('10')
    await button(page, 'Apply filter').click()
    await expect(dialog.getByRole('alert')).toContainText('minimum cannot exceed maximum')
    await expect(dialog.getByLabel('Minimum 1', { exact: true })).toHaveValue('20')
    await westStillApplied(page)
    await dialog.getByLabel('Maximum 1', { exact: true }).fill('30')
    await button(page, 'Apply filter').click()
    await expect(dialog).toHaveCount(0)
    await expect(cell(page, '25:2')).toHaveText('W20')
    await expect(cell(page, '26:2')).toHaveCount(0)
    await expect(cell(page, '27:2')).toHaveCount(0)
    await expect(cell(page, '28:2')).toHaveText('E30')
    await expect(button(page, 'Filter column A')).toHaveAttribute('data-filtered', 'false')
    await expect(button(page, 'Filter column B')).toHaveAttribute('data-filtered', 'true')
    await button(page, 'Undo').click()
    await westStillApplied(page)
    await history(page, '2 undo · 1 redo')
    await button(page, 'Redo').click()
    await expect(cell(page, '28:2')).toHaveText('E30')
    await expect(cell(page, '27:2')).toHaveCount(0)
    await expect(cell(page, '29:0')).toHaveText('')
    await open(page)
    await expect(dialog.getByLabel('Minimum 1', { exact: true })).toHaveValue('20')
    await expect(dialog.getByLabel('Maximum 1', { exact: true })).toHaveValue('30')
  })
