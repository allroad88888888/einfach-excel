import { expect, test, type Page } from '@playwright/test'

const cell = (page: Page, coord: string) => page.locator(`td[data-cell="${coord}"]`)
const menu = (page: Page) => page.getByRole('combobox', { name: 'Worksheet filter' })
async function select(page: Page, address: string) {
  const name = page.getByRole('textbox', { name: 'Name box' })
  await name.fill(address)
  await name.press('Enter')
  await expect(name).toHaveValue(address)
  await expect(page.locator('[data-workbook-grid]')).toHaveAttribute('data-projection-retained', 'false')
}
async function open(page: Page) {
  await menu(page).selectOption('open')
  return page.getByRole('dialog', { name: 'Filter conditions' })
}
async function applyWest(page: Page) {
  const dialog = await open(page)
  await dialog.getByLabel('Filter column 1', { exact: true }).selectOption('2')
  await dialog.getByLabel('Filter value 1', { exact: true }).fill('West')
  await dialog.getByRole('button', { name: 'Apply filter', exact: true }).click()
  await expect(dialog).not.toBeVisible()
  await expect(page.getByLabel('Filter status')).toHaveText('750 rows filtered out.')
}
test.beforeEach(async ({ page }) => {
  await page.goto('/')
  await expect(cell(page, '1:0')).toHaveText('SO-10001')
})

test('filter 1,000 rows through Rust, preserve header and source row numbers, undo/redo once', async ({ page }) => {
  await applyWest(page)
  await expect(cell(page, '0:2')).toHaveText('Region')
  await expect(cell(page, '1:0')).toHaveCount(0)
  await expect(cell(page, '4:0')).toHaveText('SO-10004')
  await select(page, 'A1001')
  await expect(cell(page, '1000:2')).toHaveText('West')
  await page.getByRole('button', { name: 'Undo', exact: true }).click()
  await select(page, 'A2')
  await expect(cell(page, '1:0')).toHaveText('SO-10001')
  await expect(page.getByRole('button', { name: 'Undo', exact: true })).toBeDisabled()
  await page.getByRole('button', { name: 'Redo', exact: true }).click()
  await expect(cell(page, '1:0')).toHaveCount(0)
  const dialog = await open(page)
  await expect(dialog.getByLabel('Filter value 1', { exact: true })).toHaveValue('West')
  await dialog.getByRole('button', { name: 'Cancel' }).click()
  await expect(menu(page)).toBeFocused()
})

test('clear filter preserves manually hidden rows and can be undone', async ({ page }) => {
  await select(page, 'A5')
  await page.getByRole('combobox', { name: 'Row and column visibility' }).selectOption('hide-rows')
  await applyWest(page)
  await expect(cell(page, '4:0')).toHaveCount(0)
  await menu(page).selectOption('clear')
  await expect(page.getByLabel('Filter status')).toContainText('Manually hidden rows are unchanged')
  await select(page, 'A2')
  await expect(cell(page, '1:0')).toHaveText('SO-10001')
  await expect(cell(page, '4:0')).toHaveCount(0)
  await page.getByRole('button', { name: 'Undo', exact: true }).click()
  await expect(cell(page, '1:0')).toHaveCount(0)
  await expect(cell(page, '8:0')).toHaveText('SO-10008')
})

test('edit does not live-filter; reapply hides the changed row and undo restores the snapshot', async ({ page }) => {
  await applyWest(page)
  await select(page, 'C5')
  const input = page.getByRole('textbox', { name: 'Active cell value' })
  await input.fill('East')
  await input.press('Enter')
  await expect(cell(page, '4:2')).toHaveText('East')
  await menu(page).selectOption('reapply')
  await expect(page.getByLabel('Filter status')).toHaveText('751 rows filtered out.')
  await expect(cell(page, '4:2')).toHaveCount(0)
  await page.getByRole('button', { name: 'Undo', exact: true }).click()
  await select(page, 'C5')
  await expect(cell(page, '4:2')).toHaveText('East')
})

test('multiple conditions use AND and numeric range is inclusive', async ({ page }) => {
  await applyWest(page)
  const dialog = await open(page)
  await dialog.getByRole('button', { name: 'Add condition' }).click()
  await dialog.getByLabel('Filter column 2', { exact: true }).selectOption('4')
  await dialog.getByLabel('Filter condition 2', { exact: true }).selectOption('range')
  await dialog.getByLabel('Minimum 2', { exact: true }).fill('8')
  await dialog.getByLabel('Maximum 2', { exact: true }).fill('12')
  await dialog.getByRole('button', { name: 'Apply filter', exact: true }).click()
  await expect(dialog).not.toBeVisible()
  await expect(cell(page, '4:0')).toHaveCount(0)
  await expect(cell(page, '8:4')).toHaveText('8')
  await expect(cell(page, '12:4')).toHaveText('12')
  await expect(cell(page, '16:0')).toHaveCount(0)
})

test('cross-sheet subtotal follows filtering, sheet switch retains rules and cross-sheet undo restores', async ({ page }) => {
  await page.getByRole('tab', { name: 'Summary', exact: true }).click()
  await select(page, 'B3')
  const input = page.getByRole('textbox', { name: 'Active cell value' })
  await input.fill("=SUBTOTAL(3,'Sales Orders'!A2:A1001)")
  await input.press('Enter')
  await expect(cell(page, '2:1')).toHaveText('1000')
  await page.getByRole('tab', { name: 'Sales Orders', exact: true }).click()
  await applyWest(page)
  await page.getByRole('tab', { name: 'Summary', exact: true }).click()
  await select(page, 'B3')
  await expect(cell(page, '2:1')).toHaveText('250')
  await expect(menu(page).locator('option[value="clear"]')).toBeDisabled()
  await page.getByRole('button', { name: 'Undo', exact: true }).click()
  await expect(cell(page, '2:1')).toHaveText('1000')
  await page.getByRole('tab', { name: 'Sales Orders', exact: true }).click()
  await select(page, 'A2')
  await expect(cell(page, '1:0')).toHaveText('SO-10001')
})

test('invalid numeric bounds and cancel preserve data; no-op reapply adds no history', async ({ page }) => {
  const dialog = await open(page)
  await dialog.getByLabel('Filter condition 1', { exact: true }).selectOption('range')
  await dialog.getByLabel('Minimum 1', { exact: true }).fill('20')
  await dialog.getByLabel('Maximum 1', { exact: true }).fill('10')
  await dialog.getByRole('button', { name: 'Apply filter', exact: true }).click()
  await expect(dialog.getByRole('alert')).toContainText('minimum cannot exceed maximum')
  await page.keyboard.press('Escape')
  await expect(dialog).not.toBeVisible()
  await expect(page.getByRole('button', { name: 'Undo', exact: true })).toBeDisabled()
  await applyWest(page)
  await menu(page).selectOption('reapply')
  await expect(menu(page)).toBeEnabled()
  await page.getByRole('button', { name: 'Undo', exact: true }).click()
  await expect(cell(page, '1:0')).toHaveText('SO-10001')
  await expect(page.getByRole('button', { name: 'Undo', exact: true })).toBeDisabled()
})

test('contains is case insensitive by default; match-case can hide every data row and clear recovers', async ({ page }) => {
  let dialog = await open(page)
  await dialog.getByLabel('Filter column 1', { exact: true }).selectOption('2')
  await dialog.getByLabel('Filter condition 1', { exact: true }).selectOption('contains')
  await dialog.getByLabel('Filter value 1', { exact: true }).fill('wEs')
  await dialog.getByRole('button', { name: 'Apply filter', exact: true }).click()
  await expect(page.getByLabel('Filter status')).toHaveText('750 rows filtered out.')
  dialog = await open(page)
  await dialog.getByLabel('Match case').check()
  await dialog.getByRole('button', { name: 'Apply filter', exact: true }).click()
  await expect(page.getByLabel('Filter status')).toHaveText('1000 rows filtered out.')
  await expect(cell(page, '0:0')).toHaveText('Order')
  await expect(page.locator('td[data-cell]:not([data-cell^="0:"])')).toHaveCount(0)
  await menu(page).selectOption('clear')
  await expect(cell(page, '1:0')).toHaveText('SO-10001')
})

test('value list keeps both groups; unhide-all does not remove a filter', async ({ page }) => {
  const dialog = await open(page)
  await dialog.getByLabel('Filter column 1', { exact: true }).selectOption('2')
  await dialog.getByLabel('Filter condition 1', { exact: true }).selectOption('list')
  await dialog.getByLabel('Filter value 1', { exact: true }).fill('North\nWest')
  await dialog.getByRole('button', { name: 'Apply filter', exact: true }).click()
  await expect(page.getByLabel('Filter status')).toHaveText('500 rows filtered out.')
  await page.getByRole('combobox', { name: 'Row and column visibility' }).selectOption('unhide-all')
  await expect(cell(page, '1:2')).toHaveText('North')
  await expect(cell(page, '2:2')).toHaveCount(0)
  await expect(cell(page, '4:2')).toHaveText('West')
  await open(page)
  await expect(page.getByLabel('Filter value 1', { exact: true })).toHaveValue('North\nWest')
})

