import { expect, test, type Page } from '@playwright/test'
import { select } from '../support/clipboard'

const cell = (page: Page, coord: string) => page.locator(`td[data-cell="${coord}"]`)
const panel = (page: Page) => page.getByRole('dialog', { name: 'Find and replace' })
async function open(page: Page) {
  await page.getByRole('button', { name: 'Find and replace', exact: true }).click()
  await panel(page).getByRole('textbox', { name: 'Find what' }).fill('alpha')
}
async function findAll(page: Page, count: number) {
  await panel(page).getByRole('button', { name: 'Find all', exact: true }).click()
  await expect(panel(page).getByText(`Results 1–${count} of ${count}`, { exact: true })).toBeVisible()
}
async function closeWithoutHistory(page: Page) {
  await panel(page).getByRole('button', { name: 'Close', exact: true }).click()
  await expect(panel(page)).toHaveCount(0)
  await expect(page.locator('[data-workbook-grid]')).toBeFocused()
  await expect(page.getByRole('button', { name: 'Undo', exact: true })).toBeDisabled()
  await expect(page.getByRole('button', { name: 'Redo', exact: true })).toBeDisabled()
}
test.beforeEach(async ({ page }) => {
  await page.goto('/e2e/fixtures/plain-sales-orders/')
  await expect(cell(page, '1:0')).toHaveText('SO-10001')
})

for (const width of [1280, 390]) {
  test(`current sheet find excludes matches on another worksheet at ${width}px`, async ({ page }) => {
    await page.setViewportSize({ width, height: 850 })
    await open(page)
    const scope = panel(page).getByRole('combobox', { name: 'Within' })
    await scope.selectOption('workbook')
    await scope.selectOption('sheet')
    await panel(page).getByRole('button', { name: 'Find all', exact: true }).click()
    await expect(panel(page).getByText('No matches found.', { exact: true })).toBeVisible()
    await expect(panel(page).getByRole('region', { name: 'All search results' })).toHaveCount(0)
    await closeWithoutHistory(page)
    await expect(page.getByRole('tab', { name: 'Sales Orders', exact: true })).toHaveAttribute('aria-selected', 'true')
    await expect(cell(page, '1:0')).toHaveText('SO-10001')
    await expect(cell(page, '3:0')).toHaveText('00123')
  })

  test(`original selection find retains its initial rectangle after result navigation at ${width}px`, async ({ page }) => {
    await page.setViewportSize({ width, height: 850 })
    await page.getByRole('tab', { name: 'Summary', exact: true }).click()
    await select(page, 'A85:B85', '84:0')
    await open(page)
    await panel(page).getByRole('combobox', { name: 'Within' }).selectOption('current-selection')
    await findAll(page, 3)
    await expect(panel(page).getByRole('button', { name: 'Go to Summary!C85, match 4', exact: true })).toHaveCount(0)
    await panel(page).getByRole('button', { name: 'Go to Summary!B85, match 3', exact: true }).click()
    await expect(page.getByRole('textbox', { name: 'Name box' })).toHaveValue('B85')
    await panel(page).getByRole('button', { name: 'Find next', exact: true }).click()
    await expect(panel(page).getByText('1 of 3 · Summary!A85', { exact: true })).toBeVisible()
    await closeWithoutHistory(page)
    await expect(cell(page, '84:0')).toHaveText('😀alpha alpha')
    await expect(cell(page, '84:1')).toHaveText('ALPHA')
    await expect(cell(page, '84:2')).toHaveText('5')
    await expect(cell(page, '0:1')).toHaveText('79')
  })

  test(`find match case changes occurrence membership without editing cells at ${width}px`, async ({ page }) => {
    await page.setViewportSize({ width, height: 850 })
    await page.getByRole('tab', { name: 'Summary', exact: true }).click()
    await select(page, 'A85:C85', '84:0')
    await open(page)
    await panel(page).getByRole('combobox', { name: 'Within' }).selectOption('current-selection')
    await panel(page).getByRole('checkbox', { name: 'Match case', exact: true }).check()
    await findAll(page, 3)
    await expect(panel(page).getByRole('button', { name: 'Go to Summary!C85, match 3', exact: true })).toBeVisible()
    await expect(panel(page).getByRole('button', { name: /Go to Summary!B85/ })).toHaveCount(0)
    await panel(page).getByRole('checkbox', { name: 'Match case', exact: true }).uncheck()
    await findAll(page, 4)
    await expect(panel(page).getByRole('button', { name: 'Go to Summary!B85, match 3', exact: true })).toBeVisible()
    await closeWithoutHistory(page)
    await expect(cell(page, '84:0')).toHaveText('😀alpha alpha')
    await expect(cell(page, '84:1')).toHaveText('ALPHA')
    await expect(cell(page, '84:2')).toHaveText('5')
  })
}

for (const width of [1280, 390]) {
  test(`find entire cell excludes substrings inside text and formula source at ${width}px`, async ({ page }) => {
    await page.setViewportSize({ width, height: 850 })
    await page.getByRole('tab', { name: 'Summary', exact: true }).click()
    await select(page, 'A85:C85', '84:0')
    await open(page)
    await panel(page).getByRole('combobox', { name: 'Within' }).selectOption('current-selection')
    await panel(page).getByRole('checkbox', { name: 'Match entire cell', exact: true }).check()
    await findAll(page, 1)
    await expect(panel(page).getByRole('button', { name: 'Go to Summary!B85, match 1', exact: true })).toBeVisible()
    await panel(page).getByRole('checkbox', { name: 'Match entire cell', exact: true }).uncheck()
    await findAll(page, 4)
    await closeWithoutHistory(page)
    await expect(cell(page, '84:0')).toHaveText('😀alpha alpha')
    await expect(cell(page, '84:1')).toHaveText('ALPHA')
    await expect(cell(page, '84:2')).toHaveText('5')
  })

  test(`find wildcards distinguishes star question mark and escaped literal at ${width}px`, async ({ page }) => {
    await page.setViewportSize({ width, height: 850 })
    await page.getByRole('tab', { name: 'Summary', exact: true }).click()
    await select(page, 'A86:C87', '85:0')
    await open(page)
    const query = panel(page).getByRole('textbox', { name: 'Find what' })
    await query.fill('SKU-*')
    await panel(page).getByRole('combobox', { name: 'Within' }).selectOption('current-selection')
    await findAll(page, 1)
    await panel(page).getByRole('checkbox', { name: 'Use wildcards', exact: true }).check()
    await findAll(page, 4)
    await panel(page).getByRole('checkbox', { name: 'Match entire cell', exact: true }).check()
    await query.fill('SKU-?')
    await findAll(page, 2)
    await expect(panel(page).getByRole('button', { name: 'Go to Summary!A87, match 2', exact: true })).toBeVisible()
    await query.fill('SKU-~*')
    await findAll(page, 1)
    await expect(panel(page).getByRole('button', { name: 'Go to Summary!C86, match 1', exact: true })).toBeVisible()
    await closeWithoutHistory(page)
    await expect(cell(page, '85:0')).toHaveText('SKU-100')
    await expect(cell(page, '85:1')).toHaveText('SKU-200')
    await expect(cell(page, '85:2')).toHaveText('SKU-*')
    await expect(cell(page, '86:0')).toHaveText('SKU-😀')
  })

  test(`displayed value find locates a formula result without changing its source at ${width}px`, async ({ page }) => {
    await page.setViewportSize({ width, height: 850 })
    await page.getByRole('tab', { name: 'Summary', exact: true }).click()
    await select(page, 'C85', '84:2')
    await open(page)
    await panel(page).getByRole('textbox', { name: 'Find what' }).fill('5')
    await panel(page).getByRole('combobox', { name: 'Within' }).selectOption('current-selection')
    await panel(page).getByRole('combobox', { name: 'Look in' }).selectOption('values')
    await findAll(page, 1)
    await panel(page).getByRole('button', { name: 'Go to Summary!C85, match 1', exact: true }).click()
    await expect(page.getByRole('textbox', { name: 'Name box' })).toHaveValue('C85')
    await closeWithoutHistory(page)
    await expect(cell(page, '84:2')).toHaveText('5')
    await expect(page.getByRole('textbox', { name: 'Active cell value' })).toHaveValue('=LEN("alpha")')
    await expect(cell(page, '84:1')).toHaveText('ALPHA')
  })

  test(`raw formula find matches source text rather than the displayed result at ${width}px`, async ({ page }) => {
    await page.setViewportSize({ width, height: 850 })
    await page.getByRole('tab', { name: 'Summary', exact: true }).click()
    await select(page, 'C85', '84:2')
    await open(page)
    await panel(page).getByRole('combobox', { name: 'Within' }).selectOption('current-selection')
    await panel(page).getByRole('combobox', { name: 'Look in' }).selectOption('values')
    await panel(page).getByRole('button', { name: 'Find all', exact: true }).click()
    await expect(panel(page).getByText('No matches found.', { exact: true })).toBeVisible()
    await panel(page).getByRole('combobox', { name: 'Look in' }).selectOption('formulas')
    await findAll(page, 1)
    await panel(page).getByRole('button', { name: 'Go to Summary!C85, match 1', exact: true }).click()
    await closeWithoutHistory(page)
    await expect(cell(page, '84:2')).toHaveText('5')
    await expect(page.getByRole('textbox', { name: 'Active cell value' })).toHaveValue('=LEN("alpha")')
    await expect(cell(page, '84:0')).toHaveText('😀alpha alpha')
  })
}
