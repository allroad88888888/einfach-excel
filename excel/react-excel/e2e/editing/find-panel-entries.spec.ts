import { expect, test, type Page } from '@playwright/test'
import { select } from '../support/clipboard'

const cell = (page: Page, coord: string) => page.locator(`td[data-cell="${coord}"]`)
const panel = (page: Page) => page.getByRole('dialog', { name: 'Find and replace' })
test.beforeEach(async ({ page }) => {
  await page.goto('/e2e/fixtures/plain-sales-orders/')
  await expect(cell(page, '1:0')).toHaveText('SO-10001')
  await select(page, 'B3', '2:1')
})

for (const entry of ['toolbar', 'Control+f', 'Meta+f', 'Control+h', 'Meta+h']) for (const width of [1280, 390])
  test(`${entry} opens ${entry.endsWith('+h') ? 'Replace' : 'Find'} with focused input and preserves the selection at ${width}px`, async ({ page }) => {
    await page.setViewportSize({ width, height: 850 })
    if (entry === 'toolbar') await page.getByRole('button', { name: 'Find and replace', exact: true }).click()
    else await page.locator('[data-workbook-grid]').press(entry)
    const dialog = panel(page)
    const tab = entry.endsWith('+h') ? 'Replace' : 'Find'
    await expect(dialog).toBeVisible()
    await expect(dialog.getByRole('textbox', { name: 'Find what' })).toBeFocused()
    await expect(dialog.getByRole('tab', { name: tab, exact: true })).toHaveAttribute('aria-selected', 'true')
    await expect(dialog.getByRole('textbox', { name: 'Replace with' })).toHaveCount(tab === 'Replace' ? 1 : 0)
    await expect(dialog.getByRole('combobox', { name: 'Within' })).toHaveValue('sheet')
    await expect(dialog.getByRole('combobox', { name: 'Look in' })).toHaveValue('formulas')
    await dialog.getByRole('textbox', { name: 'Find what' }).fill('Unsubmitted query')
    await dialog.getByRole('button', { name: 'Close', exact: true }).click()
    await expect(dialog).toHaveCount(0)
    await expect(page.locator('[data-workbook-grid]')).toBeFocused()
    await expect(page.getByRole('textbox', { name: 'Name box' })).toHaveValue('B3')
    await expect(cell(page, '2:1')).toHaveText('Northwind')
    await expect(cell(page, '1:1')).toHaveText('Acme Co.')
    await expect(cell(page, '1:1')).toHaveCSS('font-style', 'italic')
    await expect(page.getByRole('button', { name: 'Undo', exact: true })).toBeDisabled()
    await expect(page.getByRole('button', { name: 'Redo', exact: true })).toBeDisabled()
  })

for (const width of [1280, 390])
  test(`Replace tab click retains the find draft without writing cells at ${width}px`, async ({ page }) => {
    await page.setViewportSize({ width, height: 850 })
    await page.getByRole('button', { name: 'Find and replace', exact: true }).click()
    const dialog = panel(page)
    await dialog.getByRole('textbox', { name: 'Find what' }).fill('Northwind')
    await dialog.getByRole('tab', { name: 'Replace', exact: true }).click()
    await expect(dialog.getByRole('tab', { name: 'Replace', exact: true })).toHaveAttribute('aria-selected', 'true')
    await expect(dialog.getByRole('textbox', { name: 'Find what' })).toHaveValue('Northwind')
    await dialog.getByRole('textbox', { name: 'Replace with' }).fill('Unsubmitted replacement')
    await expect(dialog.getByRole('button', { name: 'Replace current', exact: true })).toBeDisabled()
    await expect(dialog.getByRole('button', { name: 'Replace all', exact: true })).toBeEnabled()
    await dialog.getByRole('button', { name: 'Close', exact: true }).click()
    await expect(dialog).toHaveCount(0)
    await expect(page.getByRole('textbox', { name: 'Name box' })).toHaveValue('B3')
    await expect(cell(page, '2:1')).toHaveText('Northwind')
    await expect(cell(page, '1:1')).toHaveText('Acme Co.')
    await expect(page.getByRole('button', { name: 'Undo', exact: true })).toBeDisabled()
  })

for (const width of [1280, 390])
  test(`Find tab click hides replacement controls without applying the draft at ${width}px`, async ({ page }) => {
    await page.setViewportSize({ width, height: 850 })
    await page.locator('[data-workbook-grid]').press('Control+h')
    const dialog = panel(page)
    await dialog.getByRole('textbox', { name: 'Find what' }).fill('Northwind')
    await dialog.getByRole('textbox', { name: 'Replace with' }).fill('Unsubmitted replacement')
    await dialog.getByRole('tab', { name: 'Find', exact: true }).click()
    await expect(dialog.getByRole('tab', { name: 'Find', exact: true })).toHaveAttribute('aria-selected', 'true')
    await expect(dialog.getByRole('textbox', { name: 'Replace with' })).toHaveCount(0)
    await expect(dialog.getByRole('button', { name: 'Replace all', exact: true })).toHaveCount(0)
    await expect(dialog.getByRole('textbox', { name: 'Find what' })).toHaveValue('Northwind')
    await dialog.getByRole('button', { name: 'Close', exact: true }).click()
    await expect(cell(page, '2:1')).toHaveText('Northwind')
    await expect(cell(page, '1:1')).toHaveText('Acme Co.')
    await expect(page.getByRole('button', { name: 'Undo', exact: true })).toBeDisabled()
  })

for (const action of ['Close', 'Escape']) for (const width of [1280, 390])
  test(`${action} find panel keeps unapplied replacement and existing redo intact at ${width}px`, async ({ page }) => {
    await page.setViewportSize({ width, height: 850 })
    const input = page.getByRole('textbox', { name: 'Active cell value' })
    await input.fill('Remember redo'); await input.press('Enter')
    await expect(cell(page, '2:1')).toHaveText('Remember redo')
    await page.getByRole('button', { name: 'Undo', exact: true }).click()
    await select(page, 'B3', '2:1')
    await page.locator('[data-workbook-grid]').press('Control+h')
    const dialog = panel(page)
    await dialog.getByRole('textbox', { name: 'Find what' }).fill('Northwind')
    await dialog.getByRole('textbox', { name: 'Replace with' }).fill('Unsubmitted replacement')
    if (action === 'Close') await dialog.getByRole('button', { name: 'Close', exact: true }).click()
    else await page.keyboard.press('Escape')
    await expect(dialog).toHaveCount(0)
    await expect(page.locator('[data-workbook-grid]')).toBeFocused()
    await expect(page.getByRole('textbox', { name: 'Name box' })).toHaveValue('B3')
    await expect(cell(page, '2:1')).toHaveText('Northwind')
    await expect(cell(page, '1:1')).toHaveText('Acme Co.')
    await expect(page.getByRole('button', { name: 'Undo', exact: true })).toBeDisabled()
    await page.getByRole('button', { name: 'Redo', exact: true }).click()
    await expect(cell(page, '2:1')).toHaveText('Remember redo')
    await page.getByRole('button', { name: 'Undo', exact: true }).click()
    await expect(cell(page, '2:1')).toHaveText('Northwind')
  })
