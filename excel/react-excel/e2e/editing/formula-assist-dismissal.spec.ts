import { expect, test, type Page } from '@playwright/test'
import { select } from '../support/clipboard'

const cell = (page: Page, coord: string) => page.locator(`td[data-cell="${coord}"]`)

for (const width of [1280, 390]) for (const source of ['cell', 'formula'] as const)
  test(`${source} Escape dismisses suggestions before cancelling the draft at ${width}px`, async ({ page }) => {
    await page.setViewportSize({ width, height: 850 })
    await page.goto('/e2e/fixtures/plain-sales-orders/')
    await expect(cell(page, '1:0')).toHaveText('SO-10001')
    await select(page, 'E2', '1:4')
    const bar = page.getByRole('textbox', { name: 'Active cell value', exact: true })
    await bar.fill('3')
    await bar.press('Enter')
    await expect(cell(page, '1:4')).toHaveText('3')
    await page.getByRole('button', { name: 'Undo', exact: true }).click()
    await expect(cell(page, '1:4')).toHaveText('1')
    await select(page, 'B3', '2:1')
    if (source === 'cell') await cell(page, '2:1').dblclick()
    const input = page.getByRole('textbox', {
      name: source === 'cell' ? 'Cell editor' : 'Active cell value', exact: true,
    })
    await input.fill('=SU')
    const list = page.getByRole('listbox', { name: 'Formula functions' })
    await expect(list).toBeVisible()
    await page.keyboard.press('Escape')
    await expect(list).toHaveCount(0)
    await expect(input).toHaveValue('=SU')
    await expect(input).toBeFocused()
    await expect(cell(page, '2:1')).toHaveText('Northwind')
    await expect(page.getByRole('button', { name: 'Undo', exact: true })).toBeDisabled()
    await page.keyboard.press('Escape')
    if (source === 'cell') await expect(input).toHaveCount(0)
    else await expect(input).toHaveValue('Northwind')
    await expect(page.locator('[data-workbook-grid]')).toBeFocused()
    await expect(page.getByRole('textbox', { name: 'Name box' })).toHaveValue('B3')
    if (source === 'cell') await cell(page, '2:1').dblclick()
    await input.fill('=SU')
    await expect(list).toBeVisible()
    await input.fill('="SUM"')
    await expect(list).toHaveCount(0)
    await input.press('Escape')
    await expect(cell(page, '2:1')).toHaveText('Northwind')
    await page.getByRole('button', { name: 'Redo', exact: true }).click()
    await select(page, 'G2', '1:6')
    await expect(cell(page, '1:6')).toHaveText('237')
    await select(page, 'A2', '1:0')
    await expect(cell(page, '1:0')).toHaveCSS('font-weight', '700')
    await expect(cell(page, '1:1')).toHaveCSS('font-style', 'italic')
  })
