import { expect, test, type Page } from '@playwright/test'
import { select } from '../support/clipboard'

const cell = (page: Page, coord: string) => page.locator(`td[data-cell="${coord}"]`)

for (const width of [1280, 390]) for (const source of ['cell', 'formula'] as const)
  test(`${source} F4 cycles all reference locks before one native commit at ${width}px`, async ({ page }) => {
    await page.setViewportSize({ width, height: 850 })
    await page.goto('/e2e/fixtures/plain-sales-orders/')
    await expect(cell(page, '1:0')).toHaveText('SO-10001')
    await select(page, 'B3', '2:1')
    if (source === 'cell') await cell(page, '2:1').dblclick()
    const input = page.getByRole('textbox', {
      name: source === 'cell' ? 'Cell editor' : 'Active cell value', exact: true,
    })
    await input.fill('=E2')
    for (const draft of ['=$E$2', '=E$2', '=$E2', '=E2', '=$E$2']) {
      await page.keyboard.press('F4')
      await expect(input).toHaveValue(draft)
      await expect(input).toBeFocused()
      expect(await input.evaluate((node: HTMLTextAreaElement) =>
        [node.selectionStart, node.selectionEnd])).toEqual([draft.length, draft.length])
      await expect(page.getByRole('textbox', { name: 'Name box' })).toHaveValue('B3')
      await expect(cell(page, '2:1')).toHaveText('Northwind')
      await expect(page.getByRole('button', { name: 'Undo', exact: true })).toBeDisabled()
    }
    await page.keyboard.press('Enter')
    await expect(cell(page, '2:1')).toHaveText('1')
    await expect(page.locator('[data-workbook-grid]')).toBeFocused()
    await select(page, 'B3', '2:1')
    const bar = page.getByRole('textbox', { name: 'Active cell value', exact: true })
    await expect(bar).toHaveValue('=$E$2')
    await expect(cell(page, '2:0')).toHaveText('SO-10002')
    await expect(cell(page, '2:2')).toHaveText('East')
    await page.getByRole('button', { name: 'Undo', exact: true }).click()
    await expect(cell(page, '2:1')).toHaveText('Northwind')
    await expect(page.getByRole('button', { name: 'Undo', exact: true })).toBeDisabled()
    await page.getByRole('button', { name: 'Redo', exact: true }).click()
    await expect(cell(page, '2:1')).toHaveText('1')
    await select(page, 'E2', '1:4')
    await bar.fill('3')
    await bar.press('Enter')
    await select(page, 'B3', '2:1')
    await expect(cell(page, '2:1')).toHaveText('3')
    await expect(bar).toHaveValue('=$E$2')
    await select(page, 'A2', '1:0')
    await expect(cell(page, '1:0')).toHaveCSS('font-weight', '700')
    await expect(cell(page, '1:1')).toHaveCSS('font-style', 'italic')
  })

for (const width of [1280, 390])
  test(`formula F2 changes caret mode without duplicating the picked reference at ${width}px`, async ({ page }) => {
    await page.setViewportSize({ width, height: 850 })
    await page.goto('/e2e/fixtures/plain-sales-orders/')
    await expect(cell(page, '1:0')).toHaveText('SO-10001')
    await select(page, 'G2', '1:6')
    const input = page.getByRole('textbox', { name: 'Active cell value', exact: true })
    await input.fill('=SUM(')
    await input.press('F2')
    await input.press('ArrowLeft')
    await expect(input).toHaveValue('=SUM(')
    expect(await input.evaluate((node: HTMLTextAreaElement) => node.selectionStart)).toBe(4)
    await input.press('ArrowRight')
    await input.press('F2')
    await input.press('ArrowLeft')
    await input.press('ArrowLeft')
    await expect(input).toHaveValue('=SUM(E2')
    await input.press('F2')
    await input.press('ArrowLeft')
    expect(await input.evaluate((node: HTMLTextAreaElement) => node.selectionStart)).toBe(6)
    await input.press('F2')
    await input.press('ArrowDown')
    await expect(input).toHaveValue('=SUM(E3')
    await expect(input).toBeFocused()
    await expect(page.getByRole('textbox', { name: 'Name box' })).toHaveValue('G2')
    await expect(cell(page, '1:6')).toHaveText('79')
    await expect(page.getByRole('button', { name: 'Undo', exact: true })).toBeDisabled()
    await input.pressSequentially(')')
    await input.press('Enter')
    await expect(cell(page, '1:6')).toHaveText('2')
    await expect(input).toHaveValue('=SUM(E3)')
    await expect(cell(page, '1:6')).toHaveCSS('font-family', 'Georgia')
    await expect(page.locator('[data-workbook-grid]')).toBeFocused()
    await page.getByRole('button', { name: 'Undo', exact: true }).click()
    await expect(cell(page, '1:6')).toHaveText('79')
    await expect(input).toHaveValue('=E2*F2')
    await expect(page.getByRole('button', { name: 'Undo', exact: true })).toBeDisabled()
    await page.getByRole('button', { name: 'Redo', exact: true }).click()
    await expect(cell(page, '1:6')).toHaveText('2')
    await select(page, 'E2', '1:4')
    await expect(cell(page, '1:4')).toHaveText('1')
    await expect(cell(page, '1:5')).toHaveText('79')
  })
