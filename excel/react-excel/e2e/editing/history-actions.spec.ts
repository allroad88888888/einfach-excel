import { expect, test, type Page } from '@playwright/test'
import { select } from '../support/clipboard'

const cell = (page: Page, coord: string) => page.locator(`td[data-cell="${coord}"]`)
const button = (page: Page, name: string) => page.getByRole('button', { name, exact: true })
async function originalNeighbors(page: Page) {
  await expect(cell(page, '1:1')).toHaveText('Acme Co.')
  await expect(cell(page, '1:1')).toHaveCSS('font-style', 'italic')
  await expect(cell(page, '2:1')).toHaveText('Northwind')
  await expect(cell(page, '1:0')).toHaveText('SO-10001')
  await expect(cell(page, '1:0')).toHaveCSS('font-weight', '700')
}
test.beforeEach(async ({ page }) => {
  await page.goto('/e2e/fixtures/plain-sales-orders/')
  await expect(cell(page, '1:0')).toHaveText('SO-10001')
  await select(page, 'E2', '1:4')
  const input = page.getByRole('textbox', { name: 'Active cell value' })
  await input.fill('10'); await input.press('Enter')
  await expect(cell(page, '1:6')).toHaveText('790')
})

for (const width of [1280, 390]) {
  test(`Undo button restores input and cross-sheet formulas without switching tabs at ${width}px`, async ({ page }) => {
    await page.setViewportSize({ width, height: 850 })
    await page.getByRole('tab', { name: 'Summary', exact: true }).click()
    await expect(cell(page, '0:1')).toHaveText('790')
    await button(page, 'Undo').click()
    await expect(cell(page, '0:1')).toHaveText('79')
    await expect(page.getByRole('tab', { name: 'Summary', exact: true })).toHaveAttribute('aria-selected', 'true')
    await expect(button(page, 'Undo')).toBeDisabled()
    await expect(button(page, 'Redo')).toBeEnabled()
    await page.getByRole('tab', { name: 'Sales Orders', exact: true }).click()
    await expect(cell(page, '1:4')).toHaveText('1')
    await expect(cell(page, '1:6')).toHaveText('79')
    await originalNeighbors(page)
  })

  test(`Redo button reapplies input and cross-sheet formulas without switching tabs at ${width}px`, async ({ page }) => {
    await page.setViewportSize({ width, height: 850 })
    await button(page, 'Undo').click()
    await expect(cell(page, '1:6')).toHaveText('79')
    await page.getByRole('tab', { name: 'Summary', exact: true }).click()
    await expect(cell(page, '0:1')).toHaveText('79')
    await button(page, 'Redo').click()
    await expect(cell(page, '0:1')).toHaveText('790')
    await expect(page.getByRole('tab', { name: 'Summary', exact: true })).toHaveAttribute('aria-selected', 'true')
    await expect(button(page, 'Redo')).toBeDisabled()
    await page.getByRole('tab', { name: 'Sales Orders', exact: true }).click()
    await expect(cell(page, '1:4')).toHaveText('10')
    await expect(cell(page, '1:6')).toHaveText('790')
    await originalNeighbors(page)
  })

  test(`Recent operations lists native addresses and undone records without changing history at ${width}px`, async ({ page }) => {
    await page.setViewportSize({ width, height: 850 })
    await select(page, 'B3', '2:1')
    await button(page, 'Bold').click()
    await expect(cell(page, '2:1')).toHaveCSS('font-weight', '700')
    await button(page, 'Undo').click()
    await expect(cell(page, '2:1')).toHaveCSS('font-weight', '400')
    await button(page, 'Recent operations').click()
    const dialog = page.getByRole('dialog', { name: 'Recent operations' })
    await expect(dialog).toContainText('1 undo · 1 redo')
    await expect(dialog.getByRole('listitem')).toHaveCount(2)
    await expect(dialog.getByRole('listitem').nth(0)).toContainText('Sales Orders · E2:E2')
    await expect(dialog.getByRole('listitem').nth(1)).toContainText('Sales Orders · B3:B3 · Undone')
    await expect(button(page, 'Close history')).toBeFocused()
    await button(page, 'Close history').click()
    await expect(button(page, 'Recent operations')).toBeFocused()
    await button(page, 'Redo').click()
    await expect(cell(page, '2:1')).toHaveCSS('font-weight', '700')
    await expect(cell(page, '1:6')).toHaveText('790')
    await originalNeighbors(page)
  })
}

for (const action of ['Close history', 'Escape']) for (const width of [1280, 390])
  test(`${action} closes native history without applying or losing redo at ${width}px`, async ({ page }) => {
    await page.setViewportSize({ width, height: 850 })
    await button(page, 'Undo').click()
    await expect(cell(page, '1:6')).toHaveText('79')
    await button(page, 'Recent operations').click()
    const dialog = page.getByRole('dialog', { name: 'Recent operations' })
    await expect(dialog).toContainText('0 undo · 1 redo')
    if (action === 'Escape') await page.keyboard.press('Escape')
    else await button(page, 'Close history').click()
    await expect(dialog).toHaveCount(0)
    await expect(button(page, 'Recent operations')).toBeFocused()
    await expect(button(page, 'Undo')).toBeDisabled()
    await expect(cell(page, '1:6')).toHaveText('79')
    await button(page, 'Redo').click()
    await expect(cell(page, '1:4')).toHaveText('10')
    await expect(cell(page, '1:6')).toHaveText('790')
    await originalNeighbors(page)
  })
