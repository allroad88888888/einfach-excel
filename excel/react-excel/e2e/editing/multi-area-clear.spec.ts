import { expect, test, type Page } from '@playwright/test'

const button = (page: Page, name: string) => page.getByRole('button', { name, exact: true })
const cell = (page: Page, coord: string) => page.locator(`td[data-cell="${coord}"]`)
async function go(page: Page, range: string) {
  const name = page.getByRole('textbox', { name: 'Name box' })
  await name.fill(range)
  await name.press('Enter')
  await expect(name).toHaveValue(range)
  await expect(button(page, 'Go to special')).toBeEnabled()
}
async function locate(page: Page, kind: string) {
  await button(page, 'Go to special').click()
  await button(page, kind).click()
  await expect(page.getByRole('dialog', { name: 'Go to special' })).toBeHidden()
}
test.beforeEach(async ({ page }) => {
  await page.goto('/')
  await expect(cell(page, '1:0')).toHaveText('SO-10001')
  await page.getByRole('tab', { name: 'Summary', exact: true }).click()
  await expect(cell(page, '1:1')).toHaveText('Acme Co.')
})

for (const mode of ['Clear contents', 'Clear formatting', 'Clear all']) {
  test(`${mode} affects every located area, keeps gaps and undoes once`, async ({ page }) => {
    await go(page, 'A93:F94')
    await expect(cell(page, '92:0')).toHaveCSS('font-style', 'italic')
    await expect(cell(page, '92:2')).toHaveCSS('font-weight', '700')
    await expect(cell(page, '92:4')).toHaveCSS('text-decoration-line', 'underline')
    await locate(page, 'Constants')
    await expect(page.getByRole('status', { name: 'Multi-area selection' }))
      .toContainText('Clear and formatting apply to all areas')
    await button(page, mode).click()
    const contents = mode !== 'Clear formatting'
    const formats = mode !== 'Clear contents'
    await expect(cell(page, '92:0')).toHaveText(contents ? '' : '10')
    await expect(cell(page, '92:4')).toHaveText(contents ? '' : '30')
    await expect(cell(page, '92:5')).toHaveText(contents ? '' : 'TRUE')
    await expect(cell(page, '92:0')).toHaveCSS('font-style', formats ? 'normal' : 'italic')
    await expect(cell(page, '92:2')).toHaveCSS('font-weight', formats ? '400' : '700')
    await expect(cell(page, '92:4')).toHaveCSS('text-decoration-line', formats ? 'none' : 'underline')
    // 间隙 D93 的公式会随 A93 重算，但不能被清除或丢掉原始黄色底色。
    await expect(cell(page, '92:3')).toHaveText(contents ? '0' : '20')
    await expect(cell(page, '92:3')).toHaveCSS('background-color', 'rgb(255, 242, 204)')
    await expect(cell(page, '93:2')).toHaveText('#DIV/0!')
    await button(page, 'Undo').click()
    await expect(button(page, 'Undo')).toBeDisabled()
    await expect(cell(page, '92:0')).toHaveText('10')
    await expect(cell(page, '92:4')).toHaveText('30')
    await expect(cell(page, '92:0')).toHaveCSS('font-style', 'italic')
    await expect(cell(page, '92:2')).toHaveCSS('font-weight', '700')
    await button(page, 'Redo').click()
    await expect(button(page, 'Redo')).toBeDisabled()
    await expect(cell(page, '92:0')).toHaveText(contents ? '' : '10')
    await expect(cell(page, '92:4')).toHaveCSS('text-decoration-line', formats ? 'none' : 'underline')
  })
}

test('Delete clears all located formula areas, including offscreen and frozen cells', async ({ page }) => {
  await go(page, 'H100')
  await locate(page, 'Formulas')
  await page.locator('[data-workbook-grid="true"]').press('Delete')
  await expect(button(page, 'Undo')).toBeEnabled()
  await expect(cell(page, '0:1')).toHaveText('')
  await page.locator('.sheet-scroll').evaluate((node) => { node.scrollTop = node.scrollHeight })
  await expect(cell(page, '93:1')).toHaveText('')
  await expect(cell(page, '93:2')).toHaveText('')
  await expect(cell(page, '92:0')).toHaveText('10')
  await button(page, 'Undo').click()
  await expect(button(page, 'Undo')).toBeDisabled()
  await go(page, 'C94')
  await expect(page.getByRole('textbox', { name: 'Active cell value' })).toHaveValue('=1/0')
  await go(page, 'B1')
  await expect(page.getByRole('textbox', { name: 'Active cell value' }))
    .toHaveValue("='Sales Orders'!G2")
})

for (const width of [1280, 390]) test(`native spill rejection is visible and retryable at ${width}px`, async ({ page }) => {
  const errors: string[] = []
  page.on('pageerror', (error) => errors.push(error.message))
  await page.setViewportSize({ width, height: 850 })
  await go(page, 'F58:H59')
  await locate(page, 'Formulas')
  await button(page, 'Clear all').click()
  const error = page.getByRole('alert', { name: 'Selection change error' })
  await expect(error).toContainText('Include its formula cell')
  await expect(cell(page, '57:5')).toHaveText('20')
  await page.locator('.sheet-scroll').evaluate((node) => { node.scrollLeft = node.scrollWidth })
  await expect(cell(page, '57:7')).toHaveText('2')
  await expect(button(page, 'Undo')).toBeDisabled()
  const bounds = (await error.boundingBox())!
  expect(bounds.x).toBeGreaterThanOrEqual(0)
  expect(bounds.x + bounds.width).toBeLessThanOrEqual(width)
  expect(await error.evaluate((node) => node.scrollWidth <= node.clientWidth)).toBe(true)
  await page.screenshot({ path: `/tmp/excel-multi-clear-error-${width}.png` })
  await go(page, 'F57:H59')
  await locate(page, 'Formulas')
  await button(page, 'Clear contents').click()
  await expect(error).toBeHidden()
  await expect(cell(page, '56:5')).toHaveText('')
  await page.locator('.sheet-scroll').evaluate((node) => { node.scrollLeft = node.scrollWidth })
  await expect(cell(page, '56:7')).toHaveText('')
  await button(page, 'Undo').click()
  await expect(button(page, 'Undo')).toBeDisabled()
  await go(page, 'A93:F94')
  await locate(page, 'Constants')
  await button(page, 'Clear formatting').focus()
  await page.keyboard.press('Enter')
  await expect(cell(page, '92:0')).toHaveCSS('font-style', 'normal')
  await page.screenshot({ path: `/tmp/excel-multi-clear-success-${width}.png` })
  expect(errors).toEqual([])
})
