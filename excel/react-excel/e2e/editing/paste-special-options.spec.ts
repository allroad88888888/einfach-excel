import { expect, test, type Page } from '@playwright/test'
import { select, copy } from '../support/clipboard'

const cell = (page: Page, coord: string) => page.locator(`td[data-cell="${coord}"]`)

// 单独验证弹窗转置入口，不能以“运算＋转置＋跳过空白”的综合用例替代。
for (const width of [1280, 390])
  test(`transpose checkbox rotates the native paste without touching neighbors at ${width}px`, async ({ page, context }) => {
    await page.setViewportSize({ width, height: 850 })
    await context.grantPermissions(['clipboard-read', 'clipboard-write'])
    await page.goto('/e2e/fixtures/plain-sales-orders/')
    await expect(cell(page, '1:0')).toHaveText('SO-10001')
    await select(page, 'E4:F4', '3:4')
    await copy(page)
    await select(page, 'E10', '9:4')
    await page.getByRole('button', { name: 'Paste special', exact: true }).click()
    const dialog = page.getByRole('dialog', { name: 'Paste special', exact: true })
    await dialog.getByRole('combobox', { name: 'Paste content', exact: true }).selectOption('values')
    await dialog.getByRole('checkbox', { name: 'Transpose', exact: true }).check()
    await dialog.getByRole('button', { name: 'Apply paste', exact: true }).click()
    await expect(dialog).toHaveCount(0)
    for (const [coord, value] of [['9:4', '3'], ['10:4', '149'], ['9:5', '149'], ['10:5', '119'],
      ['3:4', '3'], ['3:5', '149'], ['9:6', '447'], ['10:6', '17731']] as const)
      await expect(cell(page, coord)).toHaveText(value)
    await page.getByRole('button', { name: 'Undo', exact: true }).click()
    await expect(cell(page, '9:4')).toHaveText('9')
    await expect(cell(page, '10:4')).toHaveText('10')
    await expect(cell(page, '9:6')).toHaveText('1341')
    await expect(cell(page, '10:6')).toHaveText('1190')
    await expect(page.getByRole('button', { name: 'Undo', exact: true })).toBeDisabled()
    await page.getByRole('button', { name: 'Redo', exact: true }).click()
    await expect(cell(page, '9:4')).toHaveText('3')
    await expect(cell(page, '10:4')).toHaveText('149')
  })

for (const width of [1280, 390])
  test(`skip blanks checkbox preserves a formula but writes zero and false at ${width}px`, async ({ page, context }) => {
    await page.setViewportSize({ width, height: 850 })
    await context.grantPermissions(['clipboard-read', 'clipboard-write'])
    await page.goto('/e2e/fixtures/plain-sales-orders/')
    await expect(cell(page, '1:0')).toHaveText('SO-10001')
    await select(page, 'G9', '8:6')
    const status = await cell(page, '8:7').textContent()
    const owner = await cell(page, '8:8').textContent()
    const originalFont = await cell(page, '8:6').evaluate(node => getComputedStyle(node).fontFamily)
    await page.evaluate(() => navigator.clipboard.writeText('\t0\tfalse'))
    await page.getByRole('button', { name: 'Paste special', exact: true }).click()
    const dialog = page.getByRole('dialog', { name: 'Paste special', exact: true })
    await dialog.getByRole('combobox', { name: 'Paste content', exact: true }).selectOption('values')
    await dialog.getByRole('checkbox', { name: 'Skip blanks', exact: true }).check()
    await dialog.getByRole('button', { name: 'Apply paste', exact: true }).click()
    await expect(dialog).toHaveCount(0)
    await expect(cell(page, '8:6')).toHaveText('2,632.00')
    await expect(cell(page, '8:6')).toHaveCSS('font-family', originalFont)
    await expect(page.getByRole('textbox', { name: 'Active cell value', exact: true })).toHaveValue('=E9*F9')
    await expect(cell(page, '8:7')).toHaveText('0')
    await expect(cell(page, '8:8')).toHaveText(/false/i)
    await expect(cell(page, '8:5')).toHaveText('329')
    await page.getByRole('button', { name: 'Undo', exact: true }).click()
    await expect(cell(page, '8:7')).toHaveText(status ?? '')
    await expect(cell(page, '8:8')).toHaveText(owner ?? '')
    await expect(cell(page, '8:6')).toHaveText('2,632.00')
    await expect(page.getByRole('button', { name: 'Undo', exact: true })).toBeDisabled()
    await page.getByRole('button', { name: 'Redo', exact: true }).click()
    await expect(cell(page, '8:7')).toHaveText('0')
    await expect(cell(page, '8:8')).toHaveText(/false/i)
    await expect(cell(page, '8:6')).toHaveText('2,632.00')
  })
