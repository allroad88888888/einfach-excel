import { expect, test, type Page } from '@playwright/test'
import { select, copy } from '../support/clipboard'

const cell = (page: Page, coord: string) => page.locator(`td[data-cell="${coord}"]`)

// 选择性粘贴的草稿会话不写原生数据；每次重新打开都必须从默认选项开始。
for (const width of [1280, 390]) for (const action of ['Open', 'Cancel', 'Escape', 'Tab', 'Shift+Tab'] as const)
  test(`${action} paste special preserves target and resets choices without losing redo at ${width}px`, async ({ page, context }, info) => {
    await page.setViewportSize({ width, height: 850 })
    await context.grantPermissions(['clipboard-read', 'clipboard-write'])
    await page.goto('/e2e/fixtures/plain-sales-orders/')
    await expect(cell(page, '1:0')).toHaveText('SO-10001')
    await select(page, 'H2', '1:7')
    const bar = page.getByRole('textbox', { name: 'Active cell value', exact: true })
    const undo = page.getByRole('button', { name: 'Undo', exact: true })
    await bar.fill('Keep paste redo')
    await bar.press('Enter')
    await expect(cell(page, '1:7')).toHaveText('Keep paste redo')
    await undo.click()
    // 历史操作会使原生剪贴板失效，必须在历史准备完成后走真实 Copy。
    await select(page, 'B2', '1:1')
    await copy(page)
    await select(page, 'B3', '2:1')
    const opener = page.getByRole('button', { name: 'Paste special', exact: true })
    await opener.click()
    const dialog = page.getByRole('dialog', { name: 'Paste special', exact: true })
    const content = dialog.getByRole('combobox', { name: 'Paste content', exact: true })
    const operation = dialog.getByRole('combobox', { name: 'Operation', exact: true })
    const transpose = dialog.getByRole('checkbox', { name: 'Transpose', exact: true })
    const blanks = dialog.getByRole('checkbox', { name: 'Skip blanks', exact: true })
    await expect(content).toBeFocused()
    await expect(content).toHaveValue('all')
    await expect(operation).toHaveValue('none')
    await expect(transpose).not.toBeChecked()
    await expect(blanks).not.toBeChecked()
    if (action !== 'Open') {
      await content.selectOption('values')
      await operation.selectOption('multiply')
      await transpose.check()
      await blanks.check()
    } else {
      await expect(dialog).toBeInViewport()
      expect(await dialog.evaluate(node => node.scrollWidth <= node.clientWidth)).toBe(true)
      await page.screenshot({ path: info.outputPath(`paste-session-${width}.png`) })
    }
    if (action === 'Tab' || action === 'Shift+Tab') {
      const last = dialog.getByRole('button', { name: 'Apply paste', exact: true })
      await (action === 'Tab' ? last : content).focus()
      await page.keyboard.press(action)
      await expect(action === 'Tab' ? content : last).toBeFocused()
    }
    if (action === 'Escape') await page.keyboard.press('Escape')
    else await dialog.getByRole('button', { name: 'Cancel', exact: true }).click()
    await expect(dialog).toHaveCount(0)
    await expect(opener).toBeFocused()
    await expect(page.getByRole('textbox', { name: 'Name box' })).toHaveValue('B3')
    await expect(cell(page, '2:1')).toHaveText('Northwind')
    await expect(cell(page, '2:1')).toHaveCSS('font-style', 'normal')
    await expect(cell(page, '1:1')).toHaveText('Acme Co.')
    await expect(cell(page, '1:1')).toHaveCSS('font-style', 'italic')
    await expect(cell(page, '2:2')).toHaveText('East')
    await expect(undo).toBeDisabled()
    await opener.click()
    await expect(content).toHaveValue('all')
    await expect(operation).toHaveValue('none')
    await expect(transpose).not.toBeChecked()
    await expect(blanks).not.toBeChecked()
    await dialog.getByRole('button', { name: 'Cancel', exact: true }).click()
    await page.getByRole('button', { name: 'Redo', exact: true }).click()
    await select(page, 'H2', '1:7')
    await expect(cell(page, '1:7')).toHaveText('Keep paste redo')
    await select(page, 'A2', '1:0')
    await expect(cell(page, '1:0')).toHaveCSS('font-weight', '700')
  })
