import { expect, test } from '@playwright/test'
import { select } from '../support/clipboard'

for (const width of [1280, 390]) for (const action of ['Open', 'Tab', 'Shift+Tab'])
  test(`${action} custom sort retains draft data and native redo at ${width}px`, async ({ page }, info) => {
    await page.setViewportSize({ width, height: 850 })
    await page.goto('/e2e/fixtures/plain-sales-orders/')
    const cell = (coord: string) => page.locator(`td[data-cell="${coord}"]`)
    const button = (name: string) => page.getByRole('button', { name, exact: true })
    await expect(cell('1:0')).toHaveText('SO-10001')
    await page.getByRole('tab', { name: 'Summary', exact: true }).click()
    await select(page, 'H94', '93:7')
    const bar = page.getByRole('textbox', { name: 'Active cell value', exact: true })
    await bar.fill('sort redo')
    await bar.press('Enter')
    await expect(cell('93:7')).toHaveText('sort redo')
    await button('Undo').click()
    await select(page, 'D32:F37', '31:3')
    const menu = page.getByRole('combobox', { name: 'Sort selected range', exact: true })
    await menu.selectOption('custom')
    const dialog = page.getByRole('dialog', { name: 'Custom sort', exact: true })
    const first = dialog.getByRole('checkbox', { name: 'First row is a header', exact: true })
    const last = dialog.getByRole('button', { name: 'Cancel', exact: true })
    await expect(first).toBeFocused()
    await expect(first).not.toBeChecked()
    await expect(dialog.getByRole('combobox', { name: 'Sort column 1', exact: true })).toHaveValue('3')
    if (action === 'Open') {
      expect(await dialog.evaluate(node => node.scrollWidth <= node.clientWidth)).toBe(true)
      await page.screenshot({ path: info.outputPath(`sort-open-${width}.png`) })
    } else {
      await first.check()
      await (action === 'Tab' ? last : first).focus()
      await page.keyboard.press(action)
      await expect(action === 'Tab' ? first : last).toBeFocused()
      await expect(first).toBeChecked()
    }
    await last.click()
    await expect(dialog).toHaveCount(0)
    await expect(menu).toBeFocused()
    await expect(page.getByRole('textbox', { name: 'Name box' })).toHaveValue('D32:F37')
    await expect(cell('31:3')).toHaveText('Key')
    await expect(cell('31:3')).toHaveCSS('font-weight', '700')
    await expect(cell('32:3')).toHaveText('Maple')
    await expect(cell('32:5')).toHaveText('M1')
    await expect(cell('32:5')).toHaveCSS('font-style', 'italic')
    await expect(cell('36:5')).toHaveText('P1')
    await expect(button('Undo')).toBeDisabled()
    await button('Redo').click()
    await select(page, 'H94', '93:7')
    await expect(cell('93:7')).toHaveText('sort redo')
  })
