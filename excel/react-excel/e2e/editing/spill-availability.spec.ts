import { expect, test, type Page } from '@playwright/test'
import { select } from '../support/clipboard'

const cell = (page: Page, coord: string) => page.locator(`td[data-cell="${coord}"]`)
const button = (page: Page, name: string) => page.getByRole('button', { name, exact: true })
const dialog = (page: Page) => page.getByRole('dialog', { name: 'Spill details' })
test.beforeEach(async ({ page }) => {
  await page.goto('/')
  await expect(cell(page, '1:0')).toHaveText('SO-10001')
  await page.getByRole('tab', { name: 'Summary', exact: true }).click()
  await select(page, 'B2', '1:1')
})

for (const width of [1280, 390]) {
  test(`ordinary cell spill details never fabricates navigation at ${width}px`, async ({ page }) => {
    await page.setViewportSize({ width, height: 850 })
    await button(page, 'Spill details').click()
    await expect(dialog(page)).toContainText('This cell is not part of a spilled array.')
    for (const name of ['Select spill range', 'Go to formula cell', 'Select blocking cell'])
      await expect(button(page, name)).toHaveCount(0)
    await button(page, 'Close').click()
    await expect(page.locator('[data-workbook-grid]')).toBeFocused()
    await expect(page.getByRole('textbox', { name: 'Name box' })).toHaveValue('B2')
    await expect(cell(page, '1:1')).toHaveText('Acme Co.')
    await expect(cell(page, '0:1')).toHaveText('79')
    await expect(button(page, 'Undo')).toBeDisabled()
  })

  test(`editing draft disables spill details and cancellation restores entry at ${width}px`, async ({ page }) => {
    await page.setViewportSize({ width, height: 850 })
    const input = page.getByRole('textbox', { name: 'Active cell value' })
    await input.fill('=SUM(')
    await expect(button(page, 'Spill details')).toBeDisabled()
    await expect(input).toHaveValue('=SUM(')
    await expect(dialog(page)).toHaveCount(0)
    await input.press('Escape')
    await expect(input).toHaveValue("='Sales Orders'!B2")
    await button(page, 'Spill details').click()
    await expect(dialog(page)).toContainText('This cell is not part of a spilled array.')
    await button(page, 'Close').click()
    await expect(cell(page, '1:1')).toHaveText('Acme Co.')
    await expect(cell(page, '0:1')).toHaveText('79')
    await expect(button(page, 'Undo')).toBeDisabled()
  })

  test(`outside canvas spill refuses clamping and still allows valid anchor navigation at ${width}px`, async ({ page }) => {
    await page.setViewportSize({ width, height: 850 })
    await select(page, 'H99', '98:7')
    const input = page.getByRole('textbox', { name: 'Active cell value' })
    await input.fill('=SEQUENCE(3)'); await input.press('Enter')
    await expect(cell(page, '98:7')).toHaveText('1')
    await select(page, 'H99', '98:7')
    await button(page, 'Spill details').click()
    await expect(dialog(page)).toContainText('Spill range: H99:H101')
    await button(page, 'Select spill range').click()
    await expect(dialog(page).getByRole('alert')).toContainText('outside the current worksheet canvas')
    await expect(page.getByRole('textbox', { name: 'Name box' })).toHaveValue('H99')
    await button(page, 'Go to formula cell').click()
    await expect(dialog(page)).toHaveCount(0)
    await expect(input).toHaveValue('=SEQUENCE(3)')
    await expect(cell(page, '99:7')).toHaveText('2')
    await button(page, 'Undo').click()
    await expect(cell(page, '98:7')).toHaveText('')
    await expect(cell(page, '99:7')).toHaveText('')
    await expect(button(page, 'Undo')).toBeDisabled()
    await button(page, 'Redo').click()
    await expect(cell(page, '98:7')).toHaveText('1')
    await expect(cell(page, '99:7')).toHaveText('2')
    await expect(cell(page, '98:6')).toHaveCount(0)
  })
}
