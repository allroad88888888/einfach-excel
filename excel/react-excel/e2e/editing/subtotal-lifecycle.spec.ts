import { expect, test } from '@playwright/test'
import { downloadDateFile, openDateFile } from '../support/conditional-dates'
import { button, cell, go } from '../support/date-filter'
import { applySubtotal, launchSubtotal, openSubtotal } from '../support/subtotal'

test('Replacing subtotals uses the requested function and one undo restores the prior totals', async ({ page }) => {
  await launchSubtotal(page)
  await openSubtotal(page)
  await applySubtotal(page)
  const panel = await openSubtotal(page, 'A1')
  await expect(panel.getByLabel('Replace current subtotals', { exact: true })).toBeChecked()
  await panel.getByRole('combobox', { name: 'Use function', exact: true }).selectOption('average')
  await applySubtotal(page)
  await expect(cell(page, '3:2')).toHaveText('2.5')
  await expect(cell(page, '6:2')).toHaveText('10')
  await expect(cell(page, '7:2')).toHaveText('6.25')
  await button(page, 'Undo').click()
  await expect(cell(page, '3:2')).toHaveText('5')
  await expect(cell(page, '7:2')).toHaveText('25')
})

test('Remove all protects user content in a generated row and restores the original list', async ({ page }) => {
  await launchSubtotal(page)
  await openSubtotal(page)
  await applySubtotal(page)
  await go(page, 'H4')
  await cell(page, '3:7').dblclick()
  const editor = page.getByRole('textbox', { name: 'Cell editor', exact: true })
  await editor.fill('User note')
  await editor.press('Enter')
  await expect(cell(page, '3:7')).toHaveText('User note')
  const panel = await openSubtotal(page, 'A1')
  await panel.getByRole('button', { name: 'Remove all', exact: true }).click()
  await expect(panel.getByRole('alert')).toContainText('contains edited content')
  await panel.getByRole('button', { name: 'Cancel', exact: true }).click()
  await expect(cell(page, '3:7')).toHaveText('User note')
  await button(page, 'Undo').click()
  await expect(cell(page, '3:7')).toHaveText('')
  await (await openSubtotal(page, 'A1')).getByRole('button', { name: 'Remove all', exact: true }).click()
  await expect(panel).toHaveCount(0)
  await expect(cell(page, '3:2')).toHaveText('4')
  await expect(cell(page, '8:7')).toHaveText('Independent text')
  await expect(button(page, 'Show row outline level 1')).toHaveCount(0)
  await button(page, 'Undo').click()
  await expect(cell(page, '7:2')).toHaveText('25')
})

test('Above-data subtotals reopen and collapse without the optional plugin', async ({ page }) => {
  await launchSubtotal(page)
  const panel = await openSubtotal(page)
  await panel.getByLabel('Summary below data', { exact: true }).uncheck()
  await applySubtotal(page)
  await expect(cell(page, '1:0')).toHaveText('Grand Total')
  await expect(cell(page, '1:2')).toHaveText('25')
  const saved = await downloadDateFile(page)
  expect(JSON.parse(saved.toString()).workbook.outlines[0].outline.rows[0].subtotal.summaryAbove).toBe(true)
  await page.goto('/?locale=en')
  await expect(cell(page, '1:0')).toHaveText('SO-10001')
  await openDateFile(page, saved)
  await expect(button(page, 'Subtotal')).toHaveCount(0)
  await expect(cell(page, '1:2')).toHaveText('25')
  await button(page, 'Show row outline level 1').click()
  await expect(cell(page, '2:0')).toHaveCount(0)
  await expect(cell(page, '1:2')).toHaveText('25')
})
