import { expect, test } from '@playwright/test'
import { select } from '../support/clipboard'

for (const width of [1280, 390]) for (const action of ['Merge consecutive', 'Keep empty field', 'Double quote'])
  test(`${action} split preserves target formatting through one overwrite and undo at ${width}px`, async ({ page }) => {
    await page.setViewportSize({ width, height: 850 })
    await page.goto('/e2e/fixtures/plain-sales-orders/')
    const cell = (coord: string) => page.locator(`td[data-cell="${coord}"]`)
    const button = (name: string) => page.getByRole('button', { name, exact: true })
    await expect(cell('1:0')).toHaveText('SO-10001')
    await page.getByRole('tab', { name: 'Summary', exact: true }).click()
    await select(page, 'E92', '91:4')
    const source = action === 'Double quote' ? '"North, America",001' : 'North,,001'
    const bar = page.getByRole('textbox', { name: 'Active cell value', exact: true })
    await bar.fill(source)
    await bar.press('Enter')
    await expect(cell('91:4')).toHaveText(source)
    await select(page, 'E92', '91:4')
    await button('Text to columns').click()
    const dialog = page.getByRole('dialog', { name: 'Text to columns', exact: true })
    await dialog.getByRole('textbox', { name: 'Destination cell', exact: true }).fill('B98')
    if (action === 'Double quote') {
      const qualifier = dialog.getByRole('combobox', { name: 'Text qualifier', exact: true })
      await qualifier.selectOption('')
      await qualifier.selectOption('"')
    } else {
      const merge = dialog.getByRole('checkbox', { name: 'Treat consecutive delimiters as one', exact: true })
      await merge.check()
      if (action === 'Keep empty field') await merge.uncheck()
    }
    await button('Update preview').click()
    await expect(dialog.getByRole('status'))
      .toHaveText(`Output: B98:${action === 'Keep empty field' ? 'D' : 'C'}98`)
    await dialog.getByRole('checkbox', { name: /Overwrite 1 occupied/ }).check()
    await button('Apply split').click()
    await expect(dialog).toHaveCount(0)
    await expect(await select(page, 'B98', '97:1'))
      .toHaveText(action === 'Double quote' ? 'North, America' : 'North')
    await expect(cell('97:2')).toHaveText(action === 'Keep empty field' ? '' : '001')
    await expect(cell('97:2')).toHaveCSS('font-style', 'italic')
    await expect(await select(page, 'D98', '97:3')).toHaveText(action === 'Keep empty field' ? '001' : '')
    await expect(await select(page, 'E92', '91:4')).toHaveText(source)
    await button('Undo').click()
    await expect(await select(page, 'C98', '97:2')).toHaveText('Existing destination')
    await expect(cell('97:2')).toHaveCSS('font-style', 'italic')
    await button('Undo').click()
    await expect(await select(page, 'E92', '91:4')).toHaveText('')
    await expect(button('Undo')).toBeDisabled()
    await button('Redo').click()
    await button('Redo').click()
    await expect(await select(page, 'C98', '97:2')).toHaveText(action === 'Keep empty field' ? '' : '001')
    await expect(cell('97:2')).toHaveCSS('font-style', 'italic')
  })
