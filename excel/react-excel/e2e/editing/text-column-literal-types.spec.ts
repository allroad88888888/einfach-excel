import { expect, test } from '@playwright/test'
import { select } from '../support/clipboard'

for (const width of [1280, 390]) for (const kind of ['preserve', 'general', 'text'])
  test(`${kind} split field owns only its native value and number format at ${width}px`, async ({ page }) => {
    await page.setViewportSize({ width, height: 850 })
    await page.goto('/e2e/fixtures/plain-sales-orders/')
    const cell = (coord: string) => page.locator(`td[data-cell="${coord}"]`)
    const button = (name: string) => page.getByRole('button', { name, exact: true })
    await expect(cell('1:0')).toHaveText('SO-10001')
    await page.getByRole('tab', { name: 'Summary', exact: true }).click()
    await select(page, 'E95', '94:4')
    await button('Text to columns').click()
    const dialog = page.getByRole('dialog', { name: 'Text to columns', exact: true })
    await dialog.getByRole('textbox', { name: 'Destination cell', exact: true }).fill('C21')
    await dialog.getByRole('spinbutton', { name: 'Source field number', exact: true }).fill('1')
    const type = dialog.getByRole('combobox', { name: 'Field type', exact: true })
    await type.selectOption(kind === 'preserve' ? 'general' : 'preserve')
    await type.selectOption(kind)
    await button('Update preview').click()
    await expect(dialog.getByRole('status')).toHaveText('Output: C21:F21')
    await dialog.getByRole('checkbox', { name: /Overwrite 1 occupied/ }).check()
    await button('Apply split').click()
    await expect(dialog).toHaveCount(0)
    const value = kind === 'general' ? '1' : '001'
    await expect(await select(page, 'C21', '20:2')).toHaveText(value)
    await expect(cell('20:2')).toHaveCSS('font-style', 'italic')
    await button('Number format settings').click()
    // 现有数字面板将 General 映射为 Number 草稿；关闭，不提交这份预览。
    await expect(page.getByRole('combobox', { name: 'Number format category', exact: true }))
      .toHaveValue(kind === 'preserve' ? 'date' : kind === 'general' ? 'number' : 'text')
    await button('Cancel').click()
    await expect(await select(page, 'D21', '20:3')).toHaveText('29/02/2024')
    await expect(await select(page, 'F21', '20:5')).toHaveText('=1+2')
    await expect(await select(page, 'E95', '94:4')).toHaveText('001,29/02/2024,ignore,=1+2')
    await button('Undo').click()
    await expect(await select(page, 'C21', '20:2')).toHaveText('2024-02-29')
    await expect(cell('20:2')).toHaveCSS('font-style', 'italic')
    await expect(button('Undo')).toBeDisabled()
    await expect(await select(page, 'F21', '20:5')).toHaveText('')
    await button('Redo').click()
    await expect(await select(page, 'C21', '20:2')).toHaveText(value)
    await expect(await select(page, 'B21', '20:1')).toHaveText('')
  })
