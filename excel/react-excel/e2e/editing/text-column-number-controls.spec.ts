import { expect, test } from '@playwright/test'
import { select } from '../support/clipboard'

const cases = [
  { action: 'Decimal separator', source: '12,50;keep', value: '12.5', sum: '12.5' },
  { action: 'Thousands separator', source: '1,234.50;keep', value: '1234.5', sum: '1,234.5' },
  { action: 'Trailing minus', source: '123-;keep', value: '-123', sum: '-123' },
]
for (const width of [1280, 390]) for (const { action, source, value, sum } of cases)
  test(`${action} split setting creates a native number and one undo at ${width}px`, async ({ page }) => {
    await page.setViewportSize({ width, height: 850 })
    await page.goto('/e2e/fixtures/plain-sales-orders/')
    const cell = (coord: string) => page.locator(`td[data-cell="${coord}"]`)
    const button = (name: string) => page.getByRole('button', { name, exact: true })
    await expect(cell('1:0')).toHaveText('SO-10001')
    await page.getByRole('tab', { name: 'Summary', exact: true }).click()
    await select(page, 'E92', '91:4')
    const bar = page.getByRole('textbox', { name: 'Active cell value', exact: true })
    await bar.fill(source)
    await bar.press('Enter')
    await expect(cell('91:4')).toHaveText(source)
    await select(page, 'E92', '91:4')
    await button('Text to columns').click()
    const dialog = page.getByRole('dialog', { name: 'Text to columns', exact: true })
    await dialog.getByRole('textbox', { name: 'Destination cell', exact: true }).fill('A92')
    await dialog.getByRole('checkbox', { name: 'Comma', exact: true }).uncheck()
    await dialog.getByRole('checkbox', { name: 'Semicolon', exact: true }).check()
    await dialog.getByRole('spinbutton', { name: 'Source field number', exact: true }).fill('1')
    await dialog.getByRole('combobox', { name: 'Field type', exact: true }).selectOption('general')
    await dialog.getByText('Advanced number parsing', { exact: true }).click()
    if (action === 'Trailing minus')
      await dialog.getByRole('checkbox', { name: /Allow trailing minus/ }).check()
    else await dialog.getByRole('combobox', { name: action, exact: true }).selectOption(',')
    await button('Update preview').click()
    await expect(dialog.getByRole('table', { name: 'Split preview' })).toContainText(value)
    await button('Apply split').click()
    await expect(dialog).toHaveCount(0)
    await expect(await select(page, 'A92', '91:0')).toHaveText(value)
    await expect(bar).toHaveValue(value)
    await expect(cell('91:1')).toHaveText('keep')
    await select(page, 'A92:B92', '91:0')
    await expect(button('Copy Sum')).toHaveText(`Sum: ${sum}`)
    await expect(await select(page, 'C92', '91:2')).toHaveText('')
    await expect(await select(page, 'E92', '91:4')).toHaveText(source)
    await button('Undo').click()
    await expect(await select(page, 'A92', '91:0')).toHaveText('')
    await expect(cell('91:1')).toHaveText('')
    await button('Undo').click()
    await expect(await select(page, 'E92', '91:4')).toHaveText('')
    await expect(button('Undo')).toBeDisabled()
    await button('Redo').click()
    await button('Redo').click()
    await expect(await select(page, 'A92', '91:0')).toHaveText(value)
  })
