import { expect, test, type Page } from '@playwright/test'
import { select, paste } from '../support/clipboard'

const cell = (page: Page, coord: string) => page.locator(`td[data-cell="${coord}"]`)
const button = (page: Page, name: string) => page.getByRole('button', { name, exact: true })
const combo = (page: Page, name: string) => page.getByRole('combobox', { name, exact: true })
const preview = (page: Page) => page.getByRole('table', { name: 'Split preview' })
async function field(page: Page, column: number, kind: string) {
  await page.getByLabel('Source field number', { exact: true }).fill(String(column))
  await combo(page, 'Field type').selectOption(kind)
}
async function refresh(page: Page) {
  await button(page, 'Update preview').click()
  await expect(preview(page)).toBeVisible()
}
async function open(page: Page, source = 'E96', coord = '95:4', destination = 'B100') {
  await select(page, source, coord)
  await button(page, 'Text to columns').click()
  await expect(page.getByRole('dialog')).toBeVisible()
  await page.getByLabel('Destination cell', { exact: true }).fill(destination)
  await page.getByRole('checkbox', { name: 'Comma', exact: true }).uncheck()
  await page.getByRole('checkbox', { name: 'Semicolon', exact: true }).check()
  await field(page, 1, 'general')
  await field(page, 2, 'general')
  await page.getByText('Advanced number parsing', { exact: true }).click()
}
async function european(page: Page, group = '.') {
  await combo(page, 'Decimal separator').selectOption(',')
  await combo(page, 'Thousands separator').selectOption(group)
  await page.getByRole('checkbox', { name: /Allow trailing minus/ }).check()
}
test.beforeEach(async ({ page }) => {
  await page.goto('/')
  await expect(cell(page, '1:0')).toHaveText('SO-10001')
  await page.getByRole('tab', { name: 'Summary', exact: true }).click()
  await expect(cell(page, '0:0')).toHaveText('First order total')
})

for (const width of [1280, 390]) test(`regional number seed converts and restores once at ${width}px`, async ({ page }, info) => {
  const errors: string[] = []
  page.on('pageerror', (error) => errors.push(error.message))
  await page.setViewportSize({ width, height: 850 })
  await open(page)
  await european(page)
  await expect(button(page, 'Apply split')).toBeDisabled()
  await refresh(page)
  await expect(preview(page).getByRole('cell', { name: '1234.5', exact: true })).toBeVisible()
  await expect(preview(page).getByRole('cell', { name: '-12.50%', exact: true })).toBeVisible()
  await expect(preview(page).getByRole('cell', { name: '001', exact: true })).toBeVisible()
  await button(page, 'Apply split').press('Tab')
  await expect(page.getByLabel('Split mode')).toBeFocused()
  await page.getByLabel('Split mode').press('Shift+Tab')
  await expect(button(page, 'Apply split')).toBeFocused()
  await page.screenshot({ path: info.outputPath(`number-parsing-${width}.png`) })
  const dialog = page.getByRole('dialog')
  const box = (await dialog.boundingBox())!
  expect(box.x).toBeGreaterThanOrEqual(0)
  expect(box.x + box.width).toBeLessThanOrEqual(width)
  expect(await dialog.evaluate((node) => node.scrollWidth <= node.clientWidth)).toBe(true)
  await button(page, 'Apply split').click()
  await expect(dialog).toHaveCount(0)
  await expect(await select(page, 'B100', '99:1')).toHaveText('1234.5')
  await expect(cell(page, '99:2')).toHaveText('-12.50%')
  await expect(cell(page, '99:3')).toHaveText('001')
  await select(page, 'B100:C100', '99:1')
  await expect(button(page, 'Copy Sum')).toHaveText('Sum: 1,234.375')
  await button(page, 'Undo').click()
  await expect(cell(page, '99:1')).toHaveText('')
  await expect(cell(page, '99:2')).toHaveText('')
  await expect(button(page, 'Undo')).toBeDisabled()
  await button(page, 'Redo').click()
  await expect(cell(page, '99:2')).toHaveText('-12.50%')
  expect(errors).toEqual([])
})

test('conflicting separators reject without history; corrected options preview and cancel reset', async ({ page }) => {
  await open(page)
  await combo(page, 'Decimal separator').selectOption(',')
  await combo(page, 'Thousands separator').selectOption(',')
  await button(page, 'Update preview').click()
  await expect(page.getByRole('alert')).toContainText('must be different')
  await expect(button(page, 'Apply split')).toBeDisabled()
  await expect(button(page, 'Undo')).toBeDisabled()
  await combo(page, 'Thousands separator').selectOption('.')
  await refresh(page)
  await expect(preview(page)).toContainText('12,50%-')
  await page.getByRole('checkbox', { name: /Allow trailing minus/ }).check()
  await expect(button(page, 'Apply split')).toBeDisabled()
  await refresh(page)
  await expect(preview(page)).toContainText('-12.50%')
  await button(page, 'Cancel').click()
  await expect(button(page, 'Undo')).toBeDisabled()
  await expect(cell(page, '95:4')).toHaveText('1.234,50;12,50%-;001')
  await open(page)
  await expect(combo(page, 'Decimal separator')).toHaveValue('.')
  await expect(combo(page, 'Thousands separator')).toHaveValue('')
  await expect(page.getByRole('checkbox', { name: /Allow trailing minus/ })).not.toBeChecked()
})

test('Text ignores locale options, malformed grouping stays text and correction recalculates preview', async ({ page, context }) => {
  await context.grantPermissions(['clipboard-read', 'clipboard-write'])
  await select(page, 'E92', '91:4')
  await page.evaluate(() => navigator.clipboard.writeText('12,34;1,234;001'))
  await paste(page)
  await open(page, 'E92', '91:4')
  await field(page, 3, 'text')
  await combo(page, 'Thousands separator').selectOption(',')
  await refresh(page)
  await expect(preview(page).getByRole('cell', { name: '12,34', exact: true })).toBeVisible()
  await expect(preview(page).getByRole('cell', { name: '1234', exact: true })).toBeVisible()
  await expect(preview(page).getByRole('cell', { name: '001', exact: true })).toBeVisible()
  await combo(page, 'Thousands separator').selectOption('')
  await combo(page, 'Decimal separator').selectOption(',')
  await refresh(page)
  await expect(preview(page).getByRole('cell', { name: '12.34', exact: true })).toBeVisible()
  await expect(preview(page).getByRole('cell', { name: '1.234', exact: true })).toBeVisible()
  await button(page, 'Apply split').click()
  await expect(page.getByRole('dialog')).toHaveCount(0)
  await expect(await select(page, 'D100', '99:3')).toHaveText('001')
  await button(page, 'Undo').click()
  await expect(cell(page, '99:3')).toHaveText('')
})

test('nonbreaking-space grouping converts all 400 source rows through the real Worker', async ({ page, context }) => {
  await context.grantPermissions(['clipboard-read', 'clipboard-write'])
  await page.getByRole('tab', { name: 'Sales Orders', exact: true }).click()
  const original = await (await select(page, 'M400', '399:12')).textContent()
  await select(page, 'P1', '0:15')
  await page.evaluate(() => navigator.clipboard.writeText(
    Array.from({ length: 400 }, () => '1\u00a0234,50;12,50%-;001').join('\n'),
  ))
  await paste(page)
  await open(page, 'P1:P400', '0:15', 'M1')
  await european(page, '\u00a0')
  await refresh(page)
  await expect(page.getByText(/Sample shortened:/)).toBeVisible()
  await page.getByRole('checkbox', { name: /Overwrite/ }).check()
  await button(page, 'Apply split').click()
  await expect(page.getByRole('dialog')).toHaveCount(0)
  await expect(await select(page, 'M400', '399:12')).toHaveText('1234.5')
  await expect(await select(page, 'N400', '399:13')).toHaveText('-12.50%')
  await expect(await select(page, 'O400', '399:14')).toHaveText('001')
  await button(page, 'Undo').click()
  await expect(await select(page, 'M400', '399:12')).toHaveText(original ?? '')
  await button(page, 'Redo').click()
  await expect(cell(page, '399:12')).toHaveText('1234.5')
})
