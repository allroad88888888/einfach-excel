import { expect, test, type Page } from '@playwright/test'
import { select, paste } from '../support/clipboard'

const cell = (page: Page, coord: string) => page.locator(`td[data-cell="${coord}"]`)
const button = (page: Page, name: string) => page.getByRole('button', { name, exact: true })
const preview = (page: Page) => page.getByRole('table', { name: 'Split preview' })
async function type(page: Page, column: number, kind: string) {
  await page.getByLabel('Source field number', { exact: true }).fill(String(column))
  await page.getByRole('combobox', { name: 'Field type', exact: true }).selectOption(kind)
}
async function refresh(page: Page) {
  await button(page, 'Update preview').click()
  await expect(preview(page)).toBeVisible()
}
async function open(page: Page, source = 'E95', coord = '94:4', destination = 'B95') {
  await select(page, source, coord)
  await button(page, 'Text to columns').click()
  // 默认在源位置预览可能越过画布；先指定可容纳输出的目标。
  await expect(page.getByRole('dialog')).toBeVisible()
  await page.getByLabel('Destination cell', { exact: true }).fill(destination)
  await refresh(page)
}
test.beforeEach(async ({ page }) => {
  await page.goto('/e2e/fixtures/plain-sales-orders/')
  await expect(cell(page, '1:0')).toHaveText('SO-10001')
  await page.getByRole('tab', { name: 'Summary', exact: true }).click()
  await expect(cell(page, '0:0')).toHaveText('First order total')
})

for (const width of [1280, 390]) test(`field types convert native seed and undo as one operation at ${width}px`, async ({ page }, info) => {
  const errors: string[] = []
  page.on('pageerror', (error) => errors.push(error.message))
  await page.setViewportSize({ width, height: 850 })
  await open(page)
  await type(page, 1, 'general')
  await type(page, 2, 'dateDmy')
  await type(page, 3, 'skip')
  await type(page, 4, 'text')
  await expect(button(page, 'Apply split')).toBeDisabled()
  await refresh(page)
  await expect(preview(page)).toContainText('2024-02-29')
  await expect(preview(page)).not.toContainText('ignore')
  await expect(preview(page).getByRole('columnheader')).toHaveText(['Row', 'B95', 'C95', 'D95'])
  await expect(page.getByRole('status').filter({ hasText: 'Output:' })).toHaveText('Output: B95:D95')
  await button(page, 'Apply split').press('Tab')
  await expect(page.getByLabel('Split mode')).toBeFocused()
  await page.getByLabel('Split mode').press('Shift+Tab')
  await expect(button(page, 'Apply split')).toBeFocused()
  await page.screenshot({ path: info.outputPath(`field-types-${width}.png`) })
  const dialog = page.getByRole('dialog')
  const box = (await dialog.boundingBox())!
  expect(box.x).toBeGreaterThanOrEqual(0)
  expect(box.x + box.width).toBeLessThanOrEqual(width)
  expect(await dialog.evaluate((node) => node.scrollWidth <= node.clientWidth)).toBe(true)
  await button(page, 'Apply split').click()
  await expect(dialog).toHaveCount(0)
  await expect(cell(page, '94:1')).toHaveText('1')
  await expect(cell(page, '94:2')).toHaveText('2024-02-29')
  await expect(await select(page, 'D95', '94:3')).toHaveText('=1+2')
  await expect(await select(page, 'E95', '94:4')).toHaveText('001,29/02/2024,ignore,=1+2')
  await expect(await select(page, 'F95', '94:5')).toHaveText('')
  await select(page, 'B95:C95', '94:1')
  await expect(button(page, 'Copy Sum')).toHaveText('Sum: 45,352')
  await button(page, 'Undo').click()
  await expect(cell(page, '94:1')).toHaveText('')
  await expect(cell(page, '94:2')).toHaveText('')
  await expect(button(page, 'Undo')).toBeDisabled()
  await button(page, 'Redo').click()
  await expect(cell(page, '94:2')).toHaveText('2024-02-29')
  expect(errors).toEqual([])
})

test('source-indexed rules survive destination changes, invalidate overwrite and never write on Cancel', async ({ page }) => {
  await open(page, 'E97:E98', '96:4', 'B97')
  await page.getByRole('checkbox', { name: /Overwrite 1 occupied/ }).check()
  await type(page, 2, 'general')
  await expect(button(page, 'Apply split')).toBeDisabled()
  await refresh(page)
  await expect(page.getByRole('checkbox', { name: /Overwrite 1 occupied/ })).not.toBeChecked()
  await expect(preview(page).getByRole('cell', { name: '1', exact: true })).toBeVisible()
  await type(page, 2, 'text')
  await refresh(page)
  await expect(preview(page).getByRole('cell', { name: '001', exact: true })).toBeVisible()
  await page.getByLabel('Destination cell', { exact: true }).fill('A97')
  await refresh(page)
  await expect(page.getByRole('combobox', { name: 'Field type', exact: true })).toHaveValue('text')
  await button(page, 'Cancel').click()
  await expect(button(page, 'Undo')).toBeDisabled()
  await expect(cell(page, '97:2')).toHaveText('Existing destination')
})

test('all-skipped and missing fields reject, correcting rules can fit the last canvas column', async ({ page }) => {
  await open(page)
  for (const column of [1, 2, 3, 4]) await type(page, column, 'skip')
  await button(page, 'Update preview').click()
  await expect(page.getByRole('alert')).toContainText('Keep at least one')
  await expect(button(page, 'Apply split')).toBeDisabled()
  await type(page, 1, 'general')
  await type(page, 5, 'text')
  await button(page, 'Update preview').click()
  await expect(page.getByRole('alert')).toContainText('missing source field')
  await type(page, 5, 'preserve')
  await page.getByLabel('Destination cell', { exact: true }).fill('H100')
  await refresh(page)
  await expect(preview(page).getByRole('columnheader')).toHaveText(['Row', 'H100'])
  await button(page, 'Apply split').click()
  await expect(page.getByRole('dialog')).toHaveCount(0)
  await expect(await select(page, 'H100', '99:7')).toHaveText('1')
  await button(page, 'Undo').click()
  await expect(cell(page, '99:7')).toHaveText('')
  await expect(button(page, 'Undo')).toBeDisabled()
})

test('fixed width supports source field types and resetting split rules clears them', async ({ page }) => {
  await open(page, 'E99', '98:4', 'B99')
  await type(page, 1, 'skip')
  await page.getByLabel('Split mode').selectOption('fixedWidth')
  await expect(page.getByRole('combobox', { name: 'Field type', exact: true })).toHaveValue('preserve')
  await page.getByLabel('Break positions').fill('2,5')
  await type(page, 1, 'skip')
  await type(page, 3, 'general')
  await refresh(page)
  await expect(preview(page)).toContainText('😀AB')
  await button(page, 'Apply split').click()
  await expect(cell(page, '98:1')).toHaveText('😀AB')
  await expect(cell(page, '98:2')).toHaveText('7')
  await expect(cell(page, '98:3')).toHaveText('')
  await button(page, 'Undo').click()
  await expect(cell(page, '98:1')).toHaveText('')
})

test('fields beyond the preview column limit can be typed and all 400 rows are converted', async ({ page, context }) => {
  await context.grantPermissions(['clipboard-read', 'clipboard-write'])
  await page.getByRole('tab', { name: 'Sales Orders', exact: true }).click()
  await select(page, 'P1', '0:15')
  const source = Array.from({ length: 400 }, (_, row) =>
    [...Array.from({ length: 12 }, () => 'x'), String(row + 1).padStart(5, '0'), '29/02/2024'].join(','),
  ).join('\n')
  await page.evaluate((value) => navigator.clipboard.writeText(value), source)
  await paste(page)
  await open(page, 'P1:P400', '0:15', 'A1')
  await type(page, 13, 'general')
  await type(page, 14, 'dateDmy')
  await refresh(page)
  await expect(page.getByText(/Sample shortened:/)).toBeVisible()
  await page.getByRole('checkbox', { name: /Overwrite/ }).check()
  await button(page, 'Apply split').click()
  await expect(page.getByRole('dialog')).toHaveCount(0)
  await expect(await select(page, 'M400', '399:12')).toHaveText('400')
  await expect(await select(page, 'N400', '399:13')).toHaveText('2024-02-29')
  await button(page, 'Undo').click()
  await expect(cell(page, '399:13')).not.toHaveText('2024-02-29')
  await button(page, 'Redo').click()
  await expect(cell(page, '399:13')).toHaveText('2024-02-29')
})
