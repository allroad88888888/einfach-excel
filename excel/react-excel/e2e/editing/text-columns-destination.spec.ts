import { expect, test } from '@playwright/test'
import { select } from '../support/clipboard'

for (const width of [1280, 390])
  test(`invalid split destination corrects before one native overwrite and undo at ${width}px`, async ({ page }) => {
    await page.setViewportSize({ width, height: 850 })
    await page.goto('/e2e/fixtures/plain-sales-orders/')
    const cell = (coord: string) => page.locator(`td[data-cell="${coord}"]`)
    const button = (name: string) => page.getByRole('button', { name, exact: true })
    await expect(cell('1:0')).toHaveText('SO-10001')
    await page.getByRole('tab', { name: 'Summary', exact: true }).click()
    await select(page, 'H94', '93:7')
    const bar = page.getByRole('textbox', { name: 'Active cell value', exact: true })
    await bar.fill('old redo')
    await bar.press('Enter')
    await expect(cell('93:7')).toHaveText('old redo')
    await button('Undo').click()
    await select(page, 'E97:E98', '96:4')
    await button('Text to columns').click()
    const dialog = page.getByRole('dialog', { name: 'Text to columns', exact: true })
    await expect(dialog.getByRole('table', { name: 'Split preview' })).toBeVisible()
    const target = dialog.getByRole('textbox', { name: 'Destination cell', exact: true })
    await target.fill('H100')
    await button('Update preview').click()
    await expect(dialog.getByRole('alert')).toContainText('boundary')
    await expect(button('Apply split')).toBeDisabled()
    await expect(button('Undo')).toBeDisabled()
    await expect(button('Redo')).toBeEnabled()
    await target.fill('B97')
    await button('Update preview').click()
    await expect(dialog.getByRole('alert')).toHaveCount(0)
    await expect(dialog.getByRole('status')).toHaveText('Output: B97:D98')
    await expect(button('Apply split')).toBeDisabled()
    await dialog.getByRole('checkbox', { name: /Overwrite 1 occupied/ }).check()
    await button('Apply split').click()
    await expect(dialog).toHaveCount(0)
    await expect(await select(page, 'B97', '96:1')).toHaveText('North, America')
    await expect(cell('97:2')).toHaveText('002')
    await expect(cell('97:2')).toHaveCSS('font-style', 'italic')
    await expect(await select(page, 'D98', '97:3')).toHaveText('On hold')
    await expect(button('Redo')).toBeDisabled()
    await button('Undo').click()
    await expect(await select(page, 'C98', '97:2')).toHaveText('Existing destination')
    await expect(await select(page, 'B97', '96:1')).toHaveText('')
    await expect(button('Undo')).toBeDisabled()
    await button('Redo').click()
    await expect(cell('96:1')).toHaveText('North, America')
    await expect(await select(page, 'H94', '93:7')).toHaveText('')
    await expect(await select(page, 'E97', '96:4')).toHaveText('"North, America",001,Ready')
  })
