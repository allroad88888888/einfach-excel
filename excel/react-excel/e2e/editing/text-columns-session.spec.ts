import { expect, test } from '@playwright/test'
import { select } from '../support/clipboard'

for (const width of [1280, 390]) for (const action of ['Open', 'Cancel', 'Escape', 'Tab', 'Shift+Tab'])
  test(`${action} text columns resets its draft without overwriting source or redo at ${width}px`, async ({ page }, info) => {
    await page.setViewportSize({ width, height: 850 })
    await page.goto('/e2e/fixtures/plain-sales-orders/')
    const cell = (coord: string) => page.locator(`td[data-cell="${coord}"]`)
    const button = (name: string) => page.getByRole('button', { name, exact: true })
    await expect(cell('1:0')).toHaveText('SO-10001')
    await page.getByRole('tab', { name: 'Summary', exact: true }).click()
    await select(page, 'H94', '93:7')
    const bar = page.getByRole('textbox', { name: 'Active cell value', exact: true })
    await bar.fill('split redo')
    await bar.press('Enter')
    await expect(cell('93:7')).toHaveText('split redo')
    await button('Undo').click()
    await select(page, 'E97:E98', '96:4')
    await button('Text to columns').click()
    const dialog = page.getByRole('dialog', { name: 'Text to columns', exact: true })
    const mode = dialog.getByRole('combobox', { name: 'Split mode', exact: true })
    const destination = dialog.getByRole('textbox', { name: 'Destination cell', exact: true })
    await expect(mode).toBeFocused()
    await expect(mode).toHaveValue('delimited')
    await expect(destination).toHaveValue('E97')
    await expect(dialog.getByRole('table', { name: 'Split preview', exact: true })).toBeVisible()
    if (action === 'Open') {
      expect(await dialog.evaluate(node => node.scrollWidth <= node.clientWidth)).toBe(true)
      const box = (await dialog.boundingBox())!
      expect(box.x).toBeGreaterThanOrEqual(0)
      expect(box.x + box.width).toBeLessThanOrEqual(width)
      await page.screenshot({ path: info.outputPath(`text-columns-open-${width}.png`) })
    } else {
      await mode.selectOption('fixedWidth')
      await dialog.getByRole('textbox', { name: 'Break positions', exact: true }).fill('2,5')
      await destination.fill('B97')
    }
    if (action === 'Tab' || action === 'Shift+Tab') {
      const last = dialog.getByRole('button', { name: 'Update preview', exact: true })
      await (action === 'Tab' ? last : mode).focus()
      await page.keyboard.press(action)
      await expect(action === 'Tab' ? mode : last).toBeFocused()
    }
    if (action === 'Escape') await page.keyboard.press('Escape')
    else await button('Cancel').click()
    await expect(dialog).toHaveCount(0)
    await expect(button('Text to columns')).toBeFocused()
    await expect(page.getByRole('textbox', { name: 'Name box' })).toHaveValue('E97:E98')
    await expect(button('Undo')).toBeDisabled()
    await button('Text to columns').click()
    await expect(mode).toHaveValue('delimited')
    await expect(destination).toHaveValue('E97')
    await button('Cancel').click()
    await expect(await select(page, 'E97', '96:4')).toHaveText('"North, America",001,Ready')
    await expect(cell('97:4')).toHaveText('"Asia",002,"On hold"')
    await expect(await select(page, 'C98', '97:2')).toHaveText('Existing destination')
    await expect(cell('97:2')).toHaveCSS('font-style', 'italic')
    await button('Redo').click()
    await expect(await select(page, 'H94', '93:7')).toHaveText('split redo')
  })
