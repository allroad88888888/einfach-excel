import { expect, test } from '@playwright/test'
import { select } from '../support/clipboard'

for (const width of [1280, 390]) for (const action of ['Open', 'Tab', 'Shift+Tab'])
  test(`${action} validation dialog preserves native rules values and redo at ${width}px`, async ({ page }, info) => {
    await page.setViewportSize({ width, height: 850 })
    await page.goto('/e2e/fixtures/plain-sales-orders/')
    const cell = (coord: string) => page.locator(`td[data-cell="${coord}"]`)
    const button = (name: string) => page.getByRole('button', { name, exact: true })
    await expect(cell('1:0')).toHaveText('SO-10001')
    await select(page, 'E2', '1:4')
    const bar = page.getByRole('textbox', { name: 'Active cell value', exact: true })
    await bar.fill('2')
    await bar.press('Enter')
    await expect(cell('1:6')).toHaveText('158')
    await button('Undo').click()
    await page.getByRole('tab', { name: 'Summary', exact: true }).click()
    await select(page, 'H47', '46:7')
    await button('Data validation').click()
    const dialog = page.getByRole('dialog', { name: 'Data validation', exact: true })
    const first = dialog.getByRole('textbox', { name: 'Applies to', exact: true })
    const last = dialog.getByRole('button', { name: 'Apply', exact: true })
    await expect(first).toBeFocused()
    await expect(first).toHaveValue('H47')
    await expect(dialog.getByRole('combobox', { name: 'Allow', exact: true })).toHaveValue('list')
    const items = dialog.getByRole('textbox', { name: 'Items, one per line', exact: true })
    await expect(items).toHaveValue('Ready\nOn hold\n001\n=1+2')
    if (action === 'Open') {
      expect(await dialog.evaluate(node => node.scrollWidth <= node.clientWidth)).toBe(true)
      const box = (await dialog.boundingBox())!
      expect(box.x).toBeGreaterThanOrEqual(0)
      expect(box.x + box.width).toBeLessThanOrEqual(width)
      await page.screenshot({ path: info.outputPath(`validation-open-${width}.png`) })
    } else {
      await (action === 'Tab' ? last : first).focus()
      await page.keyboard.press(action)
      await expect(action === 'Tab' ? first : last).toBeFocused()
    }
    await button('Cancel').click()
    await expect(dialog).toHaveCount(0)
    await expect(button('Data validation')).toBeFocused()
    await expect(page.getByRole('textbox', { name: 'Name box' })).toHaveValue('H47')
    await expect(cell('46:7')).toHaveText('Ready')
    await expect(cell('45:7')).toHaveText('0.5')
    await expect(page.getByRole('combobox', { name: 'Choose cell value' })).toBeVisible()
    await expect(button('Undo')).toBeDisabled()
    await button('Data validation').click()
    await expect(items).toHaveValue('Ready\nOn hold\n001\n=1+2')
    await button('Cancel').click()
    await button('Redo').click()
    await page.getByRole('tab', { name: 'Sales Orders', exact: true }).click()
    await select(page, 'G2', '1:6')
    await expect(cell('1:6')).toHaveText('158')
    await expect(bar).toHaveValue('=E2*F2')
    await expect(cell('1:6')).toHaveCSS('font-family', 'Georgia')
  })
