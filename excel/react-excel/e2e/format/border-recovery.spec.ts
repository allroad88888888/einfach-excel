import { expect, test, type Page } from '@playwright/test'
import { select } from '../support/clipboard'

const cell = (page: Page, coord: string) => page.locator(`td[data-cell="${coord}"]`)
const button = (page: Page, name: string) => page.getByRole('button', { name, exact: true })
const dialog = (page: Page) => page.getByRole('dialog', { name: 'Borders', exact: true })
test.beforeEach(async ({ page }) => {
  await page.goto('/e2e/fixtures/plain-sales-orders/')
  await expect(cell(page, '1:0')).toHaveText('SO-10001')
  await select(page, 'H2', '1:7')
  const input = page.getByRole('textbox', { name: 'Active cell value' })
  await input.fill('Keep border redo'); await input.press('Enter')
  await expect(cell(page, '1:7')).toHaveText('Keep border redo')
  await button(page, 'Undo').click()
  await expect(cell(page, '1:7')).not.toHaveText('Keep border redo')
  await select(page, 'B6', '5:1')
  await expect(cell(page, '5:1')).toHaveCSS('border-bottom-style', 'double')
  await expect(cell(page, '5:1')).toHaveCSS('border-bottom-color', 'rgb(192, 0, 0)')
})

for (const action of ['Cancel', 'Escape']) for (const width of [1280, 390])
  test(`${action} border settings discards invalid draft and preserves redo at ${width}px`, async ({ page }) => {
    await page.setViewportSize({ width, height: 850 })
    const original = await cell(page, '5:1').textContent()
    await button(page, 'Border settings').click()
    await page.getByLabel('Position', { exact: true }).selectOption('all')
    await page.getByLabel('Line style', { exact: true }).selectOption('thick')
    await page.getByLabel('Hex color', { exact: true }).fill('invalid-color')
    await expect(page.getByLabel('Hex color', { exact: true })).toHaveAttribute('aria-invalid', 'true')
    if (action === 'Escape') await page.keyboard.press('Escape')
    else await button(page, 'Cancel').click()
    await expect(dialog(page)).toHaveCount(0)
    await expect(button(page, 'Border settings')).toBeFocused()
    await expect(cell(page, '5:1')).toHaveCSS('border-bottom-style', 'double')
    await expect(cell(page, '5:1')).toHaveCSS('border-bottom-color', 'rgb(192, 0, 0)')
    await expect(cell(page, '5:1')).toHaveText(original!)
    await button(page, 'Border settings').click()
    await expect(page.getByLabel('Position', { exact: true })).toHaveValue('outside')
    await expect(page.getByLabel('Line style', { exact: true })).toHaveValue('double')
    await expect(page.getByLabel('Hex color', { exact: true })).toHaveValue('#c00000')
    await button(page, 'Cancel').click()
    await expect(button(page, 'Undo')).toBeDisabled()
    await button(page, 'Redo').click()
    await select(page, 'H2', '1:7')
    await expect(page.getByRole('textbox', { name: 'Active cell value' })).toHaveValue('Keep border redo')
    await select(page, 'A2', '1:0')
    await expect(cell(page, '1:0')).toHaveText('SO-10001')
  })

for (const width of [1280, 390])
  test(`invalid border Hex stays correctable and commits only the valid retry at ${width}px`, async ({ page }) => {
    await page.setViewportSize({ width, height: 850 })
    const original = await cell(page, '5:1').textContent()
    await button(page, 'Border settings').click()
    await page.getByLabel('Position', { exact: true }).selectOption('bottom')
    await page.getByLabel('Line style', { exact: true }).selectOption('thin')
    for (const color of ['red', '#123', '#gggggg', '', 'url(x)']) {
      await page.getByLabel('Hex color', { exact: true }).fill(color)
      await button(page, 'Apply borders').click()
      await expect(dialog(page).getByRole('alert')).toContainText('#RRGGBB')
      await expect(cell(page, '5:1')).toHaveCSS('border-bottom-style', 'double')
      await expect(cell(page, '5:1')).toHaveCSS('border-bottom-color', 'rgb(192, 0, 0)')
      await expect(button(page, 'Undo')).toBeDisabled()
      await expect(button(page, 'Redo')).toBeEnabled()
    }
    await page.getByLabel('Hex color', { exact: true }).fill('#AB12CD')
    await expect(dialog(page).getByRole('alert')).toHaveCount(0)
    await button(page, 'Apply borders').click()
    await expect(dialog(page)).toHaveCount(0)
    await expect(cell(page, '5:1')).toHaveCSS('border-bottom-color', 'rgb(171, 18, 205)')
    await expect(cell(page, '5:1')).toHaveCSS('border-bottom-style', 'solid')
    await expect(cell(page, '5:1')).toHaveText(original!)
    await expect(button(page, 'Redo')).toBeDisabled()
    await button(page, 'Undo').click()
    await expect(cell(page, '5:1')).toHaveCSS('border-bottom-style', 'double')
    await expect(button(page, 'Undo')).toBeDisabled()
    await button(page, 'Redo').click()
    await expect(cell(page, '5:1')).toHaveCSS('border-bottom-color', 'rgb(171, 18, 205)')
    await select(page, 'A2', '1:0')
    await expect(cell(page, '1:0')).toHaveCSS('font-weight', '700')
  })
