import { expect, test, type Page } from '@playwright/test'

const cell = (page: Page, coord: string) => page.locator(`td[data-cell="${coord}"]`)
const button = (page: Page, name: string) => page.getByRole('button', { name, exact: true })
const dialog = (page: Page) => page.getByRole('dialog', { name: 'Conditional formatting', exact: true })
const bar = (page: Page) => page.getByRole('textbox', { name: 'Active cell value' })
async function go(page: Page, reference: string) {
  await button(page, 'Go to').click()
  await page.getByLabel('Reference', { exact: true }).fill(reference)
  await button(page, 'Go').click()
  await expect(page.getByRole('dialog')).toHaveCount(0)
  await expect(bar(page)).toBeEnabled()
}
async function open(page: Page) {
  await button(page, 'Conditional formatting').click()
  await expect(dialog(page)).toBeVisible()
}
async function save(page: Page, editing = false) {
  await button(page, editing ? 'Save rule' : 'Add rule').click()
  await expect(dialog(page)).toHaveCount(0)
}
test.beforeEach(async ({ page }) => {
  await page.goto('/')
  await expect(cell(page, '1:0')).toHaveText('SO-10001')
  await page.getByRole('tab', { name: 'Summary', exact: true }).click()
  await go(page, 'C65:C67')
})

test('native seed highlights only matching numbers and value edits reveal the original style', async ({ page }) => {
  await expect(cell(page, '64:2')).not.toHaveCSS('background-color', 'rgb(255, 199, 206)')
  await expect(cell(page, '65:2')).toHaveCSS('background-color', 'rgb(255, 199, 206)')
  await expect(cell(page, '66:2')).toHaveCSS('background-color', 'rgb(255, 199, 206)')
  await expect(button(page, 'Undo')).toBeDisabled()
  await go(page, 'C66')
  await bar(page).fill('1'); await bar(page).press('Enter')
  await expect(cell(page, '65:2')).not.toHaveCSS('background-color', 'rgb(255, 199, 206)')
  await button(page, 'Undo').click()
  await expect(cell(page, '65:2')).toHaveCSS('background-color', 'rgb(255, 199, 206)')
})

test('add, edit and delete are three native actions with undo and redo', async ({ page }) => {
  await go(page, 'D65:D67')
  await open(page)
  await page.getByLabel('Value', { exact: true }).fill('3')
  await save(page)
  await expect(cell(page, '65:3')).toHaveCSS('background-color', 'rgb(255, 199, 206)')
  await open(page); await button(page, 'Edit rule 1').click()
  await page.getByLabel('Value', { exact: true }).fill('5')
  await save(page, true)
  await expect(cell(page, '65:3')).not.toHaveCSS('background-color', 'rgb(255, 199, 206)')
  await expect(cell(page, '66:3')).toHaveCSS('background-color', 'rgb(255, 199, 206)')
  await open(page); await button(page, 'Delete rule 1').click()
  await expect(dialog(page)).toHaveCount(0)
  await expect(cell(page, '66:3')).not.toHaveCSS('background-color', 'rgb(255, 199, 206)')
  await button(page, 'Undo').click()
  await expect(cell(page, '66:3')).toHaveCSS('background-color', 'rgb(255, 199, 206)')
  await button(page, 'Undo').click()
  await expect(cell(page, '65:3')).toHaveCSS('background-color', 'rgb(255, 199, 206)')
  await button(page, 'Undo').click()
  await expect(cell(page, '65:3')).not.toHaveCSS('background-color', 'rgb(255, 199, 206)')
  await button(page, 'Redo').click()
  await expect(cell(page, '65:3')).toHaveCSS('background-color', 'rgb(255, 199, 206)')
})

test('new overlapping rule wins; deleting it reveals the lower priority rule', async ({ page }) => {
  await open(page)
  await page.getByLabel('Value', { exact: true }).fill('5')
  await page.getByLabel('Highlight fill').fill('#00ff00')
  await save(page)
  await expect(cell(page, '65:2')).toHaveCSS('background-color', 'rgb(255, 199, 206)')
  await expect(cell(page, '66:2')).toHaveCSS('background-color', 'rgb(0, 255, 0)')
  await open(page); await button(page, 'Delete rule 1').click()
  await expect(cell(page, '66:2')).toHaveCSS('background-color', 'rgb(255, 199, 206)')
})

test('between includes both bounds and formula results react to their dependencies', async ({ page }) => {
  await go(page, 'C70')
  await open(page)
  await page.getByLabel('Condition', { exact: true }).selectOption('between')
  await page.getByLabel('Minimum', { exact: true }).fill('12')
  await page.getByLabel('Maximum', { exact: true }).fill('12')
  await save(page)
  await expect(cell(page, '69:2')).toHaveText('12')
  await expect(cell(page, '69:2')).toHaveCSS('background-color', 'rgb(255, 199, 206)')
  await go(page, 'C65'); await bar(page).fill('8'); await bar(page).press('Enter')
  await expect(cell(page, '69:2')).toHaveText('18')
  await expect(cell(page, '69:2')).not.toHaveCSS('background-color', 'rgb(255, 199, 206)')
})

test('invalid input stays correctable; Escape does not create a rule or history', async ({ page }) => {
  await open(page)
  await page.getByLabel('Value', { exact: true }).fill('NaN')
  await button(page, 'Add rule').click()
  await expect(dialog(page).getByRole('alert')).toContainText('finite number')
  await page.getByLabel('Applies to', { exact: true }).fill('A101')
  await button(page, 'Add rule').click()
  await expect(dialog(page).getByRole('alert')).toContainText('inside this worksheet')
  await page.getByLabel('Applies to', { exact: true }).press('Escape')
  await expect(dialog(page)).toHaveCount(0)
  await expect(button(page, 'Conditional formatting')).toBeFocused()
  await expect(button(page, 'Undo')).toBeDisabled()
})

test('row insertion shifts the rule with cells and undo restores the original scope', async ({ page }) => {
  await go(page, 'C65')
  await page.getByRole('combobox', { name: 'Insert or delete rows and columns' }).selectOption('insert-rows')
  await expect(cell(page, '66:2')).toHaveText('4')
  await expect(cell(page, '66:2')).toHaveCSS('background-color', 'rgb(255, 199, 206)')
  await open(page)
  await expect(page.getByRole('region', { name: 'Worksheet rules' })).toContainText('C66:C68')
  await button(page, 'Cancel').click()
  await button(page, 'Undo').click()
  await open(page)
  await expect(page.getByRole('region', { name: 'Worksheet rules' })).toContainText('C65:C67')
  await button(page, 'Cancel').click()
  await expect(cell(page, '65:2')).toHaveText('4')
  await expect(cell(page, '65:2')).toHaveCSS('background-color', 'rgb(255, 199, 206)')
})

test('frozen formula and merged numeric anchor use the same native display format', async ({ page }) => {
  await go(page, 'B1')
  await open(page)
  await page.getByLabel('Value', { exact: true }).fill('0')
  await save(page)
  await go(page, 'C65')
  await expect(cell(page, '0:1')).toHaveCSS('background-color', 'rgb(255, 199, 206)')
  await go(page, 'A15')
  await bar(page).fill('20'); await bar(page).press('Enter')
  await open(page)
  await page.getByLabel('Applies to', { exact: true }).fill('A15:D15')
  await page.getByLabel('Value', { exact: true }).fill('10')
  await save(page)
  await expect(cell(page, '14:0')).toHaveCSS('background-color', 'rgb(255, 199, 206)')
  await expect(cell(page, '14:0')).toHaveText('20')
})

for (const width of [1280, 390]) test(`rule editor fits at ${width}px with keyboard focus and no page errors`, async ({ page }, info) => {
  const errors: string[] = []
  page.on('pageerror', (error) => errors.push(error.message))
  await page.setViewportSize({ width, height: 800 })
  await open(page)
  await expect(page.getByLabel('Applies to', { exact: true })).toBeFocused()
  await page.getByLabel('Condition', { exact: true }).selectOption('between')
  await page.getByLabel('Minimum', { exact: true }).fill('2')
  await page.getByLabel('Maximum', { exact: true }).fill('6')
  expect(await dialog(page).evaluate((node) => node.scrollWidth <= node.clientWidth)).toBe(true)
  await page.screenshot({ path: info.outputPath(`conditional-format-${width}.png`), fullPage: true })
  expect(errors).toEqual([])
  await button(page, 'Cancel').click()
})
