import { expect, test, type Page } from '@playwright/test'

const button = (page: Page, name: string) => page.getByRole('button', { name, exact: true })
const dialog = (page: Page) => page.getByRole('dialog', { name: 'Conditional formatting', exact: true })
const rules = (page: Page) => dialog(page).getByRole('listitem')
const cell = (page: Page, coord: string) => page.locator(`td[data-cell="${coord}"]`)
const red = 'rgb(255, 199, 206)'
const blue = 'rgb(217, 234, 247)'
const green = 'rgb(0, 255, 0)'

async function open(page: Page) {
  await button(page, 'Conditional formatting').click()
  await expect(dialog(page)).toBeVisible()
}

async function seedValuesStayIntact(page: Page) {
  for (const col of [2, 3]) for (const [row, value] of [[64, '2'], [65, '4'], [66, '6']] as const)
    await expect(cell(page, `${row}:${col}`)).toHaveText(value)
  await expect(cell(page, '66:4')).toHaveCSS('background-color', 'rgb(226, 240, 217)')
}

for (const width of [1280, 390]) test.describe(`${width}px conditional rule lifecycle`, () => {
  test.use({ viewport: { width, height: 850 } })
  test.beforeEach(async ({ page }) => {
    await page.goto('/')
    await expect(cell(page, '1:0')).toHaveText('SO-10001')
    await page.getByRole('tab', { name: 'Summary', exact: true }).click()
    await button(page, 'Go to').click()
    await page.getByLabel('Reference', { exact: true }).fill('C65:D67')
    await button(page, 'Go').click()
    await expect(page.getByRole('dialog')).toHaveCount(0)
    await expect(cell(page, '65:2')).toHaveCSS('background-color', red)
    await expect(cell(page, '65:3')).toHaveCSS('background-color', blue)
    await expect(button(page, 'Undo')).toBeDisabled()
  })

  test(`adding a conditional rule changes only its applied cells at ${width}px`, async ({ page }) => {
    const nonmatchingColor = await cell(page, '64:3').evaluate(node => getComputedStyle(node).backgroundColor)
    await open(page)
    const count = await rules(page).count()
    await page.getByLabel('Applies to', { exact: true }).fill('D65:D67')
    await page.getByLabel('Value', { exact: true }).fill('NaN')
    await button(page, 'Add rule').click()
    await expect(dialog(page).getByRole('alert')).toContainText('finite number')
    await expect(rules(page)).toHaveCount(count)
    await expect(button(page, 'Undo')).toBeDisabled()
    await page.getByLabel('Value', { exact: true }).fill('3')
    await button(page, 'Add rule').click()
    await expect(dialog(page)).toHaveCount(0)
    for (const row of [65, 66]) await expect(cell(page, `${row}:3`)).toHaveCSS('background-color', red)
    await expect(cell(page, '64:3')).toHaveCSS('background-color', nonmatchingColor)
    await expect(cell(page, '65:2')).toHaveCSS('background-color', red)
    await seedValuesStayIntact(page)
    await open(page)
    await expect(rules(page)).toHaveCount(count + 1)
    await expect(rules(page).first()).toContainText('D65:D67')
    await button(page, 'Edit rule 1').click()
    await expect(page.getByLabel('Value', { exact: true })).toHaveValue('3')
    await button(page, 'Cancel').click()
    await button(page, 'Undo').click()
    for (const row of [65, 66]) await expect(cell(page, `${row}:3`)).toHaveCSS('background-color', blue)
    await expect(button(page, 'Undo')).toBeDisabled()
    await open(page)
    await expect(rules(page)).toHaveCount(count)
    await button(page, 'Cancel').click()
    await button(page, 'Redo').click()
    for (const row of [65, 66]) await expect(cell(page, `${row}:3`)).toHaveCSS('background-color', red)
    await seedValuesStayIntact(page)
  })

  test(`cancel conditional rule discards its range value and color draft at ${width}px`, async ({ page }) => {
    await open(page)
    const count = await rules(page).count()
    await button(page, 'Edit rule 1').click()
    await page.getByLabel('Applies to', { exact: true }).fill('D65:D67')
    await page.getByLabel('Value', { exact: true }).fill('99')
    await page.getByLabel('Highlight fill', { exact: true }).fill('#00ff00')
    await button(page, 'Cancel').click()
    await expect(dialog(page)).toHaveCount(0)
    await expect(button(page, 'Conditional formatting')).toBeFocused()
    await expect(button(page, 'Undo')).toBeDisabled()
    await expect(cell(page, '65:2')).toHaveCSS('background-color', red)
    await expect(cell(page, '65:3')).toHaveCSS('background-color', blue)
    await seedValuesStayIntact(page)
    await open(page); await expect(rules(page)).toHaveCount(count)
    await button(page, 'Edit rule 1').click()
    await expect(page.getByLabel('Applies to', { exact: true })).toHaveValue('C65:C67')
    await expect(page.getByLabel('Value', { exact: true })).toHaveValue('3')
    await expect(page.getByLabel('Highlight fill', { exact: true })).toHaveValue('#ffc7ce')
  })

  test(`conditional text color keeps fill and undoes once at ${width}px`, async ({ page }) => {
    const previous = await cell(page, '65:2').evaluate(node => getComputedStyle(node).color)
    const nonmatch = await cell(page, '64:2').evaluate(node => getComputedStyle(node).color)
    await open(page); await button(page, 'Edit rule 1').click()
    await page.getByLabel('Highlight text', { exact: true }).fill('#123456')
    await button(page, 'Save rule').click(); await expect(dialog(page)).toHaveCount(0)
    for (const row of [65, 66]) {
      await expect(cell(page, `${row}:2`)).toHaveCSS('color', 'rgb(18, 52, 86)')
      await expect(cell(page, `${row}:2`)).toHaveCSS('background-color', red)
    }
    await expect(cell(page, '64:2')).toHaveCSS('color', nonmatch)
    await expect(cell(page, '65:3')).toHaveCSS('background-color', blue)
    await seedValuesStayIntact(page)
    await button(page, 'Undo').click()
    await expect(cell(page, '65:2')).toHaveCSS('color', previous)
    await expect(button(page, 'Undo')).toBeDisabled()
    await button(page, 'Redo').click()
    await expect(cell(page, '65:2')).toHaveCSS('color', 'rgb(18, 52, 86)')
    await open(page); await button(page, 'Edit rule 1').click()
    await expect(page.getByLabel('Highlight text', { exact: true })).toHaveValue('#123456')
  })

  test(`out-of-sheet conditional range can retry without partial writes at ${width}px`, async ({ page }) => {
    await open(page)
    const count = await rules(page).count()
    await page.getByLabel('Applies to', { exact: true }).fill('C101:C102')
    await page.getByLabel('Value', { exact: true }).fill('5')
    await page.getByLabel('Highlight fill', { exact: true }).fill('#00ff00')
    await button(page, 'Add rule').click()
    await expect(dialog(page).getByRole('alert')).toContainText('inside this worksheet')
    await expect(page.getByLabel('Applies to', { exact: true })).toHaveValue('C101:C102')
    await expect(rules(page)).toHaveCount(count)
    await expect(button(page, 'Undo')).toBeDisabled()
    await expect(cell(page, '66:2')).toHaveCSS('background-color', red)
    await page.getByLabel('Applies to', { exact: true }).fill('C65:C67')
    await button(page, 'Add rule').click(); await expect(dialog(page)).toHaveCount(0)
    await expect(cell(page, '65:2')).toHaveCSS('background-color', red)
    await expect(cell(page, '66:2')).toHaveCSS('background-color', green)
    await expect(cell(page, '65:3')).toHaveCSS('background-color', blue)
    await seedValuesStayIntact(page)
    await button(page, 'Undo').click()
    await expect(cell(page, '66:2')).toHaveCSS('background-color', red)
    await expect(button(page, 'Undo')).toBeDisabled()
    await button(page, 'Redo').click()
    await expect(cell(page, '66:2')).toHaveCSS('background-color', green)
  })

  test(`editing a seeded conditional rule keeps one rule and one undo step at ${width}px`, async ({ page }) => {
    const originalColor = await cell(page, '64:2').evaluate(node => getComputedStyle(node).backgroundColor)
    await open(page)
    const count = await rules(page).count()
    await button(page, 'Edit rule 1').click()
    await expect(page.getByLabel('Applies to', { exact: true })).toHaveValue('C65:C67')
    await expect(page.getByLabel('Value', { exact: true })).toHaveValue('3')
    // 取消编辑只丢弃草稿，不能提前修改原生规则或产生历史。
    await page.getByLabel('Value', { exact: true }).fill('99')
    await button(page, 'Cancel').click()
    await expect(cell(page, '65:2')).toHaveCSS('background-color', red)
    await expect(button(page, 'Undo')).toBeDisabled()
    await open(page)
    await button(page, 'Edit rule 1').click()
    await expect(page.getByLabel('Value', { exact: true })).toHaveValue('3')
    await page.getByLabel('Applies to', { exact: true }).fill('D65:D67')
    await page.getByLabel('Value', { exact: true }).fill('5')
    await page.getByLabel('Highlight fill', { exact: true }).fill('#00ff00')
    await button(page, 'Save rule').click()
    await expect(dialog(page)).toHaveCount(0)
    for (const row of [65, 66]) await expect(cell(page, `${row}:2`)).toHaveCSS('background-color', originalColor)
    await expect(cell(page, '65:3')).toHaveCSS('background-color', blue)
    await expect(cell(page, '66:3')).toHaveCSS('background-color', green)
    await seedValuesStayIntact(page)
    await open(page)
    await expect(rules(page)).toHaveCount(count)
    await expect(rules(page).first()).toContainText('D65:D67')
    await button(page, 'Edit rule 1').click()
    await expect(page.getByLabel('Value', { exact: true })).toHaveValue('5')
    await expect(page.getByLabel('Highlight fill', { exact: true })).toHaveValue('#00ff00')
    await button(page, 'Cancel').click()
    await button(page, 'Undo').click()
    for (const row of [65, 66]) {
      await expect(cell(page, `${row}:2`)).toHaveCSS('background-color', red)
      await expect(cell(page, `${row}:3`)).toHaveCSS('background-color', blue)
    }
    await expect(button(page, 'Undo')).toBeDisabled()
    await button(page, 'Redo').click()
    await expect(cell(page, '65:2')).toHaveCSS('background-color', originalColor)
    await expect(cell(page, '66:3')).toHaveCSS('background-color', green)
  })

  test(`deleting a seeded conditional rule preserves other rules at ${width}px`, async ({ page }) => {
    const originalColor = await cell(page, '64:2').evaluate(node => getComputedStyle(node).backgroundColor)
    await open(page)
    const count = await rules(page).count()
    await expect(rules(page).first()).toContainText('C65:C67')
    await expect(rules(page).first()).toContainText('Greater than 3')
    await button(page, 'Delete rule 1').click()
    await expect(dialog(page)).toHaveCount(0)
    for (const row of [65, 66]) {
      await expect(cell(page, `${row}:2`)).toHaveCSS('background-color', originalColor)
      await expect(cell(page, `${row}:3`)).toHaveCSS('background-color', blue)
    }
    await seedValuesStayIntact(page)
    await open(page)
    await expect(rules(page)).toHaveCount(count - 1)
    // 原第二条仍停用：删除一条不能误删同范围规则，也不能顺手启用它。
    await expect(button(page, 'Enable rule 1')).toBeEnabled()
    await expect(rules(page).first()).toContainText('Greater than 1')
    await button(page, 'Cancel').click()
    await button(page, 'Undo').click()
    for (const row of [65, 66]) await expect(cell(page, `${row}:2`)).toHaveCSS('background-color', red)
    await expect(button(page, 'Undo')).toBeDisabled()
    await open(page)
    await expect(rules(page)).toHaveCount(count)
    await expect(rules(page).first()).toContainText('Greater than 3')
    await button(page, 'Cancel').click()
    await button(page, 'Redo').click()
    for (const row of [65, 66]) await expect(cell(page, `${row}:2`)).toHaveCSS('background-color', originalColor)
    await seedValuesStayIntact(page)
  })
})
