import { expect, test, type Page } from '@playwright/test'

const button = (page: Page, name: string) => page.getByRole('button', { name, exact: true })
const dialog = (page: Page) => page.getByRole('dialog', { name: 'Conditional formatting', exact: true })
const cell = (page: Page, coord: string) => page.locator(`td[data-cell="${coord}"]`)
const red = 'rgb(255, 199, 206)'
const blue = 'rgb(217, 234, 247)'
async function open(page: Page) {
  await button(page, 'Conditional formatting').click()
  await expect(dialog(page)).toBeVisible()
}
async function manage(page: Page, label: string) {
  await open(page)
  await button(page, label).click()
  await expect(dialog(page)).toHaveCount(0)
}
test.beforeEach(async ({ page }) => {
  await page.goto('/')
  await expect(cell(page, '1:0')).toHaveText('SO-10001')
  await page.getByRole('tab', { name: 'Summary', exact: true }).click()
  await button(page, 'Go to').click()
  await page.getByLabel('Reference', { exact: true }).fill('C65:E67')
  await button(page, 'Go').click()
  await expect(page.getByRole('dialog')).toHaveCount(0)
  await expect(cell(page, '65:2')).toHaveCSS('background-color', red)
})

test('copy is an independent native rule; edit and each undo preserve the original', async ({ page }) => {
  await manage(page, 'Copy rule 1')
  await open(page)
  await expect(dialog(page).getByRole('listitem')).toHaveCount(13)
  await button(page, 'Edit rule 2').click()
  await page.getByLabel('Applies to', { exact: true }).fill('D65:D67')
  await page.getByLabel('Value', { exact: true }).fill('5')
  await page.getByLabel('Highlight fill').fill('#00ff00')
  await button(page, 'Save rule').click()
  await expect(dialog(page)).toHaveCount(0)
  await expect(cell(page, '66:3')).toHaveCSS('background-color', 'rgb(0, 255, 0)')
  await expect(cell(page, '65:3')).not.toHaveCSS('background-color', 'rgb(0, 255, 0)')
  await expect(cell(page, '65:2')).toHaveCSS('background-color', red)
  await button(page, 'Undo').click()
  await expect(cell(page, '66:3')).not.toHaveCSS('background-color', 'rgb(0, 255, 0)')
  await button(page, 'Undo').click()
  await open(page)
  await expect(dialog(page).getByRole('listitem')).toHaveCount(12)
  await button(page, 'Cancel').click()
  await button(page, 'Redo').click()
  await open(page)
  await expect(dialog(page).getByRole('listitem')).toHaveCount(13)
})

test('seed enable and disable reveal lower rules; undo and redo restore the displayed winner', async ({ page }) => {
  await expect(cell(page, '64:2')).not.toHaveCSS('background-color', blue)
  await expect(button(page, 'Undo')).toBeDisabled()
  await manage(page, 'Enable rule 2')
  await expect(cell(page, '64:2')).toHaveCSS('background-color', blue)
  await expect(cell(page, '65:2')).toHaveCSS('background-color', red)
  await manage(page, 'Disable rule 1')
  await expect(cell(page, '65:2')).toHaveCSS('background-color', blue)
  await button(page, 'Undo').click()
  await expect(cell(page, '65:2')).toHaveCSS('background-color', red)
  await button(page, 'Undo').click()
  await expect(cell(page, '64:2')).not.toHaveCSS('background-color', blue)
  await button(page, 'Redo').click()
  await expect(cell(page, '64:2')).toHaveCSS('background-color', blue)
})

test('moving up and down changes priority in one undoable action, with disabled boundary buttons', async ({ page }) => {
  await manage(page, 'Enable rule 2')
  await manage(page, 'Move rule 2 up')
  await expect(cell(page, '65:2')).toHaveCSS('background-color', blue)
  await open(page)
  await expect(dialog(page).getByRole('listitem').first()).toContainText('Greater than 1')
  await expect(button(page, 'Move rule 1 up')).toBeDisabled()
  await expect(button(page, 'Move rule 12 down')).toBeDisabled()
  await button(page, 'Cancel').click()
  await button(page, 'Undo').click()
  await expect(cell(page, '65:2')).toHaveCSS('background-color', red)
  await button(page, 'Redo').click()
  await expect(cell(page, '65:2')).toHaveCSS('background-color', blue)
  await manage(page, 'Move rule 1 down')
  await expect(cell(page, '65:2')).toHaveCSS('background-color', red)
})

test('copying a disabled rule preserves its state; enabling only the copy leaves the original disabled', async ({ page }) => {
  await manage(page, 'Copy rule 2')
  await open(page)
  await expect(button(page, 'Enable rule 2')).toBeEnabled()
  await expect(button(page, 'Enable rule 3')).toBeEnabled()
  await button(page, 'Cancel').click()
  await manage(page, 'Enable rule 3')
  await expect(cell(page, '64:2')).toHaveCSS('background-color', blue)
  await open(page)
  await expect(button(page, 'Enable rule 2')).toBeEnabled()
  await expect(button(page, 'Disable rule 3')).toBeEnabled()
  await button(page, 'Cancel').click()
  await manage(page, 'Delete rule 3')
  await expect(cell(page, '64:2')).not.toHaveCSS('background-color', blue)
})

for (const width of [1280, 390]) test(`management controls fit at ${width}px with keyboard focus`, async ({ page }, info) => {
  const errors: string[] = []
  page.on('pageerror', (error) => errors.push(error.message))
  await page.setViewportSize({ width, height: 800 })
  await open(page)
  await expect(page.getByLabel('Applies to', { exact: true })).toBeFocused()
  expect(await dialog(page).evaluate((node) => node.scrollWidth <= node.clientWidth)).toBe(true)
  await page.screenshot({ path: info.outputPath(`conditional-management-${width}.png`), fullPage: true })
  await page.getByLabel('Applies to', { exact: true }).press('Escape')
  await expect(button(page, 'Conditional formatting')).toBeFocused()
  expect(errors).toEqual([])
})

for (const width of [1280, 390]) test.describe(`${width}px independent rule actions`, () => {
  test.use({ viewport: { width, height: 850 } })

  test(`enable one conditional rule without changing priority at ${width}px`, async ({ page }) => {
    const original = await cell(page, '64:2').evaluate(node => getComputedStyle(node).backgroundColor)
    await open(page)
    const count = await dialog(page).getByRole('listitem').count()
    await button(page, 'Enable rule 2').click()
    await expect(dialog(page)).toHaveCount(0)
    await expect(cell(page, '64:2')).toHaveCSS('background-color', blue)
    await expect(cell(page, '65:2')).toHaveCSS('background-color', red)
    await expect(cell(page, '65:3')).toHaveCSS('background-color', blue)
    await open(page)
    await expect(dialog(page).getByRole('listitem')).toHaveCount(count)
    await expect(button(page, 'Disable rule 2')).toBeEnabled()
    await expect(dialog(page).getByRole('listitem').first()).toContainText('Greater than 3')
    await button(page, 'Cancel').click()
    await button(page, 'Undo').click()
    await expect(cell(page, '64:2')).toHaveCSS('background-color', original)
    await expect(button(page, 'Undo')).toBeDisabled()
    await button(page, 'Redo').click()
    await expect(cell(page, '64:2')).toHaveCSS('background-color', blue)
    await expect(cell(page, '64:2')).toHaveText('2')
  })

  test(`disable one conditional rule without deleting it at ${width}px`, async ({ page }) => {
    const original = await cell(page, '64:2').evaluate(node => getComputedStyle(node).backgroundColor)
    await open(page)
    const count = await dialog(page).getByRole('listitem').count()
    await button(page, 'Disable rule 1').click()
    await expect(dialog(page)).toHaveCount(0)
    for (const row of [65, 66]) await expect(cell(page, `${row}:2`)).toHaveCSS('background-color', original)
    await expect(cell(page, '65:3')).toHaveCSS('background-color', blue)
    await open(page)
    await expect(dialog(page).getByRole('listitem')).toHaveCount(count)
    await expect(button(page, 'Enable rule 1')).toBeEnabled()
    await expect(button(page, 'Enable rule 2')).toBeEnabled()
    await button(page, 'Cancel').click()
    await button(page, 'Undo').click()
    await expect(cell(page, '65:2')).toHaveCSS('background-color', red)
    await expect(button(page, 'Undo')).toBeDisabled()
    await button(page, 'Redo').click()
    await expect(cell(page, '65:2')).toHaveCSS('background-color', original)
    await expect(cell(page, '65:2')).toHaveText('4')
  })

  test(`copy a conditional rule preserves its disabled state at ${width}px`, async ({ page }) => {
    const original = await cell(page, '64:2').evaluate(node => getComputedStyle(node).backgroundColor)
    await open(page)
    const count = await dialog(page).getByRole('listitem').count()
    await button(page, 'Copy rule 2').click()
    await expect(dialog(page)).toHaveCount(0)
    await expect(cell(page, '64:2')).toHaveCSS('background-color', original)
    await expect(cell(page, '65:2')).toHaveCSS('background-color', red)
    await open(page)
    await expect(dialog(page).getByRole('listitem')).toHaveCount(count + 1)
    for (const index of [2, 3]) {
      await expect(button(page, `Enable rule ${index}`)).toBeEnabled()
      await expect(dialog(page).getByRole('listitem').nth(index - 1)).toContainText('C65:C67')
    }
    await button(page, 'Cancel').click()
    await button(page, 'Undo').click()
    await expect(button(page, 'Undo')).toBeDisabled()
    await open(page)
    await expect(dialog(page).getByRole('listitem')).toHaveCount(count)
    await button(page, 'Cancel').click()
    await button(page, 'Redo').click()
    await open(page)
    await expect(dialog(page).getByRole('listitem')).toHaveCount(count + 1)
    await expect(button(page, 'Enable rule 3')).toBeEnabled()
  })

  test(`move a conditional rule up changes only its priority at ${width}px`, async ({ page }) => {
    await manage(page, 'Enable rule 2')
    await manage(page, 'Move rule 2 up')
    await expect(cell(page, '65:2')).toHaveCSS('background-color', blue)
    await expect(cell(page, '65:3')).toHaveCSS('background-color', blue)
    await open(page)
    await expect(dialog(page).getByRole('listitem').first()).toContainText('Greater than 1')
    await expect(button(page, 'Move rule 1 up')).toBeDisabled()
    await button(page, 'Cancel').click()
    await button(page, 'Undo').click()
    await expect(cell(page, '65:2')).toHaveCSS('background-color', red)
    await expect(cell(page, '64:2')).toHaveCSS('background-color', blue)
    await button(page, 'Redo').click()
    await expect(cell(page, '65:2')).toHaveCSS('background-color', blue)
    await expect(cell(page, '65:2')).toHaveText('4')
  })

  test(`move a conditional rule down changes only its priority at ${width}px`, async ({ page }) => {
    await manage(page, 'Enable rule 2')
    await manage(page, 'Move rule 1 down')
    await expect(cell(page, '65:2')).toHaveCSS('background-color', blue)
    await open(page)
    await expect(dialog(page).getByRole('listitem').nth(1)).toContainText('Greater than 3')
    const count = await dialog(page).getByRole('listitem').count()
    await expect(button(page, `Move rule ${count} down`)).toBeDisabled()
    await button(page, 'Cancel').click()
    await button(page, 'Undo').click()
    await expect(cell(page, '65:2')).toHaveCSS('background-color', red)
    await expect(cell(page, '64:2')).toHaveCSS('background-color', blue)
    await button(page, 'Redo').click()
    await expect(cell(page, '65:2')).toHaveCSS('background-color', blue)
    await expect(cell(page, '65:3')).toHaveText('4')
  })

  test(`new conditional rule resets an edited draft without writing at ${width}px`, async ({ page }) => {
    await open(page)
    const count = await dialog(page).getByRole('listitem').count()
    await button(page, 'Edit rule 1').click()
    await page.getByLabel('Value', { exact: true }).fill('99')
    await page.getByLabel('Highlight fill', { exact: true }).fill('#00ff00')
    await button(page, 'New rule').click()
    await expect(page.getByLabel('Value', { exact: true })).toHaveValue('')
    await expect(page.getByLabel('Highlight fill', { exact: true })).toHaveValue('#ffc7ce')
    await expect(page.getByLabel('Applies to', { exact: true })).toHaveValue('C65:E67')
    await expect(button(page, 'Add rule')).toBeVisible()
    await expect(button(page, 'Save rule')).toHaveCount(0)
    await expect(dialog(page).getByRole('listitem')).toHaveCount(count)
    await button(page, 'Cancel').click()
    await expect(button(page, 'Undo')).toBeDisabled()
    await expect(cell(page, '65:2')).toHaveCSS('background-color', red)
    await open(page)
    await button(page, 'Edit rule 1').click()
    await expect(page.getByLabel('Value', { exact: true })).toHaveValue('3')
  })
})
