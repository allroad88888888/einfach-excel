import { expect, test } from '@playwright/test'
import { showRibbonItem } from '../support/ribbon'

test('Chinese Enter applies a diagonal after protection is removed', async ({ page }, info) => {
  await page.setViewportSize({ width: 390, height: 850 })
  await page.goto('/?locale=zh&plugins=cell-appearance')
  const target = page.locator('td[data-cell="1:1"]')
  await expect(target).toHaveText('Acme Co.')
  const button = (name: string) => page.getByRole('button', { name, exact: true })
  const name = page.getByRole('textbox', { name: '名称框', exact: true })
  await name.fill('B2'); await name.press('Enter')
  await showRibbonItem(page, 'data.worksheet-protection')
  await button('工作表保护').click(); await button('保护工作表').click(); await button('关闭').click()
  await showRibbonItem(page, 'format.border-settings'); await button('边框设置').focus()
  await page.keyboard.press('Enter')
  const position = page.getByRole('combobox').filter({ has: page.getByRole('option', { name: '下斜线', exact: true }) })
  await expect(position).toBeFocused(); await position.selectOption('diagonal-down')
  await button('应用边框').focus(); await page.keyboard.press('Enter')
  await expect(page.getByRole('dialog').getByRole('alert')).toBeVisible()
  await expect(target.locator('[data-diagonal]')).toHaveCount(0)
  await button('取消').click()
  await showRibbonItem(page, 'data.worksheet-protection')
  await button('工作表保护').click(); await button('取消工作表保护').click(); await button('关闭').click()
  await showRibbonItem(page, 'format.border-settings'); await button('边框设置').focus(); await page.keyboard.press('Enter')
  await position.selectOption('diagonal-down'); await button('应用边框').focus(); await page.keyboard.press('Enter')
  await expect(target.locator('[data-diagonal="diagDown"]')).toHaveCount(1)
  await expect(target).toHaveText('Acme Co.')
  await expect(button('边框设置')).toBeFocused()
  await info.attach('diagonal-zh-390.png', { body: await page.screenshot(), contentType: 'image/png' })
  await button('撤销').click(); await expect(target.locator('[data-diagonal]')).toHaveCount(0)
  await expect(button('撤销')).toBeDisabled()
  expect(await page.evaluate(() => document.documentElement.scrollWidth)).toBe(390)
})
