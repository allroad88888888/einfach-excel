import { expect, test } from '@playwright/test'
import { select } from '../support/clipboard'
import { showRibbonItem } from '../support/ribbon'
import { downloadDateFile as downloadFile } from '../support/conditional-dates'
import { applyBaseline, baselineButton as button, baselineCell as cell,
  baselineGlyphBox, startBaseline } from '../support/font-baseline'

test('Superscript raises selected cell text without changing values or nominal font size', async ({ page }, info) => {
  await startBaseline(page)
  await select(page, 'G2', '1:6')
  const formula = await page.getByRole('textbox', { name: 'Active cell value' }).inputValue()
  const before = await baselineGlyphBox(cell(page, '1:1'))
  const numericBefore = await baselineGlyphBox(cell(page, '1:4'))
  await select(page, 'B2:G2', '1:1')
  await applyBaseline(page, 'Superscript')
  await expect(cell(page, '1:1').locator('[data-font-baseline="superscript"]')).toHaveText('Acme Co.')
  await expect(cell(page, '1:1')).toHaveCSS('font-size', '12px')
  await expect(cell(page, '1:1')).toHaveCSS('font-style', 'italic')
  await expect(cell(page, '1:4')).toHaveText('1')
  await expect(cell(page, '1:5')).toHaveText('79')
  await expect(cell(page, '2:1').locator('[data-font-baseline]')).toHaveCount(0)
  const after = await baselineGlyphBox(cell(page, '1:1'))
  expect(after.height).toBeLessThan(before.height * 0.8)
  expect(after.bottom).toBeLessThan(before.bottom - 1)
  expect((await baselineGlyphBox(cell(page, '1:4'))).bottom).toBeLessThan(numericBefore.bottom - 1)
  await select(page, 'G2', '1:6')
  await expect(page.getByRole('textbox', { name: 'Active cell value' })).toHaveValue(formula)
  await showRibbonItem(page, 'format.font-size')
  await expect(page.getByRole('combobox', { name: 'Font size', exact: true })).toHaveValue('12')
  const native = JSON.parse((await downloadFile(page)).toString())
  const raw = native.workbook.cells.filter((entry: { sheet: number; addr: string }) =>
    entry.sheet === 0 && ['B2', 'E2', 'G2'].includes(entry.addr))
  expect(raw.find((entry: { addr: string }) => entry.addr === 'B2')).toMatchObject({ kind: 'text', value: 'Acme Co.' })
  expect(raw.find((entry: { addr: string }) => entry.addr === 'E2')).toMatchObject({ kind: 'number', value: 1 })
  expect(raw.find((entry: { addr: string }) => entry.addr === 'G2')).toMatchObject({ kind: 'formula', value: formula })
  await button(page, 'Undo').click()
  await expect(cell(page, '1:1').locator('[data-font-baseline]')).toHaveCount(0)
  await expect(button(page, 'Undo')).toBeDisabled()
  await button(page, 'Redo').click()
  await expect(cell(page, '1:1').locator('[data-font-baseline="superscript"]')).toBeVisible()
  await page.screenshot({ path: info.outputPath('font-baseline-desktop.png') })
})

test('Subscript replaces superscript and restores normal text in one undoable step', async ({ page }) => {
  await startBaseline(page)
  await select(page, 'B2', '1:1')
  const normal = await baselineGlyphBox(cell(page, '1:1'))
  await applyBaseline(page, 'Superscript')
  const superscript = await baselineGlyphBox(cell(page, '1:1'))
  await applyBaseline(page, 'Subscript')
  const subscript = await baselineGlyphBox(cell(page, '1:1'))
  expect(subscript.bottom).toBeGreaterThan(superscript.bottom + 1)
  expect(subscript.height).toBeLessThan(normal.height * 0.8)
  await expect(button(page, 'Superscript')).toHaveAttribute('aria-pressed', 'false')
  await expect(button(page, 'Subscript')).toHaveAttribute('aria-pressed', 'true')
  await button(page, 'Undo').click()
  await expect(cell(page, '1:1').locator('[data-font-baseline="superscript"]')).toBeVisible()
  await button(page, 'Redo').click()
  await expect(cell(page, '1:1').locator('[data-font-baseline="subscript"]')).toBeVisible()
  await applyBaseline(page, 'Subscript')
  await expect(cell(page, '1:1').locator('[data-font-baseline]')).toHaveCount(0)
  expect((await baselineGlyphBox(cell(page, '1:1'))).height).toBeCloseTo(normal.height, 1)
  await button(page, 'Undo').click()
  await expect(cell(page, '1:1').locator('[data-font-baseline="subscript"]')).toBeVisible()
  await expect(cell(page, '1:1')).toHaveCSS('font-size', '12px')
  await expect(cell(page, '1:1')).toHaveText('Acme Co.')
  await expect(cell(page, '2:1').locator('[data-font-baseline]')).toHaveCount(0)
})

test('baseline buttons work by keyboard inside More at 390px and preserve selection', async ({ page }, info) => {
  await startBaseline(page, 390)
  await select(page, 'B2', '1:1')
  for (const effect of ['Superscript', 'Subscript'] as const) {
    await applyBaseline(page, effect, true)
    await expect(cell(page, '1:1').locator(`[data-font-baseline="${effect.toLowerCase()}"]`)).toBeVisible()
    await expect(page.locator('[data-ribbon-more]')).toHaveAttribute('aria-expanded', 'false')
    await expect(page.locator('[data-ribbon-more]')).toBeFocused()
  }
  await showRibbonItem(page, 'format.subscript')
  await expect(button(page, 'Subscript')).toBeInViewport()
  expect(await page.evaluate(() => document.documentElement.scrollWidth)).toBe(390)
  await page.screenshot({ path: info.outputPath('font-baseline-mobile.png') })
  await expect(page.getByRole('textbox', { name: 'Name box' })).toHaveValue('B2')
})

test('native baseline examples preserve numeric and formula sources beside normal references', async ({ page }) => {
  await startBaseline(page)
  await page.getByRole('tab', { name: 'Summary', exact: true }).click()
  await select(page, 'C5:D7', '4:2')
  await expect(cell(page, '4:3').locator('[data-font-baseline="superscript"]')).toHaveText('Superscript')
  await expect(cell(page, '5:3').locator('[data-font-baseline="subscript"]')).toHaveText('Subscript')
  await expect(cell(page, '6:2')).toHaveText('12345')
  await expect(cell(page, '6:3')).toHaveText('24690')
  await expect(cell(page, '4:2').locator('[data-font-baseline]')).toHaveCount(0)
  await select(page, 'D7', '6:3')
  await expect(page.getByRole('textbox', { name: 'Active cell value' })).toHaveValue('=C7*2')
  await expect(cell(page, '6:3')).toHaveCSS('font-size', '16px')
})
