import { expect, test } from '@playwright/test'
import { select } from '../support/clipboard'

for (const width of [1280, 390]) for (const action of ['Open', 'Cancel', 'Escape', 'Tab', 'Shift+Tab'])
  test(`${action} number settings keeps the native format formula and redo at ${width}px`, async ({ page }, info) => {
    await page.setViewportSize({ width, height: 850 })
    await page.goto('/e2e/fixtures/plain-sales-orders/')
    const cell = (coord: string) => page.locator(`td[data-cell="${coord}"]`)
    const button = (name: string) => page.getByRole('button', { name, exact: true })
    await expect(cell('1:0')).toHaveText('SO-10001')
    await select(page, 'E2', '1:4')
    const bar = page.getByRole('textbox', { name: 'Active cell value', exact: true })
    await bar.fill('2')
    await bar.press('Enter')
    await expect(cell('1:6')).toHaveText('158')
    await button('Undo').click()
    await select(page, 'G9', '8:6')
    await button('Number format settings').click()
    const dialog = page.getByRole('dialog', { name: 'Number format', exact: true })
    const category = dialog.getByRole('combobox', { name: 'Number format category', exact: true })
    const digits = dialog.getByRole('spinbutton', { name: 'Decimal places', exact: true })
    const preview = dialog.getByRole('status', { name: 'Number format preview', exact: true })
    await expect(category).toBeFocused()
    await expect(category).toHaveValue('number')
    await expect(digits).toHaveValue('2')
    await expect(dialog.getByRole('checkbox', { name: 'Use thousands separator' })).toBeChecked()
    await expect(preview).toHaveText('2,632.00')
    if (action === 'Open') {
      expect(await dialog.evaluate(node => node.scrollWidth <= node.clientWidth)).toBe(true)
      for (const control of await dialog.locator('input, select, button').all())
        await expect(control).toBeInViewport()
      await page.screenshot({ path: info.outputPath(`number-settings-open-${width}.png`) })
    } else {
      await category.selectOption('currency')
      await digits.fill('3')
      await dialog.getByRole('textbox', { name: 'Currency symbol', exact: true }).fill('USD ')
      await expect(preview).toHaveText('USD 2,632.000')
      await expect(cell('8:6')).toHaveText('2,632.00')
    }
    if (action === 'Tab' || action === 'Shift+Tab') {
      const last = dialog.getByRole('button', { name: 'Apply number format', exact: true })
      await (action === 'Tab' ? last : category).focus()
      await page.keyboard.press(action)
      await expect(action === 'Tab' ? category : last).toBeFocused()
    }
    if (action === 'Escape') await page.keyboard.press('Escape')
    else await button('Cancel').click()
    await expect(dialog).toHaveCount(0)
    await expect(button('Number format settings')).toBeFocused()
    await expect(bar).toHaveValue('=E9*F9')
    await expect(cell('8:6')).toHaveText('2,632.00')
    await expect(cell('8:5')).toHaveText('329')
    await expect(cell('9:6')).toHaveText('1341')
    await expect(button('Undo')).toBeDisabled()
    await button('Number format settings').click()
    await expect(category).toHaveValue('number')
    await expect(digits).toHaveValue('2')
    await expect(dialog.getByRole('checkbox', { name: 'Use thousands separator' })).toBeChecked()
    await button('Cancel').click()
    await button('Redo').click()
    await select(page, 'G2', '1:6')
    await expect(cell('1:6')).toHaveText('158')
    await expect(cell('1:6')).toHaveCSS('font-family', 'Georgia')
  })
