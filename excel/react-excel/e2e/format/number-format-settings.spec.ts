import { expect, test, type Page } from '@playwright/test'
import { select } from '../support/clipboard'

const cell = (page: Page, coord: string) => page.locator(`td[data-cell="${coord}"]`)
const opener = (page: Page) => page.getByRole('button', { name: 'Number format settings', exact: true })
async function open(page: Page, category?: string, digits?: string) {
  await opener(page).click()
  if (category) await page.getByLabel('Number format category').selectOption(category)
  if (digits !== undefined) await page.getByRole('spinbutton', { name: 'Decimal places', exact: true }).fill(digits)
}
async function apply(page: Page) {
  await page.getByRole('button', { name: 'Apply number format', exact: true }).click()
  await expect(page.getByRole('dialog', { name: 'Number format', exact: true })).toHaveCount(0)
}
test.beforeEach(async ({ page }) => {
  await page.goto('/')
  await expect(cell(page, '1:0')).toHaveText('SO-10001')
})

test('three categories reopen their native seed settings without changing values', async ({ page }) => {
  for (const [address, coord, category, digits, display] of [
    ['G12', '11:6', 'number', '3', '979.000'],
    ['O12', '11:14', 'percent', '1', '0.0%'],
    ['P12', '11:15', 'currency', '3', '€195.800'],
  ]) {
    await select(page, address!, coord!)
    await expect(cell(page, coord!)).toHaveText(display!)
    await open(page)
    await expect(page.getByLabel('Number format category')).toHaveValue(category!)
    await expect(page.getByRole('spinbutton', { name: 'Decimal places', exact: true })).toHaveValue(digits!)
    if (category === 'currency') await expect(page.getByLabel('Currency symbol')).toHaveValue('€')
    await page.keyboard.press('Escape')
  }
  await expect(page.getByRole('button', { name: 'Undo', exact: true })).toBeDisabled()
})

test('number settings preserve formulas and apply grouping and precision in one history entry', async ({ page }) => {
  await select(page, 'G9:G10', '8:6')
  await open(page, 'number', '3')
  await page.getByLabel('Use thousands separator').check()
  await expect(cell(page, '8:6')).toHaveText('2,632.00')
  await apply(page)
  await expect(cell(page, '8:6')).toHaveText('2,632.000')
  await expect(cell(page, '9:6')).toHaveText('1,341.000')
  await page.getByRole('button', { name: 'Undo', exact: true }).click()
  await expect(cell(page, '8:6')).toHaveText('2,632.00')
  await expect(cell(page, '9:6')).toHaveText('1341')
  await expect(page.getByRole('button', { name: 'Undo', exact: true })).toBeDisabled()
  await page.getByRole('button', { name: 'Redo', exact: true }).click()
  await select(page, 'G9', '8:6')
  await expect(page.getByRole('textbox', { name: 'Active cell value' })).toHaveValue('=E9*F9')
  await open(page)
  await page.getByLabel('Use thousands separator').uncheck()
  await apply(page)
  await expect(cell(page, '8:6')).toHaveText('2632.000')
})

test('percent settings change display only, retain raw number and integrate with precision buttons', async ({ page }) => {
  await select(page, 'O4', '3:14')
  await open(page, 'percent', '3')
  await expect(page.getByRole('checkbox')).toHaveCount(0)
  await apply(page)
  await expect(cell(page, '3:14')).toHaveText('10.000%')
  await expect(page.getByRole('textbox', { name: 'Active cell value' })).toHaveValue('0.1')
  await page.getByRole('button', { name: 'Increase decimal places' }).click()
  await expect(cell(page, '3:14')).toHaveText('10.0000%')
  await select(page, 'A900', '899:0')
  await select(page, 'O4', '3:14')
  await open(page)
  await expect(page.getByLabel('Number format category')).toHaveValue('percent')
  await expect(page.getByRole('spinbutton', { name: 'Decimal places', exact: true })).toHaveValue('4')
  await page.getByRole('button', { name: 'Cancel', exact: true }).click()
  await page.getByRole('button', { name: 'General format', exact: true }).click()
  await expect(cell(page, '3:14')).toHaveText('0.1')
})

test('currency uses the chosen literal symbol or none without dropping bold or raw precision', async ({ page }) => {
  await select(page, 'P3', '2:15')
  await open(page, 'currency', '3')
  await page.getByLabel('Currency symbol').fill('€')
  await apply(page)
  await expect(cell(page, '2:15')).toHaveText('€125.020')
  await expect(cell(page, '2:15')).toHaveCSS('font-weight', '700')
  await expect(page.getByRole('textbox', { name: 'Active cell value' })).toHaveValue('125.02')
  await open(page)
  await page.getByLabel('Currency symbol').fill('')
  await apply(page)
  await expect(cell(page, '2:15')).toHaveText('125.020')
  await page.getByRole('button', { name: 'Undo', exact: true }).click()
  await expect(cell(page, '2:15')).toHaveText('€125.020')
  await page.getByRole('button', { name: 'Undo', exact: true }).click()
  await expect(cell(page, '2:15')).toHaveText('$125')
  await expect(page.getByRole('button', { name: 'Undo', exact: true })).toBeDisabled()
})

test('later column settings override row formatting and reach the final record', async ({ page }) => {
  await page.getByRole('button', { name: 'Select row 2', exact: true }).click()
  await open(page, 'number', '3')
  await apply(page)
  await page.getByRole('columnheader', { name: 'Select column F', exact: true }).click()
  await open(page, 'currency', '1')
  await page.getByLabel('Currency symbol').fill('¥')
  await apply(page)
  await expect(cell(page, '1:5')).toHaveText('¥79.0')
  await expect(cell(page, '1:4')).toHaveText('1.000')
  await select(page, 'F1001', '1000:5')
  await expect(cell(page, '1000:5')).toHaveText('¥119.0')
  await page.getByRole('button', { name: 'Undo', exact: true }).click()
  await expect(cell(page, '1000:5')).toHaveText('119')
  await select(page, 'F2', '1:5')
  await expect(cell(page, '1:5')).toHaveText('79.000')
})

test('format settings keep text and boolean types and both editing inputs block the dialog', async ({ page }) => {
  await select(page, 'A4:H4', '3:0')
  await open(page, 'percent', '2')
  await apply(page)
  await expect(cell(page, '3:0')).toHaveText('00123')
  await expect(cell(page, '3:7')).toHaveText('TRUE')
  await select(page, 'B3', '2:1')
  await cell(page, '2:1').dblclick()
  const editor = page.getByRole('textbox', { name: 'Cell editor', exact: true })
  await editor.fill('Unsaved')
  await expect(opener(page)).toBeDisabled()
  await editor.press('Escape')
  const formula = page.getByRole('textbox', { name: 'Active cell value' })
  await formula.fill('Another draft')
  await expect(opener(page)).toBeDisabled()
  await formula.press('Escape')
  await expect(opener(page)).toBeEnabled()
  await expect(cell(page, '2:1')).toHaveText('Northwind')
})

test('invalid precision and cancellation create no native history', async ({ page }) => {
  await select(page, 'F3', '2:5')
  await open(page)
  for (const value of ['', '-1', '1.5', '16']) {
    await page.getByRole('spinbutton', { name: 'Decimal places', exact: true }).fill(value)
    await page.getByRole('button', { name: 'Apply number format' }).click()
    await expect(page.getByRole('alert')).toContainText('0 to 15')
  }
  await page.getByRole('button', { name: 'Cancel', exact: true }).click()
  await expect(cell(page, '2:5')).toHaveText('329')
  await expect(page.getByRole('button', { name: 'Undo', exact: true })).toBeDisabled()
  await open(page, 'number', '0')
  await apply(page)
  await open(page)
  await expect(page.getByRole('spinbutton', { name: 'Decimal places', exact: true })).toHaveValue('0')
})

test('currency reaches every frozen merged fragment and undo preserves the merge', async ({ page }) => {
  await select(page, 'F3', '2:5')
  await page.getByRole('combobox', { name: 'Freeze panes' }).selectOption('selection')
  await select(page, 'E2:G4', '1:4')
  await page.getByRole('combobox', { name: 'Merge cells', exact: true }).selectOption('merge')
  await page.getByRole('alertdialog').getByRole('button', { name: 'Merge cells', exact: true }).click()
  const fragments = page.locator('[data-merged-cell="true"]')
  await expect(fragments).toHaveCount(4)
  await open(page, 'currency', '3')
  await page.getByLabel('Currency symbol').fill('€')
  await apply(page)
  for (const fragment of await fragments.all()) {
    await expect(fragment).toHaveText('€1.000')
    await expect(fragment).toHaveCSS('color', 'rgb(192, 0, 0)')
  }
  await page.getByRole('button', { name: 'Undo', exact: true }).click()
  await expect(fragments).toHaveCount(4)
  for (const fragment of await fragments.all()) await expect(fragment).toHaveText('1')
})

test('zero and negative numbers accept 0 and 15 decimal places without rounding the stored value', async ({ page }) => {
  await select(page, 'F3', '2:5')
  const formula = page.getByRole('textbox', { name: 'Active cell value' })
  await formula.fill('-1234.25')
  await formula.press('Enter')
  await expect(cell(page, '2:5')).toHaveText('-1234.25')
  await select(page, 'F3', '2:5')
  await open(page, 'currency', '15')
  await page.getByLabel('Currency symbol').fill('€')
  await apply(page)
  await expect(cell(page, '2:5')).toHaveText('€-1,234.250000000000000')
  await expect(formula).toHaveValue('-1234.25')
  await open(page, 'number', '0')
  await apply(page)
  await expect(cell(page, '2:5')).toHaveText('-1234')
  await expect(formula).toHaveValue('-1234.25')
  await select(page, 'O12', '11:14')
  await open(page, 'percent', '15')
  await apply(page)
  await expect(cell(page, '11:14')).toHaveText('0.000000000000000%')
  await expect(formula).toHaveValue('0')
})

test('errors keep their native tokens and empty cells retain a format for later input', async ({ page }) => {
  await select(page, 'F3', '2:5')
  const formula = page.getByRole('textbox', { name: 'Active cell value' })
  await formula.fill('=1/0')
  await formula.press('Enter')
  await expect(cell(page, '2:5')).toHaveText('#DIV/0!')
  await select(page, 'F3', '2:5')
  await open(page, 'currency', '2')
  await page.getByLabel('Currency symbol').fill('€')
  await apply(page)
  await expect(cell(page, '2:5')).toHaveText('#DIV/0!')
  await expect(formula).toHaveValue('=1/0')
  await page.getByRole('button', { name: 'Clear contents', exact: true }).click()
  await expect(cell(page, '2:5')).toHaveText('')
  await open(page, 'currency', '3')
  await apply(page)
  await expect(cell(page, '2:5')).toHaveText('')
  await formula.fill('2')
  await formula.press('Enter')
  await expect(cell(page, '2:5')).toHaveText('€2.000')
})

