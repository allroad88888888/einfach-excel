import { expect, test } from '@playwright/test'
import { select } from '../support/clipboard'

for (const width of [1280, 390]) for (const kind of ['fill', 'text'])
  for (const action of ['Open', 'Tab', 'Shift+Tab'])
    test(`${action} ${kind} palette preserves native formulas colors and redo at ${width}px`, async ({ page }, info) => {
      await page.setViewportSize({ width, height: 850 })
      await page.goto('/e2e/fixtures/plain-sales-orders/')
      const cell = (coord: string) => page.locator(`td[data-cell="${coord}"]`)
      const button = (name: string) => page.getByRole('button', { name, exact: true })
      await expect(cell('1:0')).toHaveText('SO-10001')
      await select(page, 'E2', '1:4')
      const bar = page.getByRole('textbox', { name: 'Active cell value', exact: true })
      await bar.fill('2')
      await bar.press('Enter')
      await expect(cell('1:6')).toHaveText('158')
      await button('Undo').click()
      await select(page, 'G2', '1:6')
      const colors = await cell('1:6').evaluate(node => {
        const style = getComputedStyle(node)
        return { fill: style.backgroundColor, text: style.color }
      })
      const opener = button(`Choose ${kind} color`)
      await opener.click()
      const dialog = page.getByRole('dialog', { name: kind === 'fill' ? 'Fill color' : 'Text color', exact: true })
      const first = dialog.getByRole('button', { name: 'Close color palette', exact: true })
      const last = dialog.getByRole('button', { name: 'Apply', exact: true })
      const hex = dialog.getByRole('textbox', { name: 'Color hex', exact: true })
      await expect(first).toBeFocused()
      const original = await hex.inputValue()
      if (action === 'Open') {
        expect(await dialog.evaluate(node => node.scrollWidth <= node.clientWidth)).toBe(true)
        const box = (await dialog.boundingBox())!
        expect(box.x).toBeGreaterThanOrEqual(0)
        expect(box.x + box.width).toBeLessThanOrEqual(width)
        await page.screenshot({ path: info.outputPath(`${kind}-palette-open-${width}.png`) })
      } else {
        await (action === 'Tab' ? last : first).focus()
        await page.keyboard.press(action)
        await expect(action === 'Tab' ? first : last).toBeFocused()
      }
      await hex.fill('#123abc')
      await first.click()
      await expect(dialog).toHaveCount(0)
      await expect(opener).toBeFocused()
      await expect(page.getByRole('textbox', { name: 'Name box' })).toHaveValue('G2')
      await expect(bar).toHaveValue('=E2*F2')
      await expect(cell('1:6')).toHaveText('79')
      await expect(cell('1:6')).toHaveCSS('font-family', 'Georgia')
      await expect(cell('1:6')).toHaveCSS('background-color', colors.fill)
      await expect(cell('1:6')).toHaveCSS('color', colors.text)
      await expect(cell('1:5')).toHaveText('79')
      await expect(button('Undo')).toBeDisabled()
      await opener.click()
      await expect(hex).toHaveValue(original)
      await first.click()
      await button('Redo').click()
      await expect(cell('1:6')).toHaveText('158')
    })
