import { expect, test } from '@playwright/test'
import { showRibbonItem } from '../support/ribbon'

test('Chinese Enter submits a pattern after protection is removed and restores keyboard focus', async ({ page }, info) => {
  await page.setViewportSize({ width: 390, height: 850 })
  await page.goto('/?locale=zh&plugins=cell-appearance')
  const target = page.locator('td[data-cell="1:1"]')
  await expect(target).toHaveText('Acme Co.')
  const button = (name: string) => page.getByRole('button', { name, exact: true })
  const name = page.getByRole('textbox', { name: '名称框', exact: true })
  await name.fill('B2'); await name.press('Enter')
  await showRibbonItem(page, 'data.worksheet-protection')
  await button('工作表保护').click(); await button('保护工作表').click(); await button('关闭').click()
  await showRibbonItem(page, 'format.pattern-fill'); await button('图案填充').focus(); await page.keyboard.press('Enter')
  const pattern = page.getByLabel('图案', { exact: true })
  await expect(pattern).toBeFocused(); await pattern.selectOption('darkUp')
  await page.getByLabel('图案颜色').fill('#c00000'); await page.getByLabel('底色').fill('#fff2cc')
  await page.getByLabel('底色').press('Enter')
  await expect(page.getByRole('dialog').getByRole('alert')).toContainText('未能确认')
  await expect(target).toHaveCSS('background-image', 'none')
  await button('取消').click()
  await showRibbonItem(page, 'data.worksheet-protection')
  await button('工作表保护').click(); await button('取消工作表保护').click(); await button('关闭').click()
  await showRibbonItem(page, 'format.pattern-fill'); await button('图案填充').focus(); await page.keyboard.press('Enter')
  await pattern.selectOption('darkUp'); await page.getByLabel('图案颜色').fill('#c00000')
  await page.getByLabel('底色').fill('#fff2cc'); await page.getByLabel('底色').press('Enter')
  await expect(target).toHaveCSS('background-image', /data:image\/svg\+xml/)
  await expect(target).toHaveText('Acme Co.')
  await expect(page.locator('td[data-cell="1:2"]')).toHaveCSS('background-image', 'none')
  await expect(button('图案填充')).toBeFocused()
  await info.attach('pattern-zh-390.png', { body: await page.screenshot(), contentType: 'image/png' })
  await button('撤销').click(); await expect(target).toHaveCSS('background-image', 'none')
  await expect(button('撤销')).toBeDisabled()
  expect(await page.evaluate(() => document.documentElement.scrollWidth)).toBe(390)
})
