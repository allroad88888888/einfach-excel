import { expect, test } from '@playwright/test'
import { select } from '../support/clipboard'

// 尺寸弹窗的放弃草稿入口不能改变尺寸、值、样式或既有重做记录。
for (const width of [1280, 390]) for (const cancel of ['Cancel', 'Escape'] as const)
  test(`${cancel} discards size drafts and preserves native redo at ${width}px`, async ({ page }) => {
    await page.setViewportSize({ width, height: 850 })
    await page.goto('/e2e/fixtures/plain-sales-orders/')
    await expect(page.locator('td[data-cell="1:0"]')).toHaveText('SO-10001')
    await select(page, 'H2', '1:7')
    const bar = page.getByRole('textbox', { name: 'Active cell value', exact: true })
    const undo = page.getByRole('button', { name: 'Undo', exact: true })
    const redo = page.getByRole('button', { name: 'Redo', exact: true })
    await bar.fill('Keep size redo')
    await bar.press('Enter')
    await expect(page.locator('td[data-cell="1:7"]')).toHaveText('Keep size redo')
    await undo.click()
    await select(page, 'B2', '1:1')
    const opener = page.getByRole('button', { name: 'Row and column size', exact: true })
    await opener.click()
    const dialog = page.getByRole('dialog', { name: 'Row and column size', exact: true })
    await expect(dialog.getByRole('spinbutton', { name: 'Row height' })).toBeFocused()
    await dialog.getByRole('spinbutton', { name: 'Row height' }).fill('44')
    await dialog.getByRole('spinbutton', { name: 'Column width' }).fill('200')
    if (cancel === 'Cancel') await dialog.getByRole('button', { name: 'Cancel', exact: true }).click()
    else await page.keyboard.press('Escape')
    await expect(dialog).toHaveCount(0)
    await expect(opener).toBeFocused()
    await expect(page.getByRole('separator', { name: 'Resize row 2', exact: true }))
      .toHaveAttribute('aria-valuenow', '28')
    await expect(page.getByRole('separator', { name: 'Resize column B', exact: true }))
      .toHaveAttribute('aria-valuenow', '120')
    await expect(page.locator('td[data-cell="1:1"]')).toHaveText('Acme Co.')
    await expect(page.locator('td[data-cell="1:1"]')).toHaveCSS('font-style', 'italic')
    await expect(undo).toBeDisabled()
    await opener.click()
    await expect(dialog.getByRole('spinbutton', { name: 'Row height' })).toHaveValue('28')
    await expect(dialog.getByRole('spinbutton', { name: 'Column width' })).toHaveValue('120')
    await dialog.getByRole('button', { name: 'Cancel', exact: true }).click()
    await redo.click()
    await select(page, 'H2', '1:7')
    await expect(page.locator('td[data-cell="1:7"]')).toHaveText('Keep size redo')
    await select(page, 'A2', '1:0')
    await expect(page.locator('td[data-cell="1:0"]')).toHaveCSS('font-weight', '700')
  })
