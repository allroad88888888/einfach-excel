import { expect, test } from '@playwright/test'
import { select } from '../support/clipboard'
import { argumentsPanel, bar, button, cell, download, field, neighbors, openArguments } from './fixtures'

test.beforeEach(async ({ page }) => {
  await page.goto('/e2e/fixtures/plain-sales-orders/')
  await expect(cell(page, '1:0')).toHaveText('SO-10001')
  await select(page, 'B3', '2:1')
})

test('FARG-007 cancelling argument forms and generated drafts writes nothing', async ({ page }) => {
  const before = await download(page)
  await button(page, 'Insert function').click()
  await page.getByRole('listbox', { name: 'Function', exact: true }).selectOption('LET')
  await page.getByRole('listbox', { name: 'Function', exact: true }).selectOption('IF')
  await button(page, 'Cancel').click()
  await openArguments(page, 'SUM'); await field(page, 'number').fill('SUM(1,2)')
  await page.keyboard.press('Escape')
  await expect(argumentsPanel(page)).toHaveCount(0)
  await expect(button(page, 'Insert function')).toBeFocused()
  await openArguments(page, 'IF')
  await field(page, 'logical_test').fill('TRUE'); await field(page, 'value_if_true').fill('7')
  await button(page, 'Create formula draft').click()
  await expect(bar(page)).toHaveValue('=IF(TRUE,7)')
  await page.keyboard.press('Escape')
  await expect(cell(page)).toHaveText('Northwind')
  await expect(button(page, 'Undo')).toBeDisabled()
  await neighbors(page)
  const after = await download(page)
  expect(after.workbook).toEqual(before.workbook)
})

test('FARG-008 required and incomplete repeated arguments keep the form draft', async ({ page }) => {
  await openArguments(page, 'IF'); await field(page, 'logical_test').fill('TRUE')
  await button(page, 'Create formula draft').click()
  await expect(argumentsPanel(page).getByRole('alert')).toContainText('required argument')
  await expect(field(page, 'logical_test')).toHaveValue('TRUE')
  await expect(field(page, 'value_if_true')).toBeFocused()
  await button(page, 'Cancel').click()
  await openArguments(page, 'LET')
  await field(page, 'name').fill('x'); await field(page, 'value').fill('3')
  await field(page, 'calculation').fill('x+y'); await button(page, 'Add argument group').click()
  await field(page, 'name', 1).fill('y'); await button(page, 'Create formula draft').click()
  await expect(argumentsPanel(page).getByRole('alert')).toContainText('repeated group')
  await expect(field(page, 'name', 1)).toHaveValue('y')
  await expect(field(page, 'calculation')).toHaveValue('x+y')
  await expect(field(page, 'value', 1)).toBeFocused()
  await button(page, 'Cancel').click()
  await expect(cell(page)).toHaveText('Northwind')
  await expect(button(page, 'Undo')).toBeDisabled()
  await neighbors(page)
})

test('protected target rejects an argument-generated draft without history or a native write', async ({ page }) => {
  await button(page, 'Worksheet protection').click(); await button(page, 'Protect worksheet').click()
  await expect(button(page, 'Unprotect worksheet')).toBeEnabled(); await button(page, 'Close').click()
  await openArguments(page, 'TODAY'); await button(page, 'Create formula draft').click()
  await expect(argumentsPanel(page).getByRole('alert')).toContainText('locked')
  await button(page, 'Cancel').click()
  await expect(cell(page)).toHaveText('Northwind')
  await expect(button(page, 'Undo')).toBeDisabled(); await neighbors(page)
})

test('a Rust data-validation rejection keeps the generated formula editable for correction', async ({ page }) => {
  await page.getByRole('tab', { name: 'Summary', exact: true }).click()
  await select(page, 'H45', '44:7')
  await openArguments(page, 'SUM'); await field(page, 'number').fill('5.5')
  await button(page, 'Create formula draft').click()
  await expect(bar(page)).toHaveValue('=SUM(5.5)'); await page.keyboard.press('Enter')
  await expect(page.getByRole('alert')).toContainText('data validation rule')
  await expect(bar(page)).toHaveValue('=SUM(5.5)'); await expect(bar(page)).toBeFocused()
  await expect(cell(page, '44:7')).toHaveText('5'); await expect(button(page, 'Undo')).toBeDisabled()
  await bar(page).fill('=SUM(8)'); await page.keyboard.press('Enter')
  await expect(cell(page, '44:7')).toHaveText('8')
  await button(page, 'Undo').click(); await expect(cell(page, '44:7')).toHaveText('5')
  await expect(button(page, 'Undo')).toBeDisabled()
})
