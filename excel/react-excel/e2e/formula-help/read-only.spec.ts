import { readFile } from 'node:fs/promises'
import { expect, test, type Page } from '@playwright/test'
import { select } from '../support/clipboard'

async function download(page: Page) {
  await page.getByRole('button', { name: 'File', exact: true }).click()
  const downloading = page.waitForEvent('download')
  await page.getByRole('button', { name: 'Download workbook', exact: true }).click()
  const file = await downloading
  const data = JSON.parse(await readFile((await file.path())!, 'utf8'))
  await page.getByRole('button', { name: 'Close', exact: true }).click()
  return data
}

for (const width of [1280, 390]) test(`HELP-006 browsing preserves native file and previous history step at ${width}px`, async ({ page }) => {
  await page.setViewportSize({ width, height: 850 })
  await page.goto('/')
  const target = await select(page, 'B2', '1:1')
  const input = page.getByRole('textbox', { name: 'Active cell value', exact: true })
  await input.fill('Keep native history')
  await input.press('Enter')
  await expect(target).toHaveText('Keep native history')
  const before = await download(page)
  await page.getByRole('button', { name: 'Insert function', exact: true }).click()
  const search = page.getByRole('searchbox', { name: 'Search functions' })
  await search.fill('RANK.AVG')
  await expect(page.locator('[data-formula-help="RANK.AVG"]')).toContainText('rank')
  await search.fill('CEILING')
  await page.getByRole('listbox', { name: 'Function', exact: true }).selectOption('CEILING')
  await expect(page.locator('[data-formula-help="CEILING"] .formula-help-limitations'))
    .toContainText('unary integer rounding')
  await page.getByRole('button', { name: 'Cancel', exact: true }).click()
  const after = await download(page)
  expect(after.workbook).toEqual(before.workbook)
  expect(after.canvases).toEqual(before.canvases)
  await page.getByRole('button', { name: 'Undo', exact: true }).click()
  await expect(target).toHaveText('Acme Co.')
  await expect(page.getByRole('button', { name: 'Undo', exact: true })).toBeDisabled()
  await page.getByRole('button', { name: 'Redo', exact: true }).click()
  await expect(target).toHaveText('Keep native history')
  await expect(page.locator('[data-cell="2:1"]')).toHaveText('Northwind')
})

for (const width of [1280, 390]) test(`HELP-007 search recovery, category help and cancel keep the target at ${width}px`, async ({ page }) => {
  await page.setViewportSize({ width, height: 850 })
  await page.goto('/')
  const target = await select(page, 'B2', '1:1')
  const opener = page.getByRole('button', { name: 'Insert function', exact: true })
  await opener.click()
  const dialog = page.getByRole('dialog', { name: 'Insert function' })
  const search = dialog.getByRole('searchbox', { name: 'Search functions' })
  await expect(search).toBeFocused()
  await search.fill('not-a-native-function')
  await expect(dialog.getByRole('status')).toContainText('No matching functions')
  await expect(dialog.locator('[data-formula-help]')).toHaveCount(0)
  await expect(dialog.getByRole('button', { name: 'Insert draft' })).toBeDisabled()
  await search.fill('XLOOKUP')
  await expect(dialog.locator('[data-formula-help="XLOOKUP"] [data-parameter="lookup_value"] dd'))
    .not.toBeEmpty()
  await search.fill('')
  await dialog.getByLabel('Category', { exact: true }).selectOption('Date & time')
  await dialog.getByRole('listbox', { name: 'Function', exact: true }).selectOption('TODAY')
  await expect(dialog.locator('[data-formula-help-signature]')).toHaveText('TODAY()')
  await expect(dialog.locator('[data-parameter]')).toHaveCount(0)
  await dialog.getByRole('button', { name: 'Cancel', exact: true }).click()
  await expect(dialog).toHaveCount(0)
  await expect(opener).toBeFocused()
  await expect(target).toHaveText('Acme Co.')
  await expect(page.locator('[data-cell="1:2"]')).toHaveText('North')
  await expect(page.getByRole('button', { name: 'Undo', exact: true })).toBeDisabled()
})
