import { expect, test, type Page } from '@playwright/test'
import { select } from '../support/clipboard'

const cell = (page: Page, coord: string) => page.locator(`td[data-cell="${coord}"]`)
const button = (page: Page, name: string) => page.getByRole('button', { name, exact: true })

for (const width of [1280, 390]) for (const action of ['Open', 'Cancel', 'Escape', 'Tab', 'Shift+Tab'])
  test(`${action} Go To preserves selection scroll and native redo at ${width}px`, async ({ page }, info) => {
    await page.setViewportSize({ width, height: 850 })
    await page.goto('/e2e/fixtures/plain-sales-orders/')
    await expect(cell(page, '1:0')).toHaveText('SO-10001')
    await select(page, 'E2', '1:4')
    const bar = page.getByRole('textbox', { name: 'Active cell value', exact: true })
    await bar.fill('2')
    await bar.press('Enter')
    await expect(cell(page, '1:6')).toHaveText('158')
    await button(page, 'Undo').click()
    await expect(cell(page, '1:6')).toHaveText('79')
    await select(page, 'D90', '89:3')
    const scroll = page.locator('.sheet-scroll')
    const before = await scroll.evaluate(node => [node.scrollTop, node.scrollLeft])
    await button(page, 'Go to').click()
    const dialog = page.getByRole('dialog', { name: 'Go to', exact: true })
    const input = dialog.getByRole('textbox', { name: 'Reference', exact: true })
    await expect(input).toBeFocused()
    await expect(input).toHaveValue('')
    await expect(button(page, 'Go')).toBeDisabled()
    if (action === 'Open') {
      expect(await dialog.evaluate(node => node.scrollWidth <= node.clientWidth)).toBe(true)
      await page.screenshot({ path: info.outputPath(`go-to-open-${width}.png`) })
    } else await input.fill('Summary!B2')
    if (action === 'Tab' || action === 'Shift+Tab') {
      const last = button(page, 'Go')
      await (action === 'Tab' ? last : input).focus()
      await page.keyboard.press(action)
      await expect(action === 'Tab' ? input : last).toBeFocused()
    }
    if (action === 'Escape') await page.keyboard.press('Escape')
    else await button(page, 'Cancel').click()
    await expect(dialog).toHaveCount(0)
    await expect(page.locator('[data-workbook-grid="true"]')).toBeFocused()
    await expect(page.getByRole('textbox', { name: 'Name box' })).toHaveValue('D90')
    expect(await scroll.evaluate(node => [node.scrollTop, node.scrollLeft])).toEqual(before)
    await expect(page.getByRole('tab', { name: 'Sales Orders', exact: true }))
      .toHaveAttribute('aria-selected', 'true')
    await expect(button(page, 'Undo')).toBeDisabled()
    await button(page, 'Go to').click()
    await expect(input).toHaveValue('')
    await expect(dialog).toContainText('No recent locations yet.')
    await button(page, 'Cancel').click()
    await button(page, 'Redo').click()
    await select(page, 'E2', '1:4')
    await expect(cell(page, '1:4')).toHaveText('2')
    await expect(cell(page, '1:6')).toHaveText('158')
    await expect(cell(page, '1:6')).toHaveCSS('font-family', 'Georgia')
    await expect(cell(page, '1:5')).toHaveText('79')
  })
