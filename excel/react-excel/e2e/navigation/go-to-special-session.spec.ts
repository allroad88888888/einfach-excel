import { expect, test } from '@playwright/test'
import { select } from '../support/clipboard'

for (const width of [1280, 390]) for (const action of ['Open', 'Cancel', 'Escape', 'Tab', 'Shift+Tab'])
  test(`${action} Go To Special preserves its exact scope and native redo at ${width}px`, async ({ page }, info) => {
    await page.setViewportSize({ width, height: 850 })
    await page.goto('/e2e/fixtures/plain-sales-orders/')
    const cell = (coord: string) => page.locator(`td[data-cell="${coord}"]`)
    const button = (name: string) => page.getByRole('button', { name, exact: true })
    await expect(cell('1:0')).toHaveText('SO-10001')
    await page.getByRole('tab', { name: 'Summary', exact: true }).click()
    await select(page, 'H94', '93:7')
    const bar = page.getByRole('textbox', { name: 'Active cell value', exact: true })
    await bar.fill('special redo')
    await bar.press('Enter')
    await expect(cell('93:7')).toHaveText('special redo')
    await button('Undo').click()
    await select(page, 'A93:F94', '92:0')
    await button('Go to special').click()
    const dialog = page.getByRole('dialog', { name: 'Go to special', exact: true })
    await expect(dialog).toContainText('Selected range: A93:F94')
    await expect(button('Constants')).toBeFocused()
    for (const condition of ['Constants', 'Formulas', 'Blanks'])
      await expect(dialog.getByRole('button', { name: condition, exact: true })).toBeEnabled()
    if (action === 'Open') {
      expect(await dialog.evaluate(node => node.scrollWidth <= node.clientWidth)).toBe(true)
      await page.screenshot({ path: info.outputPath(`special-open-${width}.png`) })
    }
    if (action === 'Tab' || action === 'Shift+Tab') {
      const first = button('Constants')
      const last = button('Cancel')
      await (action === 'Tab' ? last : first).focus()
      await page.keyboard.press(action)
      await expect(action === 'Tab' ? first : last).toBeFocused()
    }
    if (action === 'Escape') await page.keyboard.press('Escape')
    else await button('Cancel').click()
    await expect(dialog).toHaveCount(0)
    await expect(page.locator('[data-workbook-grid="true"]')).toBeFocused()
    await expect(page.getByRole('textbox', { name: 'Name box' })).toHaveValue('A93:F94')
    await expect(cell('92:0')).toHaveText('10')
    await expect(cell('92:0')).toHaveCSS('font-style', 'italic')
    await expect(cell('92:2')).toHaveText('-4')
    await expect(cell('93:2')).toHaveText('#DIV/0!')
    await expect(button('Undo')).toBeDisabled()
    await button('Redo').click()
    await select(page, 'H94', '93:7')
    await expect(cell('93:7')).toHaveText('special redo')
  })
