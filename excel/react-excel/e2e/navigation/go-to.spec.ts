import { expect, test, type Page } from '@playwright/test'

const cell = (page: Page, coord: string) => page.locator(`td[data-cell="${coord}"]`)
const button = (page: Page, name: string) => page.getByRole('button', { name, exact: true })
const grid = (page: Page) => page.locator('[data-workbook-grid="true"]')
async function go(page: Page, reference: string) {
  await button(page, 'Go to').click()
  await page.getByLabel('Reference', { exact: true }).fill(reference)
  await button(page, 'Go').click()
  await expect(page.getByRole('dialog')).toHaveCount(0)
}
test.beforeEach(async ({ page }) => {
  await page.goto('/')
  await expect(cell(page, '1:0')).toHaveText('SO-10001')
})

for (const width of [1280, 390]) test(`Go To covers references, history and keyboard focus at ${width}px`, async ({ page }, info) => {
  const errors: string[] = []
  page.on('pageerror', (error) => errors.push(error.message))
  await page.setViewportSize({ width, height: 850 })
  await go(page, '$B$40:$D$42')
  await expect(page.getByRole('textbox', { name: 'Name box' })).toHaveValue('B40:D42')
  await expect(cell(page, '39:1')).toHaveAttribute('data-selected', 'true')
  await expect(grid(page)).toBeFocused()
  await go(page, 'R[2]C[-1]')
  await expect(page.getByRole('textbox', { name: 'Name box' })).toHaveValue('C44')
  await go(page, 'Summary!B2')
  await expect(page.getByRole('tab', { name: 'Summary', exact: true })).toHaveAttribute('aria-selected', 'true')
  await expect(cell(page, '1:1')).toHaveText('Acme Co.')
  await grid(page).press('Control+g')
  await expect(page.getByLabel('Reference', { exact: true })).toBeFocused()
  await page.getByLabel('Reference', { exact: true }).fill('C12')
  await button(page, 'Go').press('Tab')
  await expect(page.getByLabel('Reference', { exact: true })).toBeFocused()
  await page.getByLabel('Reference', { exact: true }).press('Shift+Tab')
  await expect(button(page, 'Go')).toBeFocused()
  const dialog = page.getByRole('dialog')
  await page.screenshot({ path: info.outputPath(`go-to-${width}.png`) })
  expect(await dialog.evaluate((node) => node.scrollWidth <= node.clientWidth)).toBe(true)
  const box = (await dialog.boundingBox())!
  expect(box.x).toBeGreaterThanOrEqual(0)
  expect(box.x + box.width).toBeLessThanOrEqual(width)
  await button(page, "'Sales Orders'!C44").click()
  await expect(dialog).toHaveCount(0)
  await expect(page.getByRole('tab', { name: 'Sales Orders', exact: true })).toHaveAttribute('aria-selected', 'true')
  await expect(cell(page, '43:2')).toBeVisible()
  await expect(page.getByRole('textbox', { name: 'Name box' })).toHaveValue('C44')
  await expect(grid(page)).toBeFocused()
  await expect(button(page, 'Undo')).toBeDisabled()
  expect(errors).toEqual([])
})

for (const key of ['F5', 'Control+g', 'Meta+g']) test(`${key} opens Go To and Escape restores grid focus`, async ({ page }) => {
  await grid(page).focus()
  await grid(page).press(key)
  await expect(page.getByRole('dialog', { name: 'Go to' })).toBeVisible()
  await page.getByLabel('Reference', { exact: true }).fill('P1001')
  await page.getByLabel('Reference', { exact: true }).press('Escape')
  await expect(page.getByRole('dialog')).toHaveCount(0)
  await expect(grid(page)).toBeFocused()
  await expect(page.getByRole('textbox', { name: 'Name box' })).toHaveValue('A1')
  await expect(button(page, 'Undo')).toBeDisabled()
})

test('absolute R1C1 reaches the last canvas row and column without clipping or adding history', async ({ page }) => {
  await go(page, 'R1001C16')
  await expect(page.getByRole('textbox', { name: 'Name box' })).toHaveValue('P1001')
  await expect(cell(page, '1000:15')).toBeVisible()
  await expect(cell(page, '1000:15')).toHaveAttribute('data-selected', 'true')
  await expect(button(page, 'Undo')).toBeDisabled()
})

test('invalid and out-of-canvas cross-sheet addresses do not change tabs, selection or scroll', async ({ page }) => {
  await go(page, 'D90')
  const before = await page.locator('.sheet-scroll').evaluate((node) => [node.scrollTop, node.scrollLeft])
  await button(page, 'Go to').click()
  for (const reference of ['Summary!Z2000', 'Absent!B2', 'R[-999]C', '$$A1']) {
    await page.getByLabel('Reference', { exact: true }).fill(reference)
    await button(page, 'Go').click()
    await expect(page.getByRole('alert')).toBeVisible()
    await expect(page.getByRole('tab', { name: 'Sales Orders', exact: true })).toHaveAttribute('aria-selected', 'true')
    await expect(page.getByRole('textbox', { name: 'Name box' })).toHaveValue('D90')
    expect(await page.locator('.sheet-scroll').evaluate((node) => [node.scrollTop, node.scrollLeft])).toEqual(before)
  }
  await page.getByLabel('Reference', { exact: true }).fill('B2')
  await expect(page.getByRole('alert')).toHaveCount(0)
  await page.getByLabel('Reference', { exact: true }).press('Enter')
  await expect(page.getByRole('dialog')).toHaveCount(0)
  await expect(cell(page, '1:1')).toHaveText('Acme Co.')
})

test('history is capped, deduplicated and scoped to the current workbook page', async ({ page }) => {
  for (let row = 2; row <= 13; row += 1) await go(page, `B${row}`)
  await go(page, 'b5')
  await button(page, 'Go to').click()
  const recent = page.getByRole('region', { name: 'Recent locations' }).getByRole('button')
  await expect(recent).toHaveCount(10)
  await expect(recent.first()).toHaveText("'Sales Orders'!B5")
  await expect(button(page, "'Sales Orders'!B2")).toHaveCount(0)
  await button(page, 'Cancel').click()
  await page.reload()
  await expect(cell(page, '1:0')).toHaveText('SO-10001')
  await button(page, 'Go to').click()
  await expect(page.getByText('No recent locations yet.')).toBeVisible()
})

test('hidden targets stay hidden until explicitly unhidden, and merged targets select the canonical rectangle', async ({ page }) => {
  await go(page, 'Summary!A10')
  await expect(page.getByRole('textbox', { name: 'Name box' })).toHaveValue('A10')
  await expect(cell(page, '9:0')).toHaveCount(0)
  await expect(button(page, 'Undo')).toBeDisabled()
  await page.getByRole('combobox', { name: 'Row and column visibility' }).selectOption('unhide-all')
  await expect(cell(page, '9:0')).toHaveText('Hidden row example')
  await button(page, 'Undo').click()
  await expect(cell(page, '9:0')).toHaveCount(0)
  await go(page, 'C15')
  await expect(page.getByRole('textbox', { name: 'Name box' })).toHaveValue('A15:D15')
  await expect(page.getByRole('textbox', { name: 'Active cell value' })).toHaveValue('Merged heading')
  await expect(button(page, 'Undo')).toBeDisabled()
})

test('offscreen cross-sheet navigation works with frozen panes and returning keeps the source view', async ({ page }) => {
  await go(page, 'C3')
  await page.getByRole('combobox', { name: 'Freeze panes' }).selectOption('selection')
  await expect(page.getByRole('combobox', { name: 'Freeze panes' })).toContainText('Panes frozen')
  await go(page, 'P1001')
  await expect(cell(page, '1000:15')).toBeVisible()
  const before = await page.locator('.sheet-scroll').evaluate((node) => [node.scrollTop, node.scrollLeft])
  await go(page, 'Summary!H100')
  await expect(cell(page, '99:7')).toBeVisible()
  await page.getByRole('tab', { name: 'Sales Orders', exact: true }).click()
  await expect(page.getByRole('textbox', { name: 'Name box' })).toHaveValue('P1001')
  await expect(cell(page, '1000:15')).toBeVisible()
  await expect.poll(() => page.locator('.sheet-scroll').evaluate((node) => [node.scrollTop, node.scrollLeft]))
    .toEqual(before)
})

test('quoted worksheet names navigate correctly and an obsolete history address stays an explicit error', async ({ page }) => {
  await go(page, 'Summary!B2')
  await button(page, 'Rename sheet').click()
  await page.getByRole('textbox', { name: 'Sheet name' }).fill("Manager'!s report")
  await page.getByRole('textbox', { name: 'Sheet name' }).press('Enter')
  await expect(page.getByRole('tab', { name: "Manager'!s report", exact: true })).toBeVisible()
  await go(page, "'Sales Orders'!B40")
  await button(page, 'Go to').click()
  await button(page, "'Summary'!B2").click()
  await expect(page.getByRole('alert')).toBeVisible()
  await expect(page.getByRole('textbox', { name: 'Name box' })).toHaveValue('B40')
  await page.getByLabel('Reference', { exact: true }).fill("'Manager''!s report'!$B$2")
  await button(page, 'Go').click()
  await expect(cell(page, '1:1')).toHaveText('Acme Co.')
  await expect(page.getByRole('tab', { name: "Manager'!s report", exact: true })).toHaveAttribute('aria-selected', 'true')
})

test('a typed edit disables Go To and composing Enter does not submit the reference form', async ({ page }) => {
  await cell(page, '1:0').dblclick()
  const editor = page.getByRole('textbox', { name: 'Cell editor' })
  await editor.fill('pending')
  await expect(button(page, 'Go to')).toBeDisabled()
  await editor.press('Escape')
  await button(page, 'Go to').click()
  const input = page.getByLabel('Reference', { exact: true })
  await input.fill('B12')
  const prevented = await input.evaluate((node) => !node.dispatchEvent(new KeyboardEvent('keydown', {
    key: 'Enter', bubbles: true, cancelable: true, isComposing: true,
  })))
  expect(prevented).toBe(true)
  await expect(page.getByRole('dialog')).toBeVisible()
  await input.press('Enter')
  await expect(page.getByRole('dialog')).toHaveCount(0)
  await expect(page.getByRole('textbox', { name: 'Name box' })).toHaveValue('B12')
  await expect(button(page, 'Undo')).toBeDisabled()
})
