import { expect, test, type Page } from '@playwright/test'
import { select } from '../support/clipboard'

const button = (page: Page, name: string) => page.getByRole('button', { name, exact: true })
const cell = (page: Page, coord: string) => page.locator(`td[data-cell="${coord}"]`)
async function openGoTo(page: Page, name: string) {
  await button(page, 'Go to').click()
  await page.getByLabel('Reference', { exact: true }).fill(name)
}
test.beforeEach(async ({ page }) => {
  await page.goto('/')
  await expect(cell(page, '1:0')).toHaveText('SO-10001')
})

for (const width of [1280, 390]) test(`Go To uses the native name seed across sheets at ${width}px`, async ({ page }, info) => {
  const errors: string[] = []
  page.on('pageerror', (error) => errors.push(error.message))
  await page.setViewportSize({ width, height: 800 })
  await openGoTo(page, 'sampleamounts')
  const dialog = page.getByRole('dialog', { name: 'Go to', exact: true })
  await expect(page.getByLabel('Reference', { exact: true })).toBeFocused()
  expect(await dialog.evaluate((node) => node.scrollWidth <= node.clientWidth)).toBe(true)
  await page.screenshot({ path: info.outputPath(`go-to-name-${width}.png`) })
  await page.getByLabel('Reference', { exact: true }).press('Enter')
  await expect(dialog).toHaveCount(0)
  await expect(page.getByRole('tab', { name: 'Summary', exact: true })).toHaveAttribute('aria-selected', 'true')
  await expect(cell(page, '64:2')).toHaveText('2')
  for (const coord of ['64:2', '65:2', '66:2'])
    await expect(cell(page, coord)).toHaveAttribute('data-selected', 'true')
  await expect(cell(page, '65:2')).toHaveText('4')
  await expect(cell(page, '66:2')).toHaveText('6')
  await expect(cell(page, '64:3')).not.toHaveAttribute('data-selected', 'true')
  await expect(cell(page, '64:3')).toHaveText('2')
  await expect(page.locator('[data-workbook-grid]')).toBeFocused()
  await expect(button(page, 'Undo')).toBeDisabled()
  await openGoTo(page, '')
  await expect(button(page, "'Summary'!C65:C67")).toBeVisible()
  await page.keyboard.press('Escape')
  expect(errors).toEqual([])
})

test('Go To follows the current renamed target and refuses deleted names', async ({ page }) => {
  await button(page, 'Name manager').click(); await button(page, 'Edit SampleAmounts').click()
  await page.getByLabel('Name', { exact: true }).fill('Revenue')
  await page.getByLabel('Refers to', { exact: true }).fill('C66:C67')
  await button(page, 'Save changes').click()
  await expect(page.getByRole('dialog')).toHaveCount(0)
  await openGoTo(page, 'Revenue'); await button(page, 'Go').click()
  await expect(page.getByRole('dialog')).toHaveCount(0)
  await expect(cell(page, '65:2')).toHaveAttribute('data-selected', 'true')
  await expect(cell(page, '65:2')).toHaveText('4')
  await button(page, 'Name manager').click(); await button(page, 'Edit Revenue').click()
  await button(page, 'Delete name').click()
  await expect(page.getByRole('dialog')).toHaveCount(0)
  await openGoTo(page, 'Revenue'); await button(page, 'Go').click()
  await expect(page.getByRole('alert')).toBeVisible()
  await expect(page.getByRole('dialog', { name: 'Go to', exact: true })).toBeVisible()
  await expect(cell(page, '65:2')).toHaveAttribute('data-selected', 'true')
})

test('Go To reports a broken named range without creating a replacement name', async ({ page }) => {
  await page.getByRole('tab', { name: 'Summary', exact: true }).click()
  await select(page, 'C65:C67', '64:2')
  await page.getByRole('combobox', { name: 'Insert or delete rows and columns' }).selectOption('delete-rows')
  await expect(button(page, 'Undo')).toBeEnabled()
  await openGoTo(page, 'SampleAmounts'); await button(page, 'Go').click()
  await expect(page.getByRole('alert')).toContainText('named range')
  await button(page, 'Cancel').click()
  await button(page, 'Name manager').click(); await button(page, 'Edit SampleAmounts').click()
  await expect(page.getByLabel('Refers to', { exact: true })).toHaveValue('#REF!')
})

for (const width of [1280, 390]) test(`name box navigates names and keeps errors correctable at ${width}px`, async ({ page }, info) => {
  await page.setViewportSize({ width, height: 800 })
  const name = page.getByRole('textbox', { name: 'Name box' })
  await name.fill('sampleamounts'); await name.press('Enter')
  await expect(page.getByRole('tab', { name: 'Summary', exact: true })).toHaveAttribute('aria-selected', 'true')
  await expect(cell(page, '64:2')).toHaveText('2')
  await expect(cell(page, '66:2')).toHaveAttribute('data-selected', 'true')
  await expect(cell(page, '65:2')).toHaveText('4')
  await expect(cell(page, '66:2')).toHaveText('6')
  await expect(cell(page, '64:3')).not.toHaveAttribute('data-selected', 'true')
  await expect(name).toHaveValue('SampleAmounts')
  await expect(page.locator('[data-workbook-grid]')).toBeFocused()
  await expect(button(page, 'Undo')).toBeDisabled()
  await name.fill('!!invalid'); await name.press('Enter')
  await expect(name).toHaveAttribute('aria-invalid', 'true')
  await expect(name).toBeFocused()
  const error = page.getByRole('alert')
  await expect(error).toBeVisible()
  expect(await error.evaluate((node) => node.scrollWidth <= node.clientWidth)).toBe(true)
  await page.screenshot({ path: info.outputPath(`name-box-error-${width}.png`) })
  await name.press('Escape')
  await expect(error).toHaveCount(0)
  await expect(name).toHaveValue('SampleAmounts')
  await expect(button(page, 'Undo')).toBeDisabled()
})

test('name box creates a native range usable by formulas, manager, Go To and undo', async ({ page }) => {
  const name = page.getByRole('textbox', { name: 'Name box' })
  await select(page, 'E2:E4', '1:4')
  await expect(cell(page, '1:4')).toHaveText('1')
  await expect(cell(page, '2:4')).toHaveText('2')
  await expect(cell(page, '3:4')).toHaveText('3')
  await name.fill('QuickUnits'); await name.press('Enter')
  await expect(name).toHaveValue('QuickUnits')
  await expect(page.locator('[data-workbook-grid]')).toBeFocused()
  await button(page, 'Name manager').click(); await button(page, 'Edit QuickUnits').click()
  await expect(page.getByLabel('Refers to', { exact: true })).toHaveValue('E2:E4')
  await button(page, 'Cancel').click()
  await select(page, 'J2', '1:9')
  const formula = page.getByRole('textbox', { name: 'Active cell value' })
  await formula.fill('=SUM(QuickUnits)'); await formula.press('Enter')
  await expect(cell(page, '1:9')).toHaveText('6')
  await button(page, 'Undo').click()
  await button(page, 'Undo').click()
  await button(page, 'Name manager').click()
  await expect(button(page, 'Edit QuickUnits')).toHaveCount(0)
  await button(page, 'Cancel').click()
  await button(page, 'Redo').click()
  await openGoTo(page, 'QuickUnits'); await button(page, 'Go').click()
  await expect(cell(page, '1:4')).toHaveAttribute('data-selected', 'true')
  await expect(cell(page, '3:4')).toHaveAttribute('data-selected', 'true')
})
