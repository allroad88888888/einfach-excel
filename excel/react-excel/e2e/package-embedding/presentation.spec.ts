import { expect, test } from '@playwright/test'

test('embedded language selection is independent and never changes host preferences', async ({ page }) => {
  await page.addInitScript(() => localStorage.setItem('react-excel.ui-locale', 'zh'))
  await page.goto('/e2e/package-embedding/host.html?locale=zh&renderer=canvas#host')
  const first = page.locator('#first'), second = page.locator('#second')
  await expect(first.locator('td[data-cell="1:0"]')).toHaveText('Original')
  await expect(first.getByRole('combobox', { name: 'Interface language' })).toHaveValue('en')
  await expect(second.getByRole('combobox', { name: 'Interface language' })).toHaveValue('en')
  await second.getByRole('combobox', { name: 'Interface language' }).selectOption('zh')
  await expect(second.getByRole('tab', { name: '开始', exact: true })).toBeVisible()
  await expect(first.getByRole('tab', { name: 'Start', exact: true })).toBeVisible()
  await first.getByRole('combobox', { name: 'Interface language' }).selectOption('zh')
  await second.getByRole('combobox', { name: '界面语言' }).selectOption('en')
  await expect(first.getByRole('tab', { name: '开始', exact: true })).toBeVisible()
  await expect(second.getByRole('tab', { name: 'Start', exact: true })).toBeVisible()
  await expect(first.locator('td[data-cell="1:0"]')).toHaveText('Original')
  expect(await page.evaluate(() => localStorage.getItem('react-excel.ui-locale'))).toBe('zh')
  expect(new URL(page.url()).search).toBe('?locale=zh&renderer=canvas')
  expect(new URL(page.url()).hash).toBe('#host')
})

test('host locale control disables only its own language selector', async ({ page }) => {
  await page.goto('/e2e/package-embedding/host.html')
  const first = page.locator('#first'), second = page.locator('#second')
  await expect(first.locator('td[data-cell="1:0"]')).toHaveText('Original')
  await first.locator('td[data-cell="1:0"]').dblclick()
  const editor = first.locator('[data-cell-editor] textarea')
  await editor.fill('Controlled locale retains data')
  await editor.press('Enter')
  await page.locator('#locale-first').click()
  await expect(first.getByRole('combobox', { name: '界面语言' })).toBeDisabled()
  await expect(second.getByRole('combobox', { name: 'Interface language' })).toBeEnabled()
  await expect(first.locator('td[data-cell="1:0"]')).toHaveText('Controlled locale retains data')
  const ids = await page.locator('[id]').evaluateAll(nodes => nodes.map(node => node.id))
  expect(new Set(ids).size).toBe(ids.length)
})

test('explicit shared I18n injection shares language while retaining independent workbook state', async ({ page }) => {
  await page.goto('/e2e/package-embedding/host.html')
  const first = page.locator('#first'), second = page.locator('#second')
  await expect(first.locator('td[data-cell="1:0"]')).toHaveText('Original')
  await page.locator('#host-button').click()
  await first.getByRole('tab', { name: 'Formulas', exact: true }).click()
  await second.getByRole('combobox', { name: 'Interface language' }).selectOption('zh')
  await expect(first.getByRole('combobox', { name: '界面语言' })).toHaveValue('zh')
  await expect(second.getByRole('combobox', { name: '界面语言' })).toHaveValue('zh')
  await expect(first.getByRole('tab', { name: '公式', exact: true })).toHaveAttribute('aria-selected', 'true')
  await expect(second.getByRole('tab', { name: '开始', exact: true })).toHaveAttribute('aria-selected', 'true')
  await expect(second.locator('td[data-cell="1:0"]')).toHaveText('Original')
})

test('host renderer prop selects canvas independently of the URL and sibling', async ({ page }) => {
  await page.goto('/e2e/package-embedding/host.html?renderer=canvas')
  const first = page.locator('#first'), second = page.locator('#second')
  await expect(first.locator('td[data-cell="1:0"]')).toHaveText('Original')
  await expect(second.locator('td[data-cell="1:0"]')).toHaveText('Original')
  await expect(page.locator('canvas')).toHaveCount(0)
  await first.locator('td[data-cell="1:0"]').dblclick()
  const editor = first.locator('[data-cell-editor] textarea')
  await editor.fill('Renderer retains data')
  await editor.press('Enter')
  await page.locator('#canvas-first').click()
  const canvas = first.getByRole('img', { name: 'Canvas worksheet cells' })
  await expect(canvas).toBeVisible()
  await expect.poll(() => canvas.getAttribute('data-painted-cells').then(Number)).toBeGreaterThan(0)
  await expect(second.locator('canvas')).toHaveCount(0)
  await expect(second.locator('td[data-cell="1:0"]')).toHaveText('Original')
  const name = first.getByRole('textbox', { name: 'Name box', exact: true })
  await name.fill('A2')
  await name.press('Enter')
  await expect(first.getByRole('textbox', { name: 'Active cell value', exact: true })).toHaveValue('Renderer retains data')
})
