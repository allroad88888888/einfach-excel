import { expect, test } from '@playwright/test'
import { select } from '../support/clipboard'
import { showRibbonItem } from '../support/ribbon'

test('Color sort is optional and sorts the native Priority examples', async ({ page }) => {
  const cell = (coord: string) => page.locator(`td[data-cell="${coord}"]`)
  const colorSort = page.getByRole('button', { name: 'Color sort', exact: true })
  await page.goto('/?locale=en')
  await expect(cell('1:0')).toHaveText('SO-10001')
  await showRibbonItem(page, 'data.sort-selected-range')
  await expect(page.getByRole('combobox', { name: 'Sort selected range', exact: true })).toBeVisible()
  await expect(colorSort).toHaveCount(0)
  await page.goto('/?plugins=data-sort&locale=en')
  await expect(cell('1:0')).toHaveText('SO-10001')
  await page.getByRole('tab', { name: 'Summary', exact: true }).click()
  await select(page, 'A97:B100', '96:0')
  await expect(cell('97:1')).toHaveText('Follow-up')
  await expect(cell('98:0')).toHaveCSS('background-color', 'rgb(244, 204, 204)')
  await showRibbonItem(page, 'data.color-sort')
  await colorSort.click()
  const dialog = page.getByRole('dialog', { name: 'Color sort', exact: true })
  await dialog.getByLabel('First row is a header', { exact: true }).check()
  await dialog.getByLabel('Target color', { exact: true }).fill('#f4cccc')
  await dialog.getByRole('button', { name: 'Apply sort', exact: true }).click()
  await expect(cell('97:0')).toHaveText('Urgent')
  await expect(cell('97:1')).toHaveText('Review today')
  await expect(cell('96:0')).toHaveText('Priority')
  await page.getByRole('button', { name: 'Undo', exact: true }).click()
  await expect(cell('97:1')).toHaveText('Follow-up')
})

test('Chinese color sort works by keyboard at 390px and restores its opener', async ({ page }, info) => {
  await page.setViewportSize({ width: 390, height: 850 })
  await page.goto('/?plugins=data-sort&locale=en')
  const cell = (coord: string) => page.locator(`td[data-cell="${coord}"]`)
  await expect(cell('1:0')).toHaveText('SO-10001')
  await page.getByRole('tab', { name: 'Summary', exact: true }).click()
  await select(page, 'A97:B100', '96:0')
  await page.getByRole('combobox', { name: 'Interface language' }).selectOption('zh')
  await showRibbonItem(page, 'data.color-sort')
  const trigger = page.getByRole('button', { name: '颜色排序', exact: true })
  await trigger.focus()
  await page.keyboard.press('Enter')
  const dialog = page.getByRole('dialog', { name: '颜色排序', exact: true })
  await dialog.getByLabel('首行是表头').check()
  await dialog.getByLabel('排序依据', { exact: true }).selectOption('font-color')
  await dialog.getByLabel('目标颜色', { exact: true }).fill('#c00000')
  expect(await dialog.evaluate(node => node.scrollWidth <= node.clientWidth)).toBe(true)
  await page.screenshot({ path: info.outputPath('color-sort-zh-390.png') })
  await dialog.getByRole('button', { name: '应用排序', exact: true }).focus()
  await page.keyboard.press('Enter')
  await expect(dialog).toHaveCount(0)
  await expect(trigger).toBeFocused()
  await expect(cell('97:1')).toHaveText('Review today')
  await page.getByRole('button', { name: '撤销', exact: true }).click()
  await expect(cell('97:1')).toHaveText('Follow-up')
})
