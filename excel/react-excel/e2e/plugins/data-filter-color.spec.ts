import { expect, test } from '@playwright/test'
import { launchColors, chooseColor, visibleColorRecords } from '../support/color-filter'
import { apply, button, cell, dialog } from '../support/date-filter'

test('Color candidates page through offscreen rows without applying a rule', async ({ page }) => {
  await launchColors(page, { palette: true })
  await chooseColor(page, 'fill')
  await button(page, 'Choose a color from this column').click()
  await expect(dialog(page)).toContainText('1–24 of 29 colors')
  await expect(button(page, '#ffffff (1 row)')).toHaveCount(0)
  await button(page, 'Next color page').click()
  await expect(dialog(page)).toContainText('25–29 of 29 colors')
  await button(page, '#ffffff (1 row)').click()
  await expect(cell(page, '1:1')).toHaveText('Red solid')
  await expect(button(page, '#ffffff (1 row)')).toHaveAttribute('aria-pressed', 'true')
  await apply(page)
  await visibleColorRecords(page, [3], 35)
})

test('Chinese color filter applies an RGB color with the keyboard at 390px', async ({ page }, info) => {
  await launchColors(page, { width: 390 })
  const header = button(page, 'Filter column A')
  const expandedTools = page.locator('[data-ribbon-more][aria-expanded="true"]')
  await expect(header).toBeVisible()
  await expect(expandedTools).toHaveCount(0)
  await page.getByRole('combobox', { name: 'Interface language' }).selectOption('zh')
  await expect(expandedTools).toHaveCount(0)
  await header.focus()
  await page.keyboard.press('Enter')
  await button(page, '按颜色筛选…').focus()
  await page.keyboard.press('Enter')
  const rgb = page.getByLabel('RGB 颜色 1', { exact: true })
  await rgb.focus()
  await page.keyboard.type('#c00000')
  await expect(rgb).toHaveValue('#c00000')
  const opened = page.getByRole('dialog')
  expect(await opened.evaluate(node => node.scrollWidth <= node.clientWidth)).toBe(true)
  await page.screenshot({ path: info.outputPath('color-filter-zh-390.png') })
  await button(page, '应用筛选').focus()
  await page.keyboard.press('Enter')
  await expect(opened).toHaveCount(0)
  await expect(cell(page, '1:1')).toHaveText('Red solid')
  await expect(cell(page, '2:1')).toHaveCount(0)
  await button(page, '撤销').click()
  await expect(cell(page, '2:1')).toHaveText('Pattern')
})
