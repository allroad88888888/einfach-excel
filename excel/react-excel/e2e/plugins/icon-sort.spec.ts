import { expect, test } from '@playwright/test'
import { select } from '../support/clipboard'
import { showRibbonItem } from '../support/ribbon'
import { button, cell, icon } from '../advanced-conditional-format/support'

test('Icon sort is optional and uses the native Summary icon samples', async ({ page }) => {
  const trigger = button(page, 'Icon sort')
  await page.goto('/?locale=en')
  await expect(cell(page, '1:0')).toHaveText('SO-10001')
  await showRibbonItem(page, 'data.sort-selected-range')
  await expect(trigger).toHaveCount(0)

  await page.goto('/?plugins=data-sort&locale=en')
  await expect(cell(page, '1:0')).toHaveText('SO-10001')
  await page.getByRole('tab', { name: 'Summary', exact: true }).click()
  await select(page, 'H75:H79', '74:7')
  await expect(icon(page, '77:7')).toHaveAttribute('data-icon-index', '2')
  await expect(icon(page, '78:7')).toHaveAttribute('data-icon-index', '2')
  const neighbor = await cell(page, '74:4').innerText()
  await showRibbonItem(page, 'data.icon-sort')
  await trigger.click()
  const panel = page.getByRole('dialog', { name: 'Icon sort' })
  await panel.getByLabel('Target icon', { exact: true }).selectOption('three-arrows:2')
  await panel.getByRole('button', { name: 'Apply sort', exact: true }).click()
  await expect(panel).toHaveCount(0)
  await expect(cell(page, '74:7')).toContainText('75')
  await expect(cell(page, '75:7')).toContainText('100')
  await expect(cell(page, '74:4')).toHaveText(neighbor)
  await button(page, 'Undo').click()
  await expect(icon(page, '74:7')).toHaveAttribute('data-icon-index', '0')
  await expect(cell(page, '77:7')).toContainText('75')
  await expect(button(page, 'Undo')).toBeDisabled()
})

test('Chinese icon sort submits by keyboard and restores focus at 390px', async ({ page }, info) => {
  await page.setViewportSize({ width: 390, height: 850 })
  await page.goto('/?plugins=data-sort&locale=en')
  await expect(cell(page, '1:0')).toHaveText('SO-10001')
  await page.getByRole('tab', { name: 'Summary', exact: true }).click()
  await select(page, 'H75:H79', '74:7')
  await expect(icon(page, '77:7')).toHaveAttribute('data-icon-index', '2')
  await page.getByRole('combobox', { name: 'Interface language' }).selectOption('zh')
  await showRibbonItem(page, 'data.icon-sort')
  const trigger = button(page, '图标排序')
  await trigger.focus()
  await page.keyboard.press('Enter')
  const panel = page.getByRole('dialog', { name: '图标排序' })
  await panel.getByLabel('目标图标', { exact: true }).selectOption('three-arrows:2')
  expect(await panel.evaluate(node => node.scrollWidth <= node.clientWidth)).toBe(true)
  await page.screenshot({ path: info.outputPath('icon-sort-zh-390.png') })
  await panel.getByRole('button', { name: '应用排序', exact: true }).focus()
  await page.keyboard.press('Enter')
  await expect(panel).toHaveCount(0)
  await expect(trigger).toBeFocused()
  await expect(cell(page, '74:7')).toContainText('75')
  await button(page, '撤销').click()
  await expect(icon(page, '74:7')).toHaveAttribute('data-icon-index', '0')
  await expect(button(page, '撤销')).toBeDisabled()
})
