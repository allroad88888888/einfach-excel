import { expect, test } from '@playwright/test'
import { button, cell, go } from '../support/date-filter'
import { showRibbonItem } from '../support/ribbon'

test('Subtotal rejects a worksheet Table through the optional ribbon entry', async ({ page }) => {
  await page.goto('/?plugins=data-subtotal&locale=en')
  await expect(cell(page, '1:0')).toHaveText('SO-10001')
  await page.getByRole('tab', { name: 'Summary', exact: true }).click()
  await go(page, 'A80:B83')
  await showRibbonItem(page, 'data.subtotal')
  await button(page, 'Subtotal').click()
  const panel = page.getByRole('dialog', { name: 'Subtotal', exact: true })
  await expect(panel.getByRole('alert')).toContainText('Convert the Table to a normal range')
  await expect(panel.getByRole('button', { name: 'Apply subtotals', exact: true })).toBeDisabled()
  await page.keyboard.press('Escape')
  await expect(button(page, 'Subtotal')).toBeFocused()
  await expect(button(page, 'Undo')).toBeDisabled()
})

test('Chinese subtotal runs by keyboard at 390px and restores focus', async ({ page }) => {
  await page.setViewportSize({ width: 390, height: 850 })
  await page.goto('/?plugins=data-subtotal&locale=zh')
  await expect(cell(page, '1:0')).toHaveText('SO-10001')
  await page.getByRole('tab', { name: 'Summary', exact: true }).click()
  const name = page.getByRole('textbox', { name: '名称框', exact: true })
  await name.fill('A25:C29')
  await name.press('Enter')
  await showRibbonItem(page, 'data.subtotal')
  const opener = button(page, '分类汇总')
  await opener.focus()
  await page.keyboard.press('Enter')
  const panel = page.getByRole('dialog', { name: '分类汇总', exact: true })
  await expect(panel.getByLabel('列表区域', { exact: true })).toHaveValue('A25:C29')
  await panel.getByRole('checkbox', { name: 'Record', exact: true }).uncheck()
  await panel.getByRole('checkbox', { name: 'Score', exact: true }).check()
  const box = await panel.boundingBox()
  expect(box && box.x >= 0 && box.x + box.width <= 390).toBe(true)
  await panel.getByRole('button', { name: '应用分类汇总', exact: true }).focus()
  await page.keyboard.press('Enter')
  await expect(panel).toHaveCount(0)
  await expect(opener).toBeFocused()
  await name.fill('B34')
  await name.press('Enter')
  await expect(cell(page, '33:1')).toHaveText('70')
})
