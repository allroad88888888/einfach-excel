import { expect, test } from '@playwright/test'
import { button, cell, go } from '../support/date-filter'
import { criteriaDialog, launchCriteria } from '../support/worksheet-criteria'
import { showRibbonItem } from '../support/ribbon'

test('Chinese worksheet criteria submit by keyboard and restore focus at 390px', async ({ page }, info) => {
  await launchCriteria(page, 390)
  await go(page, 'A1:C8')
  await page.getByRole('combobox', { name: 'Interface language' }).selectOption('zh')
  await showRibbonItem(page, 'data.advanced-filter-range')
  const opener = button(page, '高级筛选')
  await opener.focus()
  await page.keyboard.press('Enter')
  const dialogue = criteriaDialog(page, '高级筛选')
  await expect(dialogue.getByLabel('列表区域', { exact: true })).toHaveValue('A1:C8')
  await dialogue.getByLabel('条件区域', { exact: true }).fill("'Filter Rules'!A1:C4")
  expect(await dialogue.evaluate(node => node.scrollWidth <= node.clientWidth)).toBe(true)
  await page.screenshot({ path: info.outputPath('worksheet-criteria-zh-390.png') })
  await button(page, '应用筛选').focus()
  await page.keyboard.press('Enter')
  await expect(dialogue).toHaveCount(0)
  await expect(opener).toBeFocused()
  await expect(cell(page, '3:0')).toHaveCount(0)
  await expect(cell(page, '4:0')).toHaveText('Beta')
  await button(page, '撤销').click()
  await expect(cell(page, '3:0')).toHaveText('Alpine')
})

test('Summary worksheet criteria copy only the matching native sample record', async ({ page }) => {
  await page.setViewportSize({ width: 1280, height: 850 })
  await page.goto('/?plugins=data-filter&locale=en')
  await expect(cell(page, '1:0')).toHaveText('SO-10001')
  await page.getByRole('tab', { name: 'Summary', exact: true }).click()
  await go(page, 'A25:C29')
  await showRibbonItem(page, 'data.advanced-filter-range')
  await button(page, 'Advanced filter').click()
  const dialogue = criteriaDialog(page)
  await dialogue.getByRole('radio', { name: 'Copy to another location' }).check()
  await dialogue.getByLabel('Criteria range', { exact: true }).fill('B33:C34')
  await dialogue.getByLabel('Copy to', { exact: true }).fill('A51')
  await dialogue.getByRole('button', { name: 'Preview results', exact: true }).click()
  await expect(dialogue.getByRole('status')).toHaveText('1 matching record')
  await dialogue.getByRole('button', { name: 'Copy results', exact: true }).click()
  await expect(dialogue).toHaveCount(0)
  await go(page, 'A51')
  await expect(cell(page, '50:0')).toHaveText('Team')
  await expect(cell(page, '51:2')).toHaveText('E30')
  await button(page, 'Undo').click()
  await expect(cell(page, '51:2')).toHaveText('')
  await go(page, 'A25')
  await expect(cell(page, '25:2')).toHaveText('W20')
  await expect(cell(page, '28:2')).toHaveText('E30')
})
