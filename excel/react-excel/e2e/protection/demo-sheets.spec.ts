import { expect, test } from '@playwright/test'
import { button, cell, editor, panel, select, openProtection, closeProtection, input, expectLockedInput } from './support'

for (const width of [1280]) test.describe(`${width}px protection demo sheets`, () => {
  test.use({ permissions: ['clipboard-read', 'clipboard-write'] })
  test.beforeEach(async ({ page }) => {
    await page.setViewportSize({ width, height: 900 })
    await page.goto('/?locale=en')
    await expect(page.getByRole('tab', { name: '整表只读', exact: true })).toBeVisible()
  })

  test(`read-only demo rejects edits from startup and can be unprotected at ${width}px`, async ({ page }) => {
    const tab = page.getByRole('tab', { name: '整表只读', exact: true })
    await expect(tab).toHaveAttribute('data-read-only', 'true')
    await expect(tab).toHaveCSS('color', 'rgb(123, 129, 144)')
    await tab.click()
    await expect(tab).toHaveCSS('color', 'rgb(98, 105, 120)')
    await select(page, 'B6', '5:1')
    await expect(cell(page, '5:1')).toHaveText('2')
    await expect(button(page, 'Undo')).toBeDisabled()
    await openProtection(page)
    await expect(panel(page)).toContainText('This worksheet is protected.')
    await expect(panel(page)).toContainText('No editable ranges.')
    await closeProtection(page)
    await expectLockedInput(page)
    await expect(cell(page, '5:1')).toHaveText('2')
    await editor(page).press('Escape')
    await expect(button(page, 'Undo')).toBeDisabled()
    await openProtection(page)
    await button(page, 'Unprotect worksheet').click()
    await expect(button(page, 'Protect worksheet')).toBeEnabled()
    await closeProtection(page)
    await expect(page.getByRole('tab', { name: '整表只读', exact: true })).not.toHaveAttribute('data-read-only', 'true')
    await input(page, '3')
    await expect(cell(page, '5:1')).toHaveText('3')
    await button(page, 'Undo').click()
    await expect(cell(page, '5:1')).toHaveText('2')
    await expect(button(page, 'Undo')).toBeDisabled()
  })

  test(`editable-range demo changes green inputs and keeps prices and formulas locked at ${width}px`, async ({ page }) => {
    await page.getByRole('tab', { name: '局部可编辑', exact: true }).click()
    await select(page, 'B6', '5:1')
    await expect(cell(page, '5:1')).toHaveCSS('background-color', 'rgb(229, 244, 235)')
    await expect(button(page, 'Undo')).toBeDisabled()
    await openProtection(page)
    await expect(panel(page)).toContainText('This worksheet is protected.')
    await expect(button(page, 'Remove editable range B6:B9')).toBeDisabled()
    await closeProtection(page)
    await input(page, '3')
    await expect(cell(page, '5:1')).toHaveText('3')
    await select(page, 'D6', '5:3')
    await expect(cell(page, '5:3')).toHaveText('3,840.00')
    await expectLockedInput(page)
    await expect(cell(page, '5:3')).toHaveText('3,840.00')
    await editor(page).press('Escape')
    await select(page, 'C6', '5:2')
    await expectLockedInput(page)
    await expect(cell(page, '5:2')).toHaveText('1,280.00')
    await editor(page).press('Escape')
    await select(page, 'D11', '10:3')
    await expect(cell(page, '10:3')).toHaveText('5,120.00')
    await button(page, 'Undo').click()
    await expect(cell(page, '10:3')).toHaveText('3,840.00')
    await select(page, 'B6', '5:1')
    await expect(cell(page, '5:1')).toHaveText('2')
    await page.getByRole('tab', { name: 'Sales Orders', exact: true }).click()
    await expect(cell(page, '1:0')).toHaveText('SO-10001')
  })

})
