import { expect, test } from '@playwright/test'
import { button, cell, panel, select, openProtection, closeProtection, input } from './support'

for (const width of [1280, 390]) {
  test(`open worksheet protection reads native settings and fits the viewport at ${width}px`, async ({ page }, info) => {
    await page.setViewportSize({ width, height: 850 })
    await page.goto('/e2e/fixtures/plain-sales-orders/')
    await expect(cell(page, '1:0')).toHaveText('SO-10001')
    await select(page, 'E2', '1:4'); await openProtection(page)
    await expect(panel(page)).toContainText('This worksheet is open for editing.')
    await expect(panel(page)).toContainText('No editable ranges.')
    await expect(button(page, 'Close')).toBeFocused()
    const bounds = (await panel(page).boundingBox())!
    expect(bounds.x).toBeGreaterThanOrEqual(0)
    expect(bounds.x + bounds.width).toBeLessThanOrEqual(width)
    expect(await panel(page).evaluate(node => node.scrollWidth <= node.clientWidth)).toBe(true)
    await page.screenshot({ path: info.outputPath(`protection-open-${width}.png`) })
    await closeProtection(page)
    await expect(cell(page, '1:4')).toHaveText('1')
    await expect(cell(page, '1:5')).toHaveText('79')
    await expect(button(page, 'Undo')).toBeDisabled()
  })

  for (const action of ['Close', 'Escape', 'Tab', 'Shift+Tab'] as const)
    test(`${action} worksheet protection preserves redo and restores focus at ${width}px`, async ({ page }, info) => {
      await page.setViewportSize({ width, height: 850 })
      await page.goto('/e2e/fixtures/plain-sales-orders/')
      await expect(cell(page, '1:0')).toHaveText('SO-10001')
      await select(page, 'E2', '1:4'); await input(page, '2')
      await button(page, 'Undo').click()
      await openProtection(page)
      await expect(button(page, 'Close')).toBeFocused()
      await expect(panel(page).getByRole('textbox')).toHaveCount(0)
      expect(await panel(page).evaluate(node => node.scrollWidth <= node.clientWidth)).toBe(true)
      const bounds = (await panel(page).boundingBox())!
      expect(bounds.x).toBeGreaterThanOrEqual(0)
      expect(bounds.x + bounds.width).toBeLessThanOrEqual(width)
      if (action === 'Close')
        await page.screenshot({ path: info.outputPath(`protection-${width}.png`) })
      if (action === 'Tab' || action === 'Shift+Tab') {
        const first = button(page, 'Allow editing in selection E2')
        const last = button(page, 'Protect worksheet')
        await (action === 'Tab' ? last : first).focus()
        await page.keyboard.press(action)
        await expect(action === 'Tab' ? first : last).toBeFocused()
      }
      if (action === 'Escape') await page.keyboard.press('Escape')
      else await closeProtection(page)
      await expect(panel(page)).toHaveCount(0)
      await expect(button(page, 'Worksheet protection')).toBeFocused()
      await expect(cell(page, '1:4')).toHaveText('1')
      await expect(cell(page, '1:5')).toHaveText('79')
      await expect(button(page, 'Undo')).toBeDisabled()
      await button(page, 'Redo').click()
      await expect(cell(page, '1:4')).toHaveText('2')
      await expect(cell(page, '1:6')).toHaveText('158')
    })

  test(`worksheet protection switches language without losing native settings at ${width}px`, async ({ page }, info) => {
    await page.setViewportSize({ width, height: 850 })
    await page.goto('/e2e/fixtures/plain-sales-orders/')
    await expect(cell(page, '1:0')).toHaveText('SO-10001')
    await select(page, 'E2', '1:4'); await openProtection(page)
    await button(page, 'Allow editing in selection E2').click()
    await closeProtection(page)
    await page.getByRole('combobox', { name: 'Interface language' }).selectOption('zh')
    await button(page, '工作表保护').click()
    const chinese = page.getByRole('dialog', { name: '工作表保护', exact: true })
    await expect(chinese).toBeVisible()
    await expect(button(page, '删除可编辑区域 E2')).toBeEnabled()
    await expect(chinese).toContainText('不加密')
    await page.screenshot({ path: info.outputPath(`protection-zh-${width}.png`) })
    await button(page, '关闭').click()
    await page.getByRole('combobox', { name: '界面语言' }).selectOption('en')
    await openProtection(page)
    await expect(button(page, 'Remove editable range E2')).toBeVisible()
    await closeProtection(page)
    await expect(cell(page, '1:4')).toHaveText('1')
    await expect(button(page, 'Undo')).toBeDisabled()
  })
}
