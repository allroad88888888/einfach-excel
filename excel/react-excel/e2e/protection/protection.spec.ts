import { expect, test } from '@playwright/test'
import { button, cell, editor, panel, select, openProtection, protect, closeProtection, input } from './support'

for (const width of [1280, 390]) test.describe(`${width}px native worksheet protection`, () => {
  test.use({ viewport: { width, height: 850 } })
  test.beforeEach(async ({ page }) => {
    await page.goto('/e2e/fixtures/plain-sales-orders/')
    await expect(cell(page, '1:0')).toHaveText('SO-10001')
    await select(page, 'E2', '1:4')
  })

  test(`protect worksheet rejects locked input without changing data or content history at ${width}px`, async ({ page }) => {
    await input(page, '2')
    await expect(cell(page, '1:6')).toHaveText('158')
    await openProtection(page); await protect(page); await closeProtection(page)
    await input(page, '9')
    await expect(cell(page, '1:4')).toHaveText('2')
    await expect(cell(page, '1:5')).toHaveText('79')
    await editor(page).press('Escape')
    await openProtection(page)
    await button(page, 'Unprotect worksheet').click()
    await expect(button(page, 'Protect worksheet')).toBeEnabled()
    await closeProtection(page)
    await button(page, 'Undo').click()
    await expect(cell(page, '1:4')).toHaveText('1')
    await expect(cell(page, '1:6')).toHaveText('79')
    await expect(button(page, 'Undo')).toBeDisabled()
  })

  test(`allow selection permits native editing and undo while its neighbor stays locked at ${width}px`, async ({ page }) => {
    await openProtection(page)
    await button(page, 'Allow editing in selection E2').click()
    await expect(button(page, 'Remove editable range E2')).toBeVisible()
    await protect(page); await closeProtection(page)
    await input(page, '2')
    await expect(cell(page, '1:4')).toHaveText('2')
    await expect(cell(page, '1:6')).toHaveText('158')
    await select(page, 'F2', '1:5'); await input(page, '100')
    await expect(cell(page, '1:5')).toHaveText('79')
    await editor(page).press('Escape')
    await button(page, 'Undo').click()
    await expect(cell(page, '1:4')).toHaveText('1')
    await expect(cell(page, '1:6')).toHaveText('79')
    await expect(cell(page, '2:4')).toHaveText('2')
  })

  test(`unprotect worksheet restores locked input and retains configured editable ranges at ${width}px`, async ({ page }) => {
    await openProtection(page)
    await button(page, 'Allow editing in selection E2').click()
    await protect(page)
    await button(page, 'Unprotect worksheet').click()
    await expect(button(page, 'Remove editable range E2')).toBeEnabled()
    await closeProtection(page)
    await select(page, 'F2', '1:5'); await input(page, '100')
    await expect(cell(page, '1:5')).toHaveText('100')
    await expect(cell(page, '1:4')).toHaveText('1')
    await button(page, 'Undo').click()
    await expect(cell(page, '1:5')).toHaveText('79')
    await expect(button(page, 'Undo')).toBeDisabled()
  })

  test(`remove editable range relocks that selection without creating content undo at ${width}px`, async ({ page }) => {
    await openProtection(page)
    await button(page, 'Allow editing in selection E2').click()
    await button(page, 'Remove editable range E2').click()
    await expect(panel(page)).toContainText('No editable ranges.')
    await protect(page); await closeProtection(page)
    await input(page, '9')
    await expect(cell(page, '1:4')).toHaveText('1')
    await expect(cell(page, '1:5')).toHaveText('79')
    await editor(page).press('Escape')
    await expect(button(page, 'Undo')).toBeDisabled()
  })
})
