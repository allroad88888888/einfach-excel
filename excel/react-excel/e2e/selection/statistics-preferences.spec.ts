import { expect, test, type Page } from '@playwright/test'
import { select } from '../support/clipboard'

const statistics = (page: Page) => page.getByRole('status', { name: 'Selection statistics' })
const settings = (page: Page) => page.getByRole('button', { name: 'Selection statistics settings' })
const dialog = (page: Page) => page.getByRole('dialog', { name: 'Selection statistics' })
const labels = ['Count', 'Numerical count', 'Sum', 'Average', 'Min', 'Max']
async function prepareRedo(page: Page) {
  await select(page, 'H94', '93:7')
  const input = page.getByRole('textbox', { name: 'Active cell value' })
  await input.fill('Keep statistics redo'); await input.press('Enter')
  await expect(page.locator('td[data-cell="93:7"]')).toHaveText('Keep statistics redo')
  await page.getByRole('button', { name: 'Undo', exact: true }).click()
  await expect(page.locator('td[data-cell="93:7"]')).toHaveText('')
  await select(page, 'A93:F93', '92:0')
}
test.beforeEach(async ({ page }) => {
  await page.goto('/')
  await expect(page.locator('td[data-cell="1:0"]')).toHaveText('SO-10001')
  await page.getByRole('tab', { name: 'Summary', exact: true }).click()
  await select(page, 'A93:F93', '92:0')
  await expect(statistics(page)).toContainText('Sum: 26')
})

for (const label of labels) for (const width of [1280, 390])
  test(`toggle ${label} statistic changes only its visibility at ${width}px`, async ({ page }) => {
    await page.setViewportSize({ width, height: 850 })
    await settings(page).click()
    const checkbox = dialog(page).getByRole('checkbox', { name: label, exact: true })
    await checkbox.uncheck()
    await expect(statistics(page).getByRole('button', { name: `Copy ${label}`, exact: true })).toHaveCount(0)
    for (const other of labels.filter((key) => key !== label))
      await expect(statistics(page).getByRole('button', { name: `Copy ${other}`, exact: true })).toHaveCount(1)
    await checkbox.check()
    await expect(statistics(page).getByRole('button')).toHaveCount(6)
    await dialog(page).getByRole('button', { name: 'Done', exact: true }).click()
    await expect(settings(page)).toBeFocused()
    await expect(page.getByRole('textbox', { name: 'Name box' })).toHaveValue('A93:F93')
    await expect(page.locator('td[data-cell="92:0"]')).toHaveText('10')
    await expect(page.locator('td[data-cell="92:0"]')).toHaveCSS('font-style', 'italic')
    await expect(page.locator('td[data-cell="92:2"]')).toHaveText('-4')
    await expect(page.getByRole('button', { name: 'Undo', exact: true })).toBeDisabled()
  })

for (const action of ['Open', 'Done', 'Escape', 'Tab', 'Shift+Tab']) for (const width of [1280, 390])
  test(`${action} statistics settings preserves immediate preferences and history at ${width}px`, async ({ page }) => {
    await page.setViewportSize({ width, height: 850 })
    await prepareRedo(page)
    const input = page.getByRole('textbox', { name: 'Active cell value' })
    await settings(page).click()
    if (action === 'Open') {
      await expect(dialog(page).getByRole('checkbox')).toHaveCount(6)
      await expect(dialog(page).getByRole('checkbox', { name: 'Count', exact: true })).toBeFocused()
      const box = (await dialog(page).boundingBox())!
      expect(box.x).toBeGreaterThanOrEqual(0)
      expect(box.x + box.width).toBeLessThanOrEqual(width)
    } else {
      await dialog(page).getByRole('checkbox', { name: 'Sum', exact: true }).uncheck()
      await expect(statistics(page).getByRole('button', { name: 'Copy Sum', exact: true })).toHaveCount(0)
    }
    if (action === 'Tab' || action === 'Shift+Tab') {
      const first = dialog(page).getByRole('checkbox', { name: 'Count', exact: true })
      const last = dialog(page).getByRole('button', { name: 'Done', exact: true })
      await (action === 'Tab' ? last : first).focus()
      await page.keyboard.press(action)
      await expect(action === 'Tab' ? first : last).toBeFocused()
    }
    if (action === 'Escape') await page.keyboard.press('Escape')
    else await dialog(page).getByRole('button', { name: 'Done', exact: true }).click()
    await expect(dialog(page)).toHaveCount(0)
    await expect(settings(page)).toBeFocused()
    await expect(page.getByRole('textbox', { name: 'Name box' })).toHaveValue('A93:F93')
    await expect(statistics(page).getByRole('button')).toHaveCount(action === 'Open' ? 6 : 5)
    await expect(page.locator('td[data-cell="92:0"]')).toHaveText('10')
    await expect(page.getByRole('button', { name: 'Undo', exact: true })).toBeDisabled()
    await page.getByRole('button', { name: 'Redo', exact: true }).click()
    await select(page, 'H94', '93:7')
    await expect(input).toHaveValue('Keep statistics redo')
  })

for (const width of [1280, 390])
  test(`reload resets only session statistics preferences to six defaults at ${width}px`, async ({ page }, info) => {
    await page.setViewportSize({ width, height: 850 })
    await settings(page).click()
    for (const label of labels)
      await dialog(page).getByRole('checkbox', { name: label, exact: true }).uncheck()
    await expect(statistics(page)).toHaveText('No statistics selected')
    await dialog(page).getByRole('button', { name: 'Done', exact: true }).click()
    await page.reload()
    await expect(page.locator('td[data-cell="1:0"]')).toHaveText('SO-10001')
    await page.getByRole('tab', { name: 'Summary', exact: true }).click()
    await select(page, 'A93:F93', '92:0')
    await expect(statistics(page).getByRole('button')).toHaveCount(6)
    await expect(statistics(page)).toContainText('Sum: 26')
    await expect(page.locator('td[data-cell="92:0"]')).toHaveCSS('font-style', 'italic')
    await expect(page.locator('td[data-cell="92:2"]')).toHaveText('-4')
    await expect(page.getByRole('button', { name: 'Undo', exact: true })).toBeDisabled()
    await settings(page).click()
    for (const label of labels)
      await expect(dialog(page).getByRole('checkbox', { name: label, exact: true })).toBeChecked()
    expect(await dialog(page).evaluate(node => node.scrollWidth <= node.clientWidth)).toBe(true)
    for (const control of await dialog(page).locator('input, button').all())
      await expect(control).toBeInViewport()
    await page.screenshot({ path: info.outputPath(`statistics-defaults-${width}.png`) })
    await dialog(page).getByRole('button', { name: 'Done', exact: true }).click()
    await expect(settings(page)).toBeFocused()
  })

for (const width of [1280, 390])
  test(`restore default statistics resets all six without changing redo at ${width}px`, async ({ page }) => {
    await page.setViewportSize({ width, height: 850 })
    await prepareRedo(page)
    await settings(page).click()
    for (const label of ['Count', 'Average', 'Min'])
      await dialog(page).getByRole('checkbox', { name: label, exact: true }).uncheck()
    await expect(statistics(page).getByRole('button')).toHaveCount(3)
    await dialog(page).getByRole('button', { name: 'Restore defaults', exact: true }).click()
    for (const label of labels)
      await expect(dialog(page).getByRole('checkbox', { name: label, exact: true })).toBeChecked()
    for (const text of ['Count: 6', 'Numerical count: 4', 'Sum: 26', 'Average: 6.5', 'Min: -4', 'Max: 20'])
      await expect(statistics(page).getByRole('button', { name: `Copy ${text.split(':')[0]}`, exact: true })).toHaveText(text)
    await dialog(page).getByRole('button', { name: 'Done', exact: true }).click()
    await expect(page.getByRole('textbox', { name: 'Name box' })).toHaveValue('A93:F93')
    await expect(page.locator('td[data-cell="92:0"]')).toHaveText('10')
    await expect(page.getByRole('button', { name: 'Undo', exact: true })).toBeDisabled()
    await page.getByRole('button', { name: 'Redo', exact: true }).click()
    await select(page, 'H94', '93:7')
    await expect(page.getByRole('textbox', { name: 'Active cell value' })).toHaveValue('Keep statistics redo')
  })
