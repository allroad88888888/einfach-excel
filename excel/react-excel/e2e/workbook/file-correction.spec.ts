import { readFile } from 'node:fs/promises'
import { expect, test } from '@playwright/test'
import { select } from '../support/clipboard'

for (const width of [1280, 390])
  test(`invalid native file corrects in the same dialog before replacing the workbook at ${width}px`, async ({ page }) => {
    await page.setViewportSize({ width, height: 850 })
    await page.goto('/e2e/fixtures/plain-sales-orders/')
    const cell = (coord: string) => page.locator(`td[data-cell="${coord}"]`)
    const button = (name: string) => page.getByRole('button', { name, exact: true })
    await expect(cell('1:0')).toHaveText('SO-10001')
    await select(page, 'E2', '1:4')
    const bar = page.getByRole('textbox', { name: 'Active cell value', exact: true })
    await bar.fill('2')
    await bar.press('Enter')
    await expect(cell('1:6')).toHaveText('158')
    await button('File').click()
    const downloading = page.waitForEvent('download')
    await button('Download workbook').click()
    const text = await readFile((await (await downloading).path())!, 'utf8')
    const input = page.getByLabel('Open workbook', { exact: true })
    const panel = page.getByRole('dialog', { name: 'Workbook files' })
    page.on('dialog', dialog => dialog.accept())
    await input.setInputFiles({ name: 'Book.einfach.json', mimeType: 'application/json',
      buffer: Buffer.from('{not json') })
    await expect(panel.getByRole('alert')).toContainText('Current workbook kept')
    await expect(cell('1:6')).toHaveText('158')
    await expect(button('Undo')).toBeEnabled()
    await input.setInputFiles({ name: 'Book.einfach.json', mimeType: 'application/json',
      buffer: Buffer.from(text) })
    await expect(panel).toHaveCount(0)
    await select(page, 'E2', '1:4')
    await expect(cell('1:4')).toHaveText('2')
    await expect(cell('1:4')).toHaveCSS('color', 'rgb(192, 0, 0)')
    await expect(cell('1:5')).toHaveText('79')
    await expect(cell('1:6')).toHaveText('158')
    await expect(cell('1:6')).toHaveCSS('font-family', 'Georgia')
    await expect(button('Undo')).toBeDisabled()
    await expect(button('Redo')).toBeDisabled()
    await bar.fill('3')
    await bar.press('Enter')
    await expect(cell('1:6')).toHaveText('237')
    await button('Undo').click()
    await expect(cell('1:6')).toHaveText('158')
    await expect(button('Undo')).toBeDisabled()
  })
