import { expect, test } from '@playwright/test'
import { select } from '../support/clipboard'

for (const width of [1280, 390]) for (const action of ['Open', 'Tab', 'Shift+Tab', 'Cancel', 'Escape'])
  test(`${action} name manager preserves native definitions formulas and redo at ${width}px`, async ({ page }, info) => {
    await page.setViewportSize({ width, height: 850 })
    await page.goto('/e2e/fixtures/plain-sales-orders/')
    const cell = (coord: string) => page.locator(`td[data-cell="${coord}"]`)
    const button = (name: string) => page.getByRole('button', { name, exact: true })
    await expect(cell('1:0')).toHaveText('SO-10001')
    await select(page, 'E2', '1:4')
    const bar = page.getByRole('textbox', { name: 'Active cell value', exact: true })
    await bar.fill('2')
    await bar.press('Enter')
    await expect(cell('1:6')).toHaveText('158')
    await button('Undo').click()
    await select(page, 'G2', '1:6')
    await button('Name manager').click()
    const dialog = page.getByRole('dialog', { name: 'Name manager', exact: true })
    const name = dialog.getByRole('textbox', { name: 'Name', exact: true })
    await expect(name).toBeFocused()
    await expect(name).toHaveValue('')
    await expect(dialog.getByRole('textbox', { name: 'Refers to', exact: true })).toHaveValue('G2')
    const first = dialog.getByRole('button', { name: 'Edit SampleAmounts', exact: true })
    const last = dialog.getByRole('button', { name: 'Create name', exact: true })
    if (action === 'Open') {
      expect(await dialog.evaluate(node => node.scrollWidth <= node.clientWidth)).toBe(true)
      const box = (await dialog.boundingBox())!
      expect(box.x).toBeGreaterThanOrEqual(0)
      expect(box.x + box.width).toBeLessThanOrEqual(width)
      await page.screenshot({ path: info.outputPath(`name-manager-open-${width}.png`) })
    } else if (action === 'Tab' || action === 'Shift+Tab') {
      await (action === 'Tab' ? last : first).focus()
      await page.keyboard.press(action)
      await expect(action === 'Tab' ? first : last).toBeFocused()
    } else {
      await name.fill('UnsubmittedName')
      await dialog.getByRole('combobox', { name: 'Worksheet', exact: true }).selectOption('summary')
      await dialog.getByRole('textbox', { name: 'Refers to', exact: true }).fill('C65:C67')
    }
    if (action === 'Escape') await page.keyboard.press('Escape')
    else await button('Cancel').click()
    await expect(dialog).toHaveCount(0)
    await expect(button('Name manager')).toBeFocused()
    await expect(page.getByRole('textbox', { name: 'Name box' })).toHaveValue('G2')
    await expect(bar).toHaveValue('=E2*F2')
    await expect(cell('1:6')).toHaveText('79')
    await expect(cell('1:6')).toHaveCSS('font-family', 'Georgia')
    await expect(cell('1:5')).toHaveText('79')
    await expect(button('Undo')).toBeDisabled()
    await button('Redo').click()
    await expect(cell('1:6')).toHaveText('158')
    await button('Name manager').click()
    await expect(first).toBeVisible()
    await expect(name).toHaveValue('')
    await expect(dialog.getByRole('textbox', { name: 'Refers to', exact: true })).toHaveValue('G2')
    await expect(dialog.getByRole('combobox', { name: 'Worksheet', exact: true })
      .locator('option:checked')).toHaveText('Sales Orders')
    await button('Cancel').click()
  })
