import { expect, test, type Page } from '@playwright/test'
import { select } from '../support/clipboard'

const button = (page: Page, name: string) => page.getByRole('button', { name, exact: true })
const cell = (page: Page, coord: string) => page.locator(`td[data-cell="${coord}"]`)
async function open(page: Page) {
  await button(page, 'Name manager').click()
  return page.getByRole('dialog', { name: 'Name manager' })
}
async function input(page: Page, address: string, coord: string, value: string) {
  await select(page, address, coord)
  await page.locator('[data-workbook-grid]').press('F2')
  const editor = page.getByRole('textbox', { name: 'Cell editor', exact: true })
  await editor.fill(value); await editor.press('Enter')
  await expect(editor).toHaveCount(0)
}
async function save(page: Page, label: string) {
  await button(page, label).click()
  await expect(page.getByRole('dialog', { name: 'Name manager' })).toHaveCount(0)
}
test.beforeEach(async ({ page }) => {
  await page.goto('/')
  await expect(cell(page, '1:0')).toHaveText('SO-10001')
})

test('native name CRUD rewrites formulas and each operation has undo/redo', async ({ page }) => {
  await select(page, 'E2:E4', '1:4')
  await open(page)
  await expect(page.getByLabel('Refers to', { exact: true })).toHaveValue('E2:E4')
  await page.getByLabel('Name', { exact: true }).fill('OrderUnits')
  await save(page, 'Create name')
  await input(page, 'J2', '1:9', '=SUM(OrderUnits)')
  const total = await cell(page, '1:9').innerText()
  expect(Number(total)).toBeGreaterThan(0)
  await open(page); await button(page, 'Edit OrderUnits').click()
  await page.getByLabel('Name', { exact: true }).fill('订单数量')
  await save(page, 'Save changes')
  await expect(cell(page, '1:9')).toHaveText(total)
  await select(page, 'J2', '1:9')
  await expect(page.getByRole('textbox', { name: 'Active cell value' })).toHaveValue('=SUM(订单数量)')
  await button(page, 'Undo').click()
  await expect(page.getByRole('textbox', { name: 'Active cell value' })).toHaveValue('=SUM(OrderUnits)')
  await button(page, 'Redo').click()
  await expect(page.getByRole('textbox', { name: 'Active cell value' })).toHaveValue('=SUM(订单数量)')
  await open(page); await button(page, 'Edit 订单数量').click()
  await page.getByLabel('Refers to', { exact: true }).fill('E2')
  await save(page, 'Save changes')
  const first = await cell(page, '1:4').innerText()
  await expect(cell(page, '1:9')).toHaveText(first)
  await open(page); await button(page, 'Edit 订单数量').click(); await save(page, 'Delete name')
  await expect(cell(page, '1:9')).toHaveText('#NAME?')
  await button(page, 'Undo').click()
  await expect(cell(page, '1:9')).toHaveText(first)
  await open(page)
  await expect(button(page, 'Edit 订单数量')).toBeVisible()
  await save(page, 'Cancel')
  await button(page, 'Redo').click()
  await expect(cell(page, '1:9')).toHaveText('#NAME?')
})

test('cross-sheet targets stay live and duplicate names preserve the draft', async ({ page }) => {
  await open(page)
  await page.getByLabel('Name', { exact: true }).fill('SummaryValues')
  await page.getByLabel('Worksheet', { exact: true }).selectOption('summary')
  await page.getByLabel('Refers to', { exact: true }).fill('C65:C67')
  await save(page, 'Create name')
  await input(page, 'J2', '1:9', '=SUM(SummaryValues)')
  await expect(cell(page, '1:9')).toHaveText('12')
  await open(page)
  await page.getByLabel('Name', { exact: true }).fill('summaryvalues')
  await button(page, 'Create name').click()
  await expect(page.getByRole('alert')).toContainText(/already|exists|duplicate/i)
  await expect(page.getByLabel('Name', { exact: true })).toHaveValue('summaryvalues')
  await save(page, 'Cancel')
  await page.getByRole('tab', { name: 'Summary', exact: true }).click()
  await input(page, 'C65', '64:2', '8')
  await page.getByRole('tab', { name: 'Sales Orders', exact: true }).click()
  await select(page, 'J2', '1:9')
  await expect(cell(page, '1:9')).toHaveText('18')
})

for (const width of [1280, 390]) test(`name manager fits ${width}px and traps keyboard focus`, async ({ page }, info) => {
  const errors: string[] = []
  page.on('pageerror', (error) => errors.push(error.message))
  await page.setViewportSize({ width, height: 800 })
  const dialog = await open(page)
  await expect(page.getByLabel('Name', { exact: true })).toBeFocused()
  await dialog.getByRole('button').first().focus(); await page.keyboard.press('Shift+Tab')
  await expect(button(page, 'Create name')).toBeFocused()
  const box = (await dialog.boundingBox())!
  expect(box.x).toBeGreaterThanOrEqual(0)
  expect(box.x + box.width).toBeLessThanOrEqual(width)
  expect(await dialog.evaluate((node) => node.scrollWidth <= node.clientWidth)).toBe(true)
  await page.screenshot({ path: info.outputPath(`named-ranges-${width}.png`) })
  await page.keyboard.press('Escape')
  await expect(dialog).toHaveCount(0)
  await expect(button(page, 'Name manager')).toBeFocused()
  expect(errors).toEqual([])
})

