test('deleting a source range retains its broken name for repair and undo', async ({ page }) => {
  await page.getByRole('tab', { name: 'Summary', exact: true }).click()
  await select(page, 'C65:C67', '64:2')
  await page.getByRole('combobox', { name: 'Insert or delete rows and columns' })
    .selectOption('delete-rows')
  await open(page); await button(page, 'Edit SampleAmounts').click()
  await expect(page.getByLabel('Refers to', { exact: true })).toHaveValue('#REF!')
  await page.getByLabel('Refers to', { exact: true }).fill('B9')
  await save(page, 'Save changes')
  await select(page, 'B4', '3:1')
  await expect(cell(page, '3:1')).toHaveText('10')
  await button(page, 'Undo').click()
  await expect(cell(page, '3:1')).toHaveText('#REF!')
  await button(page, 'Undo').click()
  await expect(cell(page, '3:1')).toHaveText('12')
})

for (const width of [1280, 390]) test.describe(`${width}px independent name actions`, () => {
  test.use({ viewport: { width, height: 850 } })

  test(`create a name through the manager without changing its source at ${width}px`, async ({ page }) => {
    const dialog = await open(page)
    const count = await dialog.getByRole('group', { name: 'Workbook names' }).getByRole('button').count()
    await page.getByLabel('Name', { exact: true }).fill('IndependentAmounts')
    await page.getByLabel('Worksheet', { exact: true }).selectOption('summary')
    await page.getByLabel('Refers to', { exact: true }).fill('C65:C66')
    await save(page, 'Create name')
    await open(page)
    await expect(button(page, 'Edit IndependentAmounts')).toContainText('Summary!C65:C66')
    await expect(dialog.getByRole('group', { name: 'Workbook names' }).getByRole('button')).toHaveCount(count + 1)
    await save(page, 'Cancel')
    await button(page, 'Undo').click()
    await expect(button(page, 'Undo')).toBeDisabled()
    await open(page)
    await expect(button(page, 'Edit IndependentAmounts')).toHaveCount(0)
    await expect(button(page, 'Edit SampleAmounts')).toBeVisible()
    await save(page, 'Cancel')
    await button(page, 'Redo').click()
    await page.getByRole('tab', { name: 'Summary', exact: true }).click()
    await expect(cell(page, '3:1')).toHaveText('12')
    await input(page, 'B5', '4:1', '=SUM(IndependentAmounts)')
    await expect(cell(page, '4:1')).toHaveText('6')
    await expect(cell(page, '3:1')).toHaveText('12')
  })

  test(`rename a seeded name rewrites its formula in one step at ${width}px`, async ({ page }) => {
    await page.getByRole('tab', { name: 'Summary', exact: true }).click()
    await select(page, 'B4', '3:1')
    const bar = page.getByRole('textbox', { name: 'Active cell value' })
    await expect(bar).toHaveValue('=SUM(SampleAmounts)')
    await open(page)
    await button(page, 'Edit SampleAmounts').click()
    await page.getByLabel('Name', { exact: true }).fill('净收入')
    await save(page, 'Save changes')
    await expect(cell(page, '3:1')).toHaveText('12')
    await expect(bar).toHaveValue('=SUM(净收入)')
    await open(page)
    await expect(button(page, 'Edit SampleAmounts')).toHaveCount(0)
    await expect(button(page, 'Edit 净收入')).toContainText('Summary!C65:C67')
    await save(page, 'Cancel')
    await button(page, 'Undo').click()
    await expect(bar).toHaveValue('=SUM(SampleAmounts)')
    await expect(button(page, 'Undo')).toBeDisabled()
    await button(page, 'Redo').click()
    await expect(bar).toHaveValue('=SUM(净收入)')
    await expect(cell(page, '3:1')).toHaveText('12')
  })

  test(`delete a seeded name keeps its formula and can undo once at ${width}px`, async ({ page }) => {
    await page.getByRole('tab', { name: 'Summary', exact: true }).click()
    await select(page, 'B4', '3:1')
    const total = await cell(page, '0:1').innerText()
    await open(page)
    await button(page, 'Edit SampleAmounts').click()
    await save(page, 'Delete name')
    await expect(cell(page, '3:1')).toHaveText('#NAME?')
    await expect(page.getByRole('textbox', { name: 'Active cell value' })).toHaveValue('=SUM(SampleAmounts)')
    await expect(cell(page, '0:1')).toHaveText(total)
    await open(page)
    await expect(button(page, 'Edit SampleAmounts')).toHaveCount(0)
    await save(page, 'Cancel')
    await button(page, 'Undo').click()
    await expect(cell(page, '3:1')).toHaveText('12')
    await expect(button(page, 'Undo')).toBeDisabled()
    await open(page)
    await expect(button(page, 'Edit SampleAmounts')).toContainText('Summary!C65:C67')
    await save(page, 'Cancel')
    await button(page, 'Redo').click()
    await expect(cell(page, '3:1')).toHaveText('#NAME?')
    await expect(cell(page, '0:1')).toHaveText(total)
  })

  test(`change a named range worksheet without changing its address at ${width}px`, async ({ page }) => {
    await page.getByRole('tab', { name: 'Summary', exact: true }).click()
    await select(page, 'B4', '3:1')
    await open(page)
    await button(page, 'Edit SampleAmounts').click()
    await page.getByLabel('Worksheet', { exact: true }).selectOption('orders')
    await save(page, 'Save changes')
    await expect(cell(page, '3:1')).toHaveText('0')
    await open(page)
    await expect(button(page, 'Edit SampleAmounts')).toContainText('Sales Orders!C65:C67')
    await button(page, 'Edit SampleAmounts').click()
    await expect(page.getByLabel('Worksheet', { exact: true })).toHaveValue('orders')
    await expect(page.getByLabel('Refers to', { exact: true })).toHaveValue('C65:C67')
    await save(page, 'Cancel')
    await button(page, 'Undo').click()
    await expect(cell(page, '3:1')).toHaveText('12')
    await expect(button(page, 'Undo')).toBeDisabled()
    await button(page, 'Redo').click()
    await expect(cell(page, '3:1')).toHaveText('0')
    await expect(page.getByRole('textbox', { name: 'Active cell value' })).toHaveValue('=SUM(SampleAmounts)')
  })

  test(`new name discards an existing name draft without saving at ${width}px`, async ({ page }) => {
    await page.getByRole('tab', { name: 'Summary', exact: true }).click()
    await select(page, 'B4', '3:1')
    await open(page)
    await button(page, 'Edit SampleAmounts').click()
    await page.getByLabel('Name', { exact: true }).fill('ForgottenDraft')
    await page.getByLabel('Refers to', { exact: true }).fill('Z99')
    await button(page, 'New name').click()
    await expect(page.getByLabel('Name', { exact: true })).toHaveValue('')
    await expect(page.getByLabel('Refers to', { exact: true })).toHaveValue('B4')
    await expect(page.getByLabel('Worksheet', { exact: true })).toHaveValue('summary')
    await expect(button(page, 'Delete name')).toBeDisabled()
    await expect(button(page, 'Create name')).toBeVisible()
    await save(page, 'Cancel')
    await expect(button(page, 'Undo')).toBeDisabled()
    await expect(cell(page, '3:1')).toHaveText('12')
    await open(page)
    await expect(button(page, 'Edit ForgottenDraft')).toHaveCount(0)
    await button(page, 'Edit SampleAmounts').click()
    await expect(page.getByLabel('Refers to', { exact: true })).toHaveValue('C65:C67')
  })
})
