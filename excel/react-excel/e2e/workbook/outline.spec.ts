import { expect, test, type Page } from '@playwright/test'
import { select } from '../support/clipboard'

const cell = (page: Page, coord: string) => page.locator(`td[data-cell="${coord}"]`)
const button = (page: Page, name: string) => page.getByRole('button', { name, exact: true })
async function outline(page: Page, action: string) {
  const menu = page.getByRole('combobox', { name: 'Outline groups' })
  await menu.selectOption(action)
  await expect(menu).toBeEnabled()
  await expect(page.getByRole('alert')).toHaveCount(0)
}
test.beforeEach(async ({ page }) => {
  await page.goto('/')
  await expect(cell(page, '1:0')).toHaveText('SO-10001')
})

test('row grouping collapses without gaps and uses native undo/redo', async ({ page }) => {
  await select(page, 'A3:A5', '2:0')
  await outline(page, 'group-rows')
  await button(page, 'Collapse rows 3–5, level 1').click()
  await expect(cell(page, '2:0')).toHaveCount(0)
  await select(page, 'A2', '1:0')
  const before = (await cell(page, '1:0').boundingBox())!
  const after = (await cell(page, '5:0').boundingBox())!
  expect(Math.abs(after.y - before.y - before.height)).toBeLessThan(1)
  await button(page, 'Undo').click()
  await expect(cell(page, '2:0')).toHaveText('SO-10002')
  await button(page, 'Redo').click()
  await expect(cell(page, '2:0')).toHaveCount(0)
  await button(page, 'Expand rows 3–5, level 1').click()
  await expect(cell(page, '2:0')).toHaveText('SO-10002')
  await select(page, 'A3:A5', '2:0')
  await outline(page, 'ungroup-rows')
  await expect(page.locator('.outline-row')).toHaveCount(0)
  await button(page, 'Undo').click()
  await expect(button(page, 'Collapse rows 3–5, level 1')).toBeVisible()
})

test('column expansion keeps manual hiding and scrolling controls follow their columns', async ({ page }) => {
  await select(page, 'C2', '1:2')
  await page.getByRole('combobox', { name: 'Row and column visibility' }).selectOption('hide-columns')
  await expect(cell(page, '1:2')).toHaveCount(0)
  await select(page, 'B2:D2', '1:1')
  await outline(page, 'group-columns')
  await button(page, 'Collapse columns B–D, level 1').click()
  await expect(cell(page, '1:1')).toHaveCount(0)
  await button(page, 'Expand columns B–D, level 1').click()
  await expect(cell(page, '1:1')).toHaveText('Acme Co.')
  await expect(cell(page, '1:2')).toHaveCount(0)
  await select(page, 'M2:O2', '1:12')
  await outline(page, 'group-columns')
  await expect(button(page, 'Collapse columns M–O, level 1')).toBeVisible()
  await button(page, 'Collapse columns M–O, level 1').click()
  await expect(cell(page, '1:12')).toHaveCount(0)
  await button(page, 'Expand columns M–O, level 1').click()
  await expect(cell(page, '1:12')).toBeVisible()
})

test('nested groups retain child collapse and partial overlaps fail without losing history', async ({ page }) => {
  await select(page, 'A3:A7', '2:0'); await outline(page, 'group-rows')
  await select(page, 'A4:A5', '3:0'); await outline(page, 'group-rows')
  await button(page, 'Collapse rows 4–5, level 2').click()
  await button(page, 'Collapse rows 3–7, level 1').click()
  await expect(button(page, 'Expand rows 4–5, level 2')).toHaveCount(0)
  await button(page, 'Expand rows 3–7, level 1').click()
  await expect(cell(page, '2:0')).toBeVisible()
  await expect(cell(page, '3:0')).toHaveCount(0)
  await button(page, 'Show row outline level 3').click()
  await expect(cell(page, '3:0')).toBeVisible()
  await select(page, 'A6:A9', '5:0')
  await page.getByRole('combobox', { name: 'Outline groups' }).selectOption('group-rows')
  await expect(page.getByRole('alert')).toContainText('partially overlap')
  await expect(button(page, 'Collapse rows 3–7, level 1')).toBeVisible()
})

test('Summary seeds use native nesting, SUBTOTAL and independent manual hidden axes', async ({ page }) => {
  await page.getByRole('tab', { name: 'Summary', exact: true }).click()
  await expect(button(page, 'Collapse rows 8–12, level 1')).toBeVisible()
  await expect(button(page, 'Undo')).toBeDisabled()
  await expect(cell(page, '11:1')).toHaveText('30')
  await button(page, 'Collapse rows 9–11, level 2').click()
  await expect(cell(page, '11:1')).toHaveText('0')
  await button(page, 'Expand rows 9–11, level 2').click()
  await expect(cell(page, '11:1')).toHaveText('30')
  await expect(cell(page, '9:0')).toHaveCount(0)
  await outline(page, 'collapse-columns')
  await expect(cell(page, '1:4')).toHaveCount(0)
  await outline(page, 'expand-columns')
  await expect(cell(page, '1:4')).toBeVisible()
  await expect(cell(page, '0:6')).toHaveCount(0)
})

test('outline survives insert/undo and freeze crossing without moving cell editors', async ({ page }) => {
  await select(page, 'C4', '3:2')
  await page.getByRole('combobox', { name: 'Freeze panes' }).selectOption('selection')
  await select(page, 'A2:A6', '1:0'); await outline(page, 'group-rows')
  await select(page, 'B2:D2', '1:1'); await outline(page, 'group-columns')
  await outline(page, 'collapse-rows')
  await expect(cell(page, '1:0')).toHaveCount(0)
  await outline(page, 'expand-rows')
  await select(page, 'A3', '2:0')
  await page.getByRole('combobox', { name: 'Insert or delete rows and columns' }).selectOption('insert-rows')
  await expect(button(page, 'Collapse rows 2–7, level 1')).toBeVisible()
  await button(page, 'Undo').click()
  await expect(button(page, 'Collapse rows 2–6, level 1')).toBeVisible()
  await select(page, 'B2', '1:1')
  await page.locator('[data-workbook-grid]').press('F2')
  const editor = page.getByRole('textbox', { name: 'Cell editor', exact: true })
  await expect(editor).toBeVisible()
  const anchor = (await cell(page, '1:1').boundingBox())!, box = (await editor.boundingBox())!
  expect(Math.abs(anchor.x - box.x)).toBeLessThanOrEqual(2)
  expect(Math.abs(anchor.y - box.y)).toBeLessThanOrEqual(2)
  await editor.press('Escape')
})

for (const width of [1280, 390]) test(`outline controls fit ${width}px and remain keyboard accessible`, async ({ page }, info) => {
  const errors: string[] = []
  page.on('pageerror', (error) => errors.push(error.message))
  await page.setViewportSize({ width, height: 800 })
  await select(page, 'A3:A5', '2:0'); await outline(page, 'group-rows')
  await select(page, 'B2:C2', '1:1'); await outline(page, 'group-columns')
  const collapse = button(page, 'Collapse rows 3–5, level 1')
  await collapse.focus(); await collapse.press('Enter')
  await expect(cell(page, '2:0')).toHaveCount(0)
  await expect(page.locator('[data-workbook-grid]')).toBeFocused()
  await button(page, 'Expand rows 3–5, level 1').click()
  expect(await page.evaluate(() => document.documentElement.scrollWidth <= window.innerWidth)).toBe(true)
  const scroll = (await page.getByTestId('sheet-scroll').boundingBox())!
  const gutter = (await page.locator('.outline-row').boundingBox())!
  expect(gutter.x + gutter.width).toBeLessThanOrEqual(scroll.x + 1)
  await page.screenshot({ path: info.outputPath(`outline-${width}.png`) })
  expect(errors).toEqual([])
})
