import { expect, test } from '../support/input-stall-fixture'
import { select } from '../support/clipboard'

for (const width of [1280, 390]) for (const action of ['Open', 'Tab', 'Shift+Tab', 'Cancel', 'Escape'])
  test(`${action} Tables preserves native tables cell styles and redo at ${width}px`, async ({ page }, info) => {
    await page.setViewportSize({ width, height: 850 })
    await page.goto('/e2e/fixtures/plain-sales-orders/')
    const cell = (coord: string) => page.locator(`td[data-cell="${coord}"]`)
    const button = (name: string) => page.getByRole('button', { name, exact: true })
    await expect(cell('1:0')).toHaveText('SO-10001')
    await page.getByRole('tab', { name: 'Summary', exact: true }).click()
    await select(page, 'H94', '93:7')
    const bar = page.getByRole('textbox', { name: 'Active cell value', exact: true })
    await bar.fill('table redo')
    await bar.press('Enter')
    await expect(cell('93:7')).toHaveText('table redo')
    await button('Undo').click()
    await select(page, 'C75', '74:2')
    const background = await cell('74:2').evaluate(node => getComputedStyle(node).backgroundColor)
    await button('Tables').click()
    const dialog = page.getByRole('dialog', { name: 'Tables', exact: true })
    const name = dialog.getByRole('textbox', { name: 'Table name', exact: true })
    await expect(name).toBeFocused()
    await expect(name).toHaveValue('')
    await expect(dialog.getByRole('textbox', { name: 'Table range', exact: true })).toHaveValue('C75')
    // 原生目录按名称排序，CalculatedOrders 排在 DemoTable 前。
    const first = dialog.getByRole('button', { name: 'Edit table CalculatedOrders', exact: true })
    const last = dialog.getByRole('button', { name: 'Create table', exact: true })
    if (action === 'Open') {
      expect(await dialog.evaluate(node => node.scrollWidth <= node.clientWidth)).toBe(true)
      const box = (await dialog.boundingBox())!
      expect(box.x).toBeGreaterThanOrEqual(0)
      expect(box.x + box.width).toBeLessThanOrEqual(width)
      await page.screenshot({ path: info.outputPath(`tables-open-${width}.png`) })
    } else if (action === 'Tab' || action === 'Shift+Tab') {
      await (action === 'Tab' ? last : first).focus()
      await page.keyboard.press(action)
      await expect(action === 'Tab' ? first : last).toBeFocused()
    } else {
      await name.fill('UnsubmittedTable')
      await dialog.getByRole('textbox', { name: 'Table range', exact: true }).fill('Z99')
    }
    if (action === 'Escape') await page.keyboard.press('Escape')
    else await button('Cancel').click()
    await expect(dialog).toHaveCount(0)
    await expect(button('Tables')).toBeFocused()
    await expect(page.getByRole('textbox', { name: 'Name box' })).toHaveValue('C75')
    await expect(cell('74:2')).toHaveText('-10')
    await expect(cell('74:2')).toHaveCSS('background-color', background)
    await expect(button('Undo')).toBeDisabled()
    await button('Redo').click()
    await select(page, 'H94', '93:7')
    await expect(cell('93:7')).toHaveText('table redo')
    await select(page, 'B5', '4:1')
    await expect(cell('4:1')).toHaveText('60')
    await expect(bar).toHaveValue('=SUM(DemoTable[Amount])')
    await button('Tables').click()
    await expect(first).toBeVisible()
    await expect(button('Edit table DemoTable')).toBeVisible()
    await expect(button('Edit table UnsubmittedTable')).toHaveCount(0)
    await expect(name).toHaveValue('')
    await expect(dialog.getByRole('textbox', { name: 'Table range', exact: true })).toHaveValue('B5')
    await button('Cancel').click()
  })
