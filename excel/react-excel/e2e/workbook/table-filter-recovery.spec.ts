import { expect, test, type Page } from '@playwright/test'
import { select } from '../support/clipboard'

const cell = (page: Page, coord: string) => page.locator(`td[data-cell="${coord}"]`)
const button = (page: Page, name: string) => page.getByRole('button', { name, exact: true })
test.beforeEach(async ({ page }) => {
  await page.goto('/')
  await expect(cell(page, '1:0')).toHaveText('SO-10001')
  await page.getByRole('tab', { name: 'Summary', exact: true }).click()
  await select(page, 'H80', '79:7')
  const input = page.getByRole('textbox', { name: 'Active cell value' })
  await input.fill('Keep redo'); await input.press('Enter')
  await expect(cell(page, '79:7')).toHaveText('Keep redo')
  await button(page, 'Undo').click()
  await select(page, 'A80', '79:0')
})

for (const dismissal of ['Cancel', 'Escape']) for (const width of [1280, 390])
  test(`${dismissal} table filter discards value choices and preserves redo at ${width}px`, async ({ page }) => {
    await page.setViewportSize({ width, height: 850 })
    const trigger = button(page, 'Filter DemoTable column B')
    await trigger.click()
    const dialog = page.getByRole('dialog', { name: 'DemoTable filter conditions' })
    await dialog.getByLabel('Minimum 1', { exact: true }).fill('20')
    await button(page, 'Choose values for condition 1').click()
    await expect(page.getByLabel('Filter values page', { exact: true })).toHaveText('1–3 of 3')
    await page.getByRole('checkbox', { name: 'Select value 20', exact: true }).check()
    if (dismissal === 'Cancel') await button(page, 'Cancel').click()
    else await page.keyboard.press('Escape')
    await expect(dialog).toHaveCount(0)
    await expect(trigger).toBeFocused()
    for (const [offset, value] of ['10', '20', '30', '60'].entries())
      await expect(cell(page, `${80 + offset}:1`)).toHaveText(value)
    await expect(cell(page, '84:1')).toHaveText('ALPHA')
    await expect(cell(page, '0:1')).toHaveText('79')
    await button(page, 'Recent operations').click()
    await expect(page.getByRole('dialog')).toContainText('0 undo · 1 redo')
    await button(page, 'Close history').click()
    await button(page, 'Redo').click()
    await select(page, 'H80', '79:7')
    await expect(cell(page, '79:7')).toHaveText('Keep redo')
    await button(page, 'Undo').click()
    await expect(cell(page, '79:7')).toHaveText('')
    await select(page, 'A80', '79:0')
    await trigger.click()
    await expect(dialog.getByLabel('Filter condition 1', { exact: true })).toHaveValue('range')
    await expect(dialog.getByLabel('Minimum 1', { exact: true })).toHaveValue('0')
    await expect(button(page, 'Choose values for condition 1')).toHaveAttribute('aria-expanded', 'false')
    await expect(trigger).toHaveAttribute('data-filtered', 'true')
  })
