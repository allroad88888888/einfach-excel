import { expect, test, type Page } from '@playwright/test'
import { select } from '../support/clipboard'

const button = (page: Page, name: string) => page.getByRole('button', { name, exact: true })
const cell = (page: Page, coord: string) => page.locator(`td[data-cell="${coord}"]`)
async function input(page: Page, address: string, coord: string, value: string) {
  await select(page, address, coord)
  const formula = page.getByRole('textbox', { name: 'Active cell value' })
  await formula.fill(value); await formula.press('Enter')
  await expect(formula).toBeEnabled()
}
async function close(page: Page) {
  await button(page, 'Cancel').click()
  await expect(page.getByRole('dialog')).toHaveCount(0)
}
async function toggle(page: Page, enabled: boolean, range: string) {
  await button(page, 'Tables').click()
  await button(page, 'Edit table LocalOrders').click()
  const option = page.getByLabel('Header row', { exact: true })
  await option.click()
  await expect(option).toBeChecked({ checked: enabled })
  await expect(option).toBeEnabled()
  await expect(page.getByLabel('Table range', { exact: true })).toHaveValue(range)
  await close(page)
}
test.beforeEach(async ({ page }) => {
  await page.goto('/')
  await expect(cell(page, '1:0')).toHaveText('SO-10001')
  await button(page, 'New sheet').click()
  await expect(page.getByRole('tab', { name: 'Sheet3', exact: true })).toHaveAttribute('aria-selected', 'true')
  for (const [address, coord, value] of [
    ['A1', '0:0', 'Qty'], ['B1', '0:1', 'Total'], ['A2', '1:0', '2'],
    ['B2', '1:1', '=A2*2'], ['A3', '2:0', '3'], ['B3', '2:1', '=A3*2'],
  ]) await input(page, address, coord, value)
  await select(page, 'A1:B3', '0:0')
  await button(page, 'Tables').click()
  await page.getByLabel('Table name', { exact: true }).fill('LocalOrders')
  await button(page, 'Create table').click()
  await expect(page.getByRole('dialog')).toHaveCount(0)
  await toggle(page, false, 'A2:B3')
})

test('occupied former headers insert locally and named arrays follow through undo and redo', async ({ page }) => {
  await input(page, 'A1', '0:0', 'Keep outside')
  await input(page, 'D2', '1:3', '99')
  await select(page, 'A2:A3', '1:0')
  await button(page, 'Name manager').click()
  await page.getByLabel('Name', { exact: true }).fill('LocalBody')
  await button(page, 'Create name').click()
  await expect(page.getByRole('dialog')).toHaveCount(0)
  await input(page, 'F1', '0:5', '=LocalBody')
  await expect(cell(page, '1:5')).toHaveText('3')
  await toggle(page, true, 'A2:B4')
  await expect(cell(page, '0:0')).toHaveText('Keep outside')
  await expect(cell(page, '1:0')).toHaveText('Qty')
  await expect(cell(page, '2:0')).toHaveText('2')
  await expect(cell(page, '3:1')).toHaveText('6')
  await expect(cell(page, '1:3')).toHaveText('99')
  await expect(cell(page, '1:5')).toHaveText('3')
  await button(page, 'Name manager').click()
  await expect(button(page, 'Edit LocalBody')).toContainText('Sheet3!A3:A4')
  await close(page)
  await button(page, 'Undo').click()
  await expect(cell(page, '1:0')).toHaveText('2')
  await expect(cell(page, '2:1')).toHaveText('6')
  await expect(cell(page, '3:1')).toHaveText('')
  await expect(cell(page, '1:5')).toHaveText('3')
  await button(page, 'Name manager').click()
  await expect(button(page, 'Edit LocalBody')).toContainText('Sheet3!A2:A3')
  await close(page)
  await button(page, 'Redo').click()
  await expect(cell(page, '1:0')).toHaveText('Qty')
  await input(page, 'A4', '3:0', '8')
  await expect(cell(page, '3:1')).toHaveText('16')
  await select(page, 'F2', '1:5')
  await expect(cell(page, '1:5')).toHaveText('8')
})

test('a headerless table on the first row gains headers without moving adjacent cells', async ({ page }) => {
  await select(page, 'A1', '0:0')
  const structure = page.getByRole('combobox', { name: 'Insert or delete rows and columns' })
  await structure.selectOption('delete-rows')
  await expect(structure).toHaveValue('')
  await expect(cell(page, '0:0')).toHaveText('2')
  await input(page, 'D1', '0:3', '99')
  await toggle(page, true, 'A1:B3')
  await expect(cell(page, '0:0')).toHaveText('Qty')
  await expect(cell(page, '1:0')).toHaveText('2')
  await expect(cell(page, '2:1')).toHaveText('6')
  await expect(cell(page, '0:3')).toHaveText('99')
  await button(page, 'Undo').click()
  await expect(cell(page, '0:0')).toHaveText('2')
  await expect(cell(page, '1:1')).toHaveText('6')
  await expect(cell(page, '0:3')).toHaveText('99')
  await button(page, 'Redo').click()
  await expect(cell(page, '0:0')).toHaveText('Qty')
  await expect(cell(page, '2:1')).toHaveText('6')
})

test('the next table moves with its headers and formulas in the same native history entry', async ({ page }) => {
  // 先创建相邻表再填值；直接在上表下一行输入会合法触发自动扩表。
  await select(page, 'A4:B6', '3:0')
  await button(page, 'Tables').click()
  await page.getByLabel('Table name', { exact: true }).fill('LowerOrders')
  await button(page, 'Create table').click()
  await expect(page.getByRole('dialog')).toHaveCount(0)
  for (const [address, coord, value] of [
    ['A1', '0:0', 'Keep outside'], ['A4', '3:0', 'Qty'], ['B4', '3:1', 'Amount'],
    ['A5', '4:0', '5'], ['B5', '4:1', '=A5*2'], ['A6', '5:0', '6'], ['B6', '5:1', '=A6*2'],
  ]) await input(page, address, coord, value)
  await input(page, 'D1', '0:3', '=LowerOrders[Amount]')
  await expect(cell(page, '1:3')).toHaveText('12')
  await toggle(page, true, 'A2:B4')
  await expect(cell(page, '4:0')).toHaveText('Qty')
  await expect(cell(page, '6:1')).toHaveText('12')
  await expect(cell(page, '1:3')).toHaveText('12')
  await button(page, 'Tables').click()
  await expect(button(page, 'Edit table LowerOrders')).toContainText('A5:B7')
  await close(page)
  await button(page, 'Undo').click()
  await expect(cell(page, '3:0')).toHaveText('Qty')
  await expect(cell(page, '5:1')).toHaveText('12')
  await expect(cell(page, '6:1')).toHaveText('')
  await button(page, 'Redo').click()
  await expect(cell(page, '4:0')).toHaveText('Qty')
  await input(page, 'A7', '6:0', '9')
  await expect(cell(page, '6:1')).toHaveText('18')
  await select(page, 'D2', '1:3')
  await expect(cell(page, '1:3')).toHaveText('18')
})

test('a lower filter moves its hidden rows while manual hiding stays at the same row', async ({ page }) => {
  for (const [address, coord, value] of [
    ['A1', '0:0', 'Keep outside'], ['A5', '4:0', 'Qty'], ['B5', '4:1', 'Amount'],
    ['B6', '5:1', '10'], ['B7', '6:1', '20'], ['B8', '7:1', '30'],
  ]) await input(page, address, coord, value)
  await select(page, 'A5:B8', '4:0')
  await page.getByRole('combobox', { name: 'Worksheet filter' }).selectOption('selection')
  await button(page, 'Filter column B').click()
  const filter = page.getByRole('dialog', { name: 'Filter conditions' })
  await filter.getByLabel('Filter condition 1', { exact: true }).selectOption('range')
  await filter.getByLabel('Minimum 1', { exact: true }).fill('15')
  await filter.getByRole('button', { name: 'Apply filter', exact: true }).click()
  await expect(filter).not.toBeVisible()
  await expect(cell(page, '5:1')).toHaveCount(0)
  await select(page, 'A8', '7:0')
  await page.getByRole('combobox', { name: 'Row and column visibility' }).selectOption('hide-rows')
  await input(page, 'F1', '0:5', '=IF(SUBTOTAL(109,B6:B8)>25,SEQUENCE(2),SEQUENCE(1))')
  await expect(cell(page, '1:5')).toHaveText('')
  await toggle(page, true, 'A2:B4')
  await expect(cell(page, '1:5')).toHaveText('2')
  await expect(cell(page, '5:1')).toHaveText('Amount')
  await expect(cell(page, '6:1')).toHaveCount(0)
  await expect(cell(page, '7:1')).toHaveCount(0)
  await expect(cell(page, '8:1')).toHaveText('30')
  await expect(button(page, 'Filter column B')).toHaveAttribute('data-filtered', 'true')
  await button(page, 'Undo').click()
  await expect(cell(page, '1:5')).toHaveText('')
  await expect(cell(page, '4:1')).toHaveText('Amount')
  await expect(cell(page, '5:1')).toHaveCount(0)
  await expect(cell(page, '6:1')).toHaveText('20')
  await expect(cell(page, '7:1')).toHaveCount(0)
  await button(page, 'Redo').click()
  await expect(cell(page, '1:5')).toHaveText('2')
  await expect(cell(page, '6:1')).toHaveCount(0)
  await expect(cell(page, '8:1')).toHaveText('30')
})
