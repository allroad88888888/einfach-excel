import { expect, test } from '@playwright/test'
import { select } from '../support/clipboard'

for (const width of [1280, 390])
  test(`overlapping table corrects in the same panel before one native creation at ${width}px`, async ({ page }) => {
    await page.setViewportSize({ width, height: 850 })
    await page.goto('/e2e/fixtures/plain-sales-orders/')
    const cell = (coord: string) => page.locator(`td[data-cell="${coord}"]`)
    const button = (name: string) => page.getByRole('button', { name, exact: true })
    await expect(cell('1:0')).toHaveText('SO-10001')
    await page.getByRole('tab', { name: 'Summary', exact: true }).click()
    const bar = page.getByRole('textbox', { name: 'Active cell value', exact: true })
    await select(page, 'H94', '93:7')
    await bar.fill('old table redo')
    await bar.press('Enter')
    await expect(cell('93:7')).toHaveText('old table redo')
    await button('Undo').click()
    await select(page, 'C75', '74:2')
    await button('Tables').click()
    const dialog = page.getByRole('dialog', { name: 'Tables', exact: true })
    const name = dialog.getByRole('textbox', { name: 'Table name', exact: true })
    const range = dialog.getByRole('textbox', { name: 'Table range', exact: true })
    await name.fill('CreatedAfterReject')
    await range.fill('A80:B84')
    await button('Create table').click()
    await expect(dialog.getByRole('alert')).toContainText(/overlap/i)
    await expect(name).toHaveValue('CreatedAfterReject')
    await expect(range).toHaveValue('A80:B84')
    await expect(button('Undo')).toBeDisabled()
    await expect(button('Redo')).toBeEnabled()
    await range.fill('D32:F37')
    await button('Create table').click()
    await expect(dialog).toHaveCount(0)
    await expect(button('Redo')).toBeDisabled()
    await button('Tables').click()
    await expect(button('Edit table CreatedAfterReject')).toContainText('D32:F37')
    await expect(button('Edit table DemoTable')).toBeVisible()
    await button('Cancel').click()
    await button('Undo').click()
    await expect(button('Undo')).toBeDisabled()
    await button('Tables').click()
    await expect(button('Edit table CreatedAfterReject')).toHaveCount(0)
    await expect(button('Edit table DemoTable')).toBeVisible()
    await button('Cancel').click()
    await button('Redo').click()
    await select(page, 'F33', '32:5')
    await expect(cell('32:5')).toHaveText('M1')
    await expect(cell('32:5')).toHaveCSS('font-style', 'italic')
    await expect(cell('36:5')).toHaveText('P1')
    await select(page, 'B5', '4:1')
    await expect(cell('4:1')).toHaveText('60')
    await expect(bar).toHaveValue('=SUM(DemoTable[Amount])')
    await select(page, 'H94', '93:7')
    await expect(cell('93:7')).toHaveText('')
    await expect(button('Redo')).toBeDisabled()
  })
