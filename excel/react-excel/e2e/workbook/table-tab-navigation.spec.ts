import { expect, test, type Page } from '@playwright/test'
import { select } from '../support/clipboard'

const grid = (page: Page) => page.getByLabel('Summary cells', { exact: true })
const cell = (page: Page, coord: string) => page.locator(`td[data-cell="${coord}"]`)
const button = (page: Page, name: string) => page.getByRole('button', { name, exact: true })
async function at(page: Page, address: string) {
  await expect(page.getByRole('textbox', { name: 'Name box' })).toHaveValue(address)
  await expect(grid(page)).toBeFocused()
}
test.beforeEach(async ({ page }) => {
  await page.goto('/')
  await expect(cell(page, '1:0')).toHaveText('SO-10001')
  await page.getByRole('tab', { name: 'Summary', exact: true }).click()
  await expect(cell(page, '4:1')).toHaveText('60')
})

test('Tab and Shift+Tab wrap table rows without modifying data or selecting a range', async ({ page }) => {
  await select(page, 'B81', '80:1')
  await grid(page).press('Tab'); await at(page, 'A82')
  await grid(page).press('Shift+Tab'); await at(page, 'B81')
  await grid(page).press('Shift+Tab'); await at(page, 'A81')
  await expect(button(page, 'Undo')).toBeDisabled()
  await expect(cell(page, '83:1')).toHaveText('60')
})
test('Tab from the last data cell inserts before totals and one Undo restores displaced data', async ({ page }) => {
  await select(page, 'B83', '82:1')
  await grid(page).press('Tab'); await at(page, 'A84')
  await expect(cell(page, '84:1')).toHaveText('60')
  await expect(cell(page, '85:1')).toHaveText('ALPHA')
  await grid(page).press('Shift+Tab'); await at(page, 'B83')
  await button(page, 'Undo').click()
  await expect(cell(page, '83:1')).toHaveText('60')
  await expect(cell(page, '84:1')).toHaveText('ALPHA')
  await expect(button(page, 'Undo')).toBeDisabled()
})
test('editing Tab commits the value before appending, with independent edit and append undo', async ({ page }) => {
  const target = await select(page, 'B83', '82:1')
  await target.dblclick()
  const editor = page.getByRole('textbox', { name: 'Cell editor', exact: true })
  await editor.fill('40'); await editor.press('Tab')
  await at(page, 'A84')
  await expect(cell(page, '82:1')).toHaveText('40')
  await expect(cell(page, '84:1')).toHaveText('70')
  await button(page, 'Undo').click()
  await expect(cell(page, '83:1')).toHaveText('70')
  await button(page, 'Undo').click()
  await expect(cell(page, '83:1')).toHaveText('60')
  await expect(button(page, 'Undo')).toBeDisabled()
})
test('editor Shift+Tab commits and wraps backwards without creating another record', async ({ page }) => {
  const target = await select(page, 'A82', '81:0')
  await target.dblclick()
  const editor = page.getByRole('textbox', { name: 'Cell editor', exact: true })
  await editor.fill('Updated'); await editor.press('Shift+Tab')
  await at(page, 'B81')
  await expect(cell(page, '81:0')).toHaveText('Updated')
  await button(page, 'Undo').click()
  await expect(button(page, 'Undo')).toBeDisabled()
})
test('last calculated cell Tab appends inherited formulas, then further Tab remains within the row', async ({ page }) => {
  await select(page, 'C49', '48:2')
  await grid(page).press('Tab'); await at(page, 'A50')
  await expect(cell(page, '49:2')).toHaveText('0')
  await grid(page).press('Tab'); await at(page, 'B50')
  await grid(page).press('Shift+Tab'); await at(page, 'A50')
  await button(page, 'Undo').click()
  await expect(cell(page, '49:2')).toHaveText('')
  await expect(button(page, 'Undo')).toBeDisabled()
})
test('Table Tab skips hidden rows and columns in both directions', async ({ page }) => {
  const visibility = page.getByRole('combobox', { name: 'Row and column visibility' })
  await select(page, 'B47', '46:1')
  await visibility.selectOption('hide-columns'); await expect(visibility).toBeEnabled()
  await select(page, 'A48', '47:0')
  await visibility.selectOption('hide-rows'); await expect(visibility).toBeEnabled()
  await select(page, 'A47', '46:0')
  await grid(page).press('Tab'); await at(page, 'C47')
  await grid(page).press('Tab'); await at(page, 'A49')
  await grid(page).press('Shift+Tab'); await at(page, 'C47')
  await expect(cell(page, '47:0')).toHaveCount(0)
  await expect(cell(page, '46:1')).toHaveCount(0)
})
