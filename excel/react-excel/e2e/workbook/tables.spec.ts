import { expect, test, type Page } from '@playwright/test'
import { select } from '../support/clipboard'

const button = (page: Page, name: string) => page.getByRole('button', { name, exact: true })
const cell = (page: Page, coord: string) => page.locator(`td[data-cell="${coord}"]`)
async function open(page: Page) {
  await button(page, 'Tables').click()
  return page.getByRole('dialog', { name: 'Tables', exact: true })
}
async function save(page: Page, name: string) {
  await button(page, name).click()
  await expect(page.getByRole('dialog', { name: 'Tables', exact: true })).toHaveCount(0)
}
async function input(page: Page, address: string, coord: string, text: string) {
  await select(page, address, coord)
  await page.locator('[data-workbook-grid]').press('F2')
  const editor = page.getByRole('textbox', { name: 'Cell editor', exact: true })
  await editor.fill(text); await editor.press('Enter')
  await expect(editor).toHaveCount(0)
}
