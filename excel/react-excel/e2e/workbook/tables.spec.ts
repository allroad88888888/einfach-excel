import { expect, test, type Page } from '@playwright/test'
import { select } from '../support/clipboard'

const button = (page: Page, name: string) => page.getByRole('button', { name, exact: true })
const cell = (page: Page, coord: string) => page.locator(`td[data-cell="${coord}"]`)
async function open(page: Page) {
  await button(page, 'Tables').click()
  return page.getByRole('dialog', { name: 'Tables', exact: true })
}
async function save(page: Page, name: string) {
  await button(page, name).click()
  await expect(page.getByRole('dialog', { name: 'Tables', exact: true })).toHaveCount(0)
}
async function input(page: Page, address: string, coord: string, text: string) {
  await select(page, address, coord)
  await page.locator('[data-workbook-grid]').press('F2')
  const editor = page.getByRole('textbox', { name: 'Cell editor', exact: true })
  await editor.fill(text); await editor.press('Enter')
  await expect(editor).toHaveCount(0)
}
test.beforeEach(async ({ page }) => {
  await page.goto('/')
  await expect(cell(page, '1:0')).toHaveText('SO-10001')
})
test('create, rename and convert use real Rust history and keep formulas live', async ({ page }) => {
  await select(page, 'E1:E4', '0:4')
  await open(page)
  await expect(page.getByLabel('Table range', { exact: true })).toHaveValue('E1:E4')
  await page.getByLabel('Table name', { exact: true }).fill('OrderUnits')
  await save(page, 'Create table')
  await open(page); await expect(button(page, 'Edit table OrderUnits')).toContainText('E1:E4')
  await save(page, 'Cancel')
  await button(page, 'Undo').click()
  await open(page); await expect(button(page, 'Edit table OrderUnits')).toHaveCount(0)
  await save(page, 'Cancel'); await button(page, 'Redo').click()
  await input(page, 'J2', '1:9', '=SUM(OrderUnits)')
  await expect(cell(page, '1:9')).toHaveText('6')
  await open(page); await button(page, 'Edit table OrderUnits').click()
  await page.getByLabel('Table name', { exact: true }).fill('SalesUnits')
  await save(page, 'Rename table')
  await select(page, 'J2', '1:9')
  await expect(page.getByRole('textbox', { name: 'Active cell value' })).toHaveValue('=SUM(SalesUnits)')
  await button(page, 'Undo').click()
  await expect(page.getByRole('textbox', { name: 'Active cell value' })).toHaveValue('=SUM(OrderUnits)')
  await button(page, 'Redo').click()
  await open(page); await button(page, 'Edit table SalesUnits').click(); await save(page, 'Convert to range')
  await expect(cell(page, '1:9')).toHaveText('6')
  await select(page, 'J2', '1:9')
  await expect(page.getByRole('textbox', { name: 'Active cell value' })).not.toHaveValue(/SalesUnits/)
  await button(page, 'Undo').click()
  await expect(page.getByRole('textbox', { name: 'Active cell value' })).toHaveValue('=SUM(SalesUnits)')
  await button(page, 'Redo').click()
  await input(page, 'E4', '3:4', '10')
  await select(page, 'J2', '1:9'); await expect(cell(page, '1:9')).toHaveText('13')
})
test('overlap rejection preserves draft and does not add history', async ({ page }) => {
  await open(page)
  await page.getByLabel('Table range', { exact: true }).fill('E1:E4')
  await page.getByLabel('Table name', { exact: true }).fill('Units')
  await save(page, 'Create table')
  await open(page)
  await page.getByLabel('Table range', { exact: true }).fill('E2:E5')
  await page.getByLabel('Table name', { exact: true }).fill('Overlap')
  await button(page, 'Create table').click()
  await expect(page.getByRole('alert')).toContainText(/overlap/i)
  await expect(page.getByLabel('Table name', { exact: true })).toHaveValue('Overlap')
  await save(page, 'Cancel'); await button(page, 'Undo').click()
  await open(page); await expect(button(page, 'Edit table Units')).toHaveCount(0)
})
test('seed table has imported headers, live structured references and no startup history', async ({ page }) => {
  await expect(button(page, 'Undo')).toBeDisabled()
  await page.getByRole('tab', { name: 'Summary', exact: true }).click()
  await expect(cell(page, '4:1')).toHaveText('60')
  await open(page); await button(page, 'Edit table DemoTable').click()
  await expect(page.getByLabel('Table range', { exact: true })).toHaveValue('A80:B84')
  await page.getByLabel('Table name', { exact: true }).fill('SampleTable')
  await save(page, 'Rename table')
  await select(page, 'B5', '4:1')
  await expect(page.getByRole('textbox', { name: 'Active cell value' })).toHaveValue('=SUM(SampleTable[Amount])')
  await open(page); await button(page, 'Edit table SampleTable').click(); await save(page, 'Convert to range')
  await input(page, 'B81', '80:1', '40')
  await select(page, 'B5', '4:1'); await expect(cell(page, '4:1')).toHaveText('90')
})
for (const width of [1280, 390]) test(`Tables fits ${width}px and restores keyboard focus`, async ({ page }, info) => {
  const errors: string[] = []
  page.on('pageerror', (error) => errors.push(error.message))
  await page.setViewportSize({ width, height: 800 })
  const dialog = await open(page)
  await expect(page.getByLabel('Table name', { exact: true })).toBeFocused()
  await dialog.getByRole('button').first().focus(); await page.keyboard.press('Shift+Tab')
  await expect(button(page, 'Create table')).toBeFocused()
  const box = (await dialog.boundingBox())!
  expect(box.x).toBeGreaterThanOrEqual(0)
  expect(box.x + box.width).toBeLessThanOrEqual(width)
  expect(await dialog.evaluate((node) => node.scrollWidth <= node.clientWidth)).toBe(true)
  await page.screenshot({ path: info.outputPath(`tables-${width}.png`) })
  await page.keyboard.press('Escape')
  await expect(dialog).toHaveCount(0)
  await expect(button(page, 'Tables')).toBeFocused()
  expect(errors).toEqual([])
})
