for (const width of [1280, 390]) test(`Tables fits ${width}px and restores keyboard focus`, async ({ page }, info) => {
  const errors: string[] = []
  page.on('pageerror', (error) => errors.push(error.message))
  await page.setViewportSize({ width, height: 800 })
  const dialog = await open(page)
  await expect(page.getByLabel('Table name', { exact: true })).toBeFocused()
  await dialog.getByRole('button').first().focus(); await page.keyboard.press('Shift+Tab')
  await expect(button(page, 'Create table')).toBeFocused()
  const box = (await dialog.boundingBox())!
  expect(box.x).toBeGreaterThanOrEqual(0)
  expect(box.x + box.width).toBeLessThanOrEqual(width)
  expect(await dialog.evaluate((node) => node.scrollWidth <= node.clientWidth)).toBe(true)
  await page.screenshot({ path: info.outputPath(`tables-${width}.png`) })
  await page.keyboard.press('Escape')
  await expect(dialog).toHaveCount(0)
  await expect(button(page, 'Tables')).toBeFocused()
  expect(errors).toEqual([])
})

for (const width of [1280, 390]) test.describe(`${width}px independent table actions`, () => {
  test.use({ viewport: { width, height: 850 } })

  test(`create a table preserves its source and undoes once at ${width}px`, async ({ page }) => {
    await select(page, 'E1:E4', '0:4')
    const outside = await cell(page, '1:3').innerText()
    await open(page)
    await page.getByLabel('Table name', { exact: true }).fill('IndependentUnits')
    await save(page, 'Create table')
    for (const row of [1, 2, 3]) await expect(cell(page, `${row}:4`)).toHaveText(String(row))
    await expect(cell(page, '1:3')).toHaveText(outside)
    await open(page)
    await expect(button(page, 'Edit table IndependentUnits')).toContainText('E1:E4')
    await save(page, 'Cancel')
    await button(page, 'Undo').click()
    await expect(button(page, 'Undo')).toBeDisabled()
    await open(page)
    await expect(button(page, 'Edit table IndependentUnits')).toHaveCount(0)
    await save(page, 'Cancel')
    await button(page, 'Redo').click()
    await input(page, 'J2', '1:9', '=SUM(IndependentUnits)')
    await expect(cell(page, '1:9')).toHaveText('6')
  })

  test(`rename a seeded table rewrites only its references at ${width}px`, async ({ page }) => {
    await page.getByRole('tab', { name: 'Summary', exact: true }).click()
    await select(page, 'B5', '4:1')
    const bar = page.getByRole('textbox', { name: 'Active cell value' })
    await expect(bar).toHaveValue('=SUM(DemoTable[Amount])')
    await open(page)
    await button(page, 'Edit table DemoTable').click()
    await page.getByLabel('Table name', { exact: true }).fill('IndependentTable')
    await save(page, 'Rename table')
    await expect(bar).toHaveValue('=SUM(IndependentTable[Amount])')
    await expect(cell(page, '4:1')).toHaveText('60')
    await expect(cell(page, '3:1')).toHaveText('12')
    await open(page)
    await expect(button(page, 'Edit table DemoTable')).toHaveCount(0)
    await expect(button(page, 'Edit table IndependentTable')).toContainText('A80:B84')
    await expect(button(page, 'Edit table CalculatedOrders')).toBeVisible()
    await save(page, 'Cancel')
    await button(page, 'Undo').click()
    await expect(bar).toHaveValue('=SUM(DemoTable[Amount])')
    await expect(button(page, 'Undo')).toBeDisabled()
    await button(page, 'Redo').click()
    await expect(bar).toHaveValue('=SUM(IndependentTable[Amount])')
    await expect(cell(page, '4:1')).toHaveText('60')
  })

  test(`convert a seeded table keeps data and visible formatting at ${width}px`, async ({ page }) => {
    await page.getByRole('tab', { name: 'Summary', exact: true }).click()
    await select(page, 'A80:B84', '79:0')
    const background = await cell(page, '80:1').evaluate(node => getComputedStyle(node).backgroundColor)
    const weight = await cell(page, '79:0').evaluate(node => getComputedStyle(node).fontWeight)
    await open(page)
    await button(page, 'Edit table DemoTable').click()
    await save(page, 'Convert to range')
    await expect(cell(page, '79:0')).toHaveText('Product')
    await expect(cell(page, '80:1')).toHaveText('10')
    await expect(cell(page, '80:1')).toHaveCSS('background-color', background)
    await expect(cell(page, '79:0')).toHaveCSS('font-weight', weight)
    await select(page, 'B5', '4:1')
    const bar = page.getByRole('textbox', { name: 'Active cell value' })
    await expect(bar).not.toHaveValue(/DemoTable/)
    await expect(cell(page, '4:1')).toHaveText('60')
    await open(page)
    await expect(button(page, 'Edit table DemoTable')).toHaveCount(0)
    await expect(button(page, 'Edit table CalculatedOrders')).toBeVisible()
    await save(page, 'Cancel')
    await button(page, 'Undo').click()
    await expect(bar).toHaveValue('=SUM(DemoTable[Amount])')
    await expect(button(page, 'Undo')).toBeDisabled()
    await button(page, 'Redo').click()
    await expect(bar).not.toHaveValue(/DemoTable/)
    await expect(cell(page, '4:1')).toHaveText('60')
  })
})
