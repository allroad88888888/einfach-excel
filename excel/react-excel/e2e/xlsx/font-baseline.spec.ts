test('mixed external axis styles retain baseline and visibly report unsupported formatting', async ({ page }) => {
  await page.goto('/?plugins=text-format')
  await expect(cell(page, '1:0')).toHaveText('SO-10001')
  const source = await readFile(fileURLToPath(new URL('./font-baseline-mixed-axis.xlsx', import.meta.url)))
  await openFile(page, source, 'xlsx')
  await expect(page.getByRole('status', { name: 'Workbook file status' })).toContainText('row or column styles')
  await expect(cell(page, '0:0').locator('[data-font-baseline="superscript"]')).toHaveText('Column')
  await expect(cell(page, '0:0')).not.toHaveCSS('font-weight', '700')
  await expect(cell(page, '1:0').locator('[data-font-baseline]')).toHaveCount(0)
  await expect(cell(page, '1:1').locator('[data-font-baseline="subscript"]')).toHaveText('Row')
  const saved = JSON.parse((await downloadFile(page)).toString())
  expect(saved.workbook.cells).toHaveLength(6)
  expect(saved.workbook.formats[0].columnStyles[0].format).toEqual({ fontBaseline: 'superscript' })
  await openFile(page, await downloadFile(page, true), 'xlsx')
  await expect(cell(page, '0:0').locator('[data-font-baseline="superscript"]')).toHaveText('Column')
  await expect(cell(page, '1:0').locator('[data-font-baseline]')).toHaveCount(0)
  await expect(button(page, 'Undo')).toBeDisabled()
})

test('independent XLSX baseline layers and rich runs survive real reexport and native reopen', async ({ page }) => {
  await page.goto('/?plugins=text-format')
  await expect(cell(page, '1:0')).toHaveText('SO-10001')
  await openFile(page, await readFile(fileURLToPath(new URL('./font-baseline-external.xlsx', import.meta.url))), 'xlsx')
  for (let pass = 0; pass < 3; pass++) {
    await select(page, 'A1', '0:0')
    await expect(cell(page, '0:0').locator('[data-font-baseline="superscript"]')).toHaveText('Inherited super')
    await expect(cell(page, '1:1').locator('[data-font-baseline="subscript"]')).toHaveText('Inherited sub')
    await expect(cell(page, '1:0').locator('[data-font-baseline]')).toHaveCount(0)
    await expect(cell(page, '1:0')).toHaveText('Explicit normal')
    await expect(cell(page, '1:0')).toHaveCSS('font-size', '20px')
    await expect(cell(page, '0:3').locator('[data-font-baseline]')).toHaveCount(0)
    await expect(cell(page, '0:2')).toHaveText('12.5')
    await expect(cell(page, '0:5')).toHaveText('25')
    const sharedRuns = cell(page, '2:2').locator('.cell-content > span')
    await expect(sharedRuns).toHaveCount(3)
    await expect(sharedRuns.nth(0)).toHaveAttribute('data-font-baseline', 'superscript')
    await expect(sharedRuns.nth(1)).toHaveAttribute('data-font-baseline', 'normal')
    await expect(sharedRuns.nth(1)).toHaveCSS('font-weight', '700')
    await expect(sharedRuns.nth(2)).toHaveAttribute('data-font-baseline', 'subscript')
    const inlineRuns = cell(page, '2:4').locator('.cell-content > span')
    await expect(inlineRuns.nth(0)).toHaveAttribute('data-font-baseline', 'subscript')
    await expect(inlineRuns.nth(1)).toHaveAttribute('data-font-baseline', 'normal')
    await select(page, 'F1', '0:5')
    await expect(page.getByRole('textbox', { name: 'Active cell value' })).toHaveValue('=C1*2')
    const nativeBytes = await downloadFile(page)
    const native = JSON.parse(nativeBytes.toString())
    expect(native.workbook.cells).toHaveLength(8)
    const formats = native.workbook.formats.find((range: { sheet: number }) => range.sheet === 0)
    expect(formats.columnStyles).toHaveLength(1)
    expect(formats.rowStyles).toHaveLength(1)
    expect(formats.columnStyles[0].format.fontBaseline).toBe('superscript')
    expect(formats.rowStyles[0].format.fontBaseline).toBe('subscript')
    for (const address of ['A1', 'B2', 'D1'])
      expect(formats.cellStyles.find((style: { addr: string }) => style.addr === address)?.format.fontBaseline).toBeUndefined()
    expect(formats.cellStyles.find((style: { addr: string }) => style.addr === 'A2').format.fontBaseline).toBe('normal')
    if (pass === 0) await openFile(page, await downloadFile(page, true), 'xlsx')
    if (pass === 1) await openFile(page, nativeBytes)
  }
  await select(page, 'C3', '2:2')
  await applyBaseline(page, 'Subscript')
  const runs = cell(page, '2:2').locator('.cell-content > span')
  await expect(runs).toHaveCount(3)
  for (const run of await runs.all()) await expect(run).toHaveAttribute('data-font-baseline', 'subscript')
  await expect(runs.nth(1)).toHaveCSS('font-weight', '700')
  const modified = JSON.parse((await downloadFile(page)).toString())
  const originalRuns = modified.workbook.richText.find((entry: { row: number; col: number }) =>
    entry.row === 2 && entry.col === 2).runs
  expect(originalRuns.every((run: { format: { fontBaseline?: string } }) => run.format.fontBaseline === undefined)).toBe(true)
  expect(originalRuns[1].format.bold).toBe(true)
  await button(page, 'Undo').click()
  await expect(runs.nth(1)).toHaveAttribute('data-font-baseline', 'normal')
  await expect(button(page, 'Undo')).toBeDisabled()
})

test('invalid native baseline rejects atomically and corrects without replacing the current history', async ({ page }) => {
  await page.goto('/?plugins=text-format')
  await expect(cell(page, '1:0')).toHaveText('SO-10001')
  await openFile(page, baselinePixelFile)
  await select(page, 'A1', '0:0'); await applyBaseline(page, 'Subscript')
  await button(page, 'File').click()
  page.on('dialog', dialog => dialog.accept())
  const input = page.getByLabel('Open workbook', { exact: true })
  await input.setInputFiles({ name: 'Invalid.einfach.json', mimeType: 'application/json',
    buffer: Buffer.from(baselinePixelFile.toString().replace('superscript', 'invalid-baseline')) })
  const panel = page.getByRole('dialog', { name: 'Workbook files' })
  await expect(panel.getByRole('alert')).toContainText('Current workbook kept')
  await expect(cell(page, '0:0').locator('[data-font-baseline="subscript"]')).toHaveText('Hg')
  await expect(button(page, 'Undo')).toBeEnabled()
  await input.setInputFiles({ name: 'Corrected.einfach.json', mimeType: 'application/json', buffer: baselinePixelFile })
  await expect(panel).toHaveCount(0)
  await expect(cell(page, '0:0').locator('[data-font-baseline]')).toHaveCount(0)
  await expect(cell(page, '0:1').locator('[data-font-baseline="superscript"]')).toHaveText('Hg')
  await expect(button(page, 'Undo')).toBeDisabled()
})

test('existing rich-text editor previews inherited baselines and preserves them while applying italic', async ({ page }) => {
  await page.goto('/?plugins=text-format')
  await expect(cell(page, '1:0')).toHaveText('SO-10001')
  await openFile(page, await readFile(fileURLToPath(new URL('./font-baseline-external.xlsx', import.meta.url))), 'xlsx')
  await select(page, 'C3', '2:2')
  await showRibbonItem(page, 'format.rich-text'); await button(page, 'Rich text').click()
  const dialog = page.getByRole('dialog', { name: 'Rich text · C3' })
  const runs = dialog.locator('.rich-text-preview > span')
  await expect(runs).toHaveCount(3)
  await expect(runs.nth(0)).toHaveCSS('font-size', '7.8px')
  await expect(runs.nth(1)).toHaveCSS('font-size', '12px')
  await expect(runs.nth(2)).toHaveCSS('font-size', '7.8px')
  await expect(dialog.getByRole('button', { name: 'Superscript', exact: true })).toHaveCount(0)
  const text = dialog.getByRole('textbox', { name: 'Cell text' })
  await text.press('Home'); await text.press('Shift+ArrowRight')
  await dialog.getByRole('button', { name: 'Italic', exact: true }).click()
  await expect(runs.nth(0)).toHaveCSS('font-style', 'italic')
  await dialog.getByRole('button', { name: 'Save changes' }).click()
  await expect(dialog).toHaveCount(0)
  const displayed = cell(page, '2:2').locator('.cell-content > span')
  await expect(displayed.nth(0)).toHaveCSS('font-style', 'italic')
  await expect(displayed.nth(0)).toHaveAttribute('data-font-baseline', 'superscript')
  await expect(displayed.nth(1)).toHaveAttribute('data-font-baseline', 'normal')
  await expect(displayed.nth(2)).toHaveAttribute('data-font-baseline', 'subscript')
  await button(page, 'Undo').click()
  await expect(displayed.nth(0)).toHaveCSS('font-style', 'normal')
  await expect(button(page, 'Undo')).toBeDisabled()
})
