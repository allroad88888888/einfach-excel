#!/usr/bin/env node
/**
 * Extracts the master list of built-in formula names from the Rust
 * engine's delegated `is_builtin_function_name` arms and writes a sorted,
 * de-duplicated `string[]` TypeScript module.
 *
 * Run from any cwd:  node excel/spreadsheet-ui-core/scripts/extract-builtin-names.mjs
 *
 * The output file is committed; this script exists so the list stays
 * verifiable / re-generatable when the Rust engine adds new arms. The
 * UI's `BUILTIN_FORMULA_NAMES` Set is built from this generated list
 * AND from the IntelliSense seed registry so both sources stay in sync.
 *
 * NOTE: this script is intentionally dependency-free (uses only `fs` +
 * `path`) so it runs under any Node version the repo supports without
 * needing a separate `npm install`.
 */
import { readFileSync, writeFileSync } from 'node:fs'
import { dirname, resolve } from 'node:path'
import { fileURLToPath } from 'node:url'

const here = dirname(fileURLToPath(import.meta.url))
// `<repo>/excel/` — the pnpm workspace root that holds every package plus
// `rust/`. NOT the git root: it was mislabeled `repoRoot` and resolved one
// level too high, so this script crashed with ENOENT on every invocation
// and the "just re-run the generator" maintenance story never worked.
const workspaceRoot = resolve(here, '..', '..')
const reservedNameModulePaths = [
  'eval_builtin_names_a_h.rs',
  'eval_builtin_names_i_r.rs',
  'eval_builtin_names_s_z.rs',
].map((file) => resolve(workspaceRoot, 'rust', 'excel-core', 'src', file))
const outPath = resolve(here, '..', 'src', 'custom-formulas', 'engine-builtin-names.ts')

function extractModuleNames(path) {
  const src = readFileSync(path, 'utf8')
  const matchesOpen = src.indexOf('matches!(')
  if (matchesOpen === -1) throw new Error(`matches!(...) macro not found in ${path}`)

  let depth = 0
  for (let cursor = matchesOpen + 'matches!'.length; cursor < src.length; cursor++) {
    const ch = src[cursor]
    if (ch === '(') depth++
    else if (ch === ')') {
      depth--
      if (depth === 0) return src.slice(matchesOpen, cursor)
    }
  }
  throw new Error(`unbalanced matches!(...) parens in ${path}`)
}

// Pull every `"NAME"` literal out of the macro body.
const names = reservedNameModulePaths.flatMap((path) => {
  const body = extractModuleNames(path)
  return Array.from(body.matchAll(/"([A-Z][A-Z0-9_.]*)"/g)).map((match) => match[1])
})
const unique = Array.from(new Set(names)).sort()

const header = `/**
 * Auto-generated by \`scripts/extract-builtin-names.mjs\`.
 *
 * DO NOT EDIT BY HAND. Re-run the script if a Rust
 * \`eval_builtin_names_*.rs\` module adds or removes a reserved arm. Source
 * of truth for the JS-side shadow check lives in the Rust engine — this file
 * is a mirror, not an authority.
 *
 * Count: ${unique.length} names.
 */
export const ENGINE_BUILTIN_FORMULA_NAMES: readonly string[] = Object.freeze([
${unique.map((n) => `  '${n}',`).join('\n')}
])
`

writeFileSync(outPath, header)
process.stdout.write(`wrote ${unique.length} names -> ${outPath}\n`)
